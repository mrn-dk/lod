# put a mechanical description of the edit in 45 % of subjects -- "pull the display pieces
# out into a private helper", "thread the tenant through the client call" -- and a
# multinomial naive Bayes over the subject line ALONE then read semver at 68.7 % against a
# 35.9 % majority baseline. That is the row-36 leak in this row's clothing: the wording
# carried the label and the diff was decoration. Measured, found, removed.
