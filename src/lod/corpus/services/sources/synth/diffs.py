def _camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(w.title() for w in rest)


def _pascal(name: str) -> str:
    return "".join(w.title() for w in name.split("_"))


@dataclass
class Param:
    name: str
    type: str
    default: str | None = None      # rendered source text, python/typescript only
    widened: bool = False


@dataclass
class Func:
    name: str
    body: str                       # fetch | listing | validate | format | decode | bucket
    params: list[Param]
    ret: str
    doc: str
    public: bool = True
    ret_optional: bool = False      # fetch may return nothing
    bound: float = 250.0            # validate
    bound0: float | None = None     # the bound this commit started from
    offby: int = 1                  # bucket
    log: bool = False
    local: str = "rows"             # the local the body names, for rename_local
    shim_for: str | None = None     # deprecate_with_shim
    helper: bool = False            # extract_helper split a step out
    doc0: str | None = None         # the doc this commit opened with (update_docstring)

    def __post_init__(self):
        if self.doc0 is None:
            self.doc0 = self.doc


@dataclass
class Module:
    pkg: str
    noun: str
    struct: str
    route: str
    enum: str
    enum_members: list[str]
    fields: list[tuple[str, str]]
    funcs: list[Func]
    lang: str
    # names `_e_add_field` appended during THIS commit. `rename_field` and
    # `remove_field` must not touch them: renaming the field the previous edit
    # just added leaves no trace in the diff at all, and the commit then ships a
    # `major` label on a hunk that shows nothing but an added optional field.
    fresh_fields: set[str] = field(default_factory=set)
    extra_funcs: list[Func] = field(default_factory=list)

    @property
    def path(self) -> str:
        return {"python": f"{self.pkg}/{self.noun}s.py",
                "typescript": f"src/{self.pkg}/{self.noun}s.ts",
                "go": f"{self.pkg}/{self.noun}s.go"}[self.lang]

    def public_funcs(self) -> list[Func]:
        return [f for f in self.funcs if f.public]

    def find(self, body: str) -> Func | None:
        for f in self.funcs:
            if f.body == body:
                return f
        return None


def _ty(t: str, m: Module) -> str:
    if t == "struct":
        return m.struct
    if t == "enum":
        return m.enum
    return TYPES[t][m.lang]


def make_module(rng: random.Random, lang: str) -> Module:
    pkg, noun, struct, route, enum, members = rng.choice(TOPICS)
    fields = [("id", "str"), ("status", "enum"), (f"{rng.choice(('weight','amount','score','size'))}_value", "float")]
    fields += list(rng.sample(EXTRA_FIELDS, 2))
    m = Module(pkg=pkg, noun=noun, struct=struct, route=route, enum=enum,
               enum_members=list(members), fields=fields, funcs=[], lang=lang)
    fetch = Func(name=f"fetch_{noun}", body="fetch", ret="struct",
                 doc=f"Return the {noun} stored under the given id.",
                 params=[Param("client", "client"), Param(f"{noun}_id", "str")],
                 ret_optional=True)
    if lang in _PY_TS:
        fetch.params.append(Param("timeout", "float", default="5.0"))
    else:
        # go has no default arguments, so the parameter is there without one -- which is
        # what keeps `remove_param` and `widen_param_type` available in the held-out
        # language rather than silently dropping two trained edit kinds from it.
        fetch.params.append(Param("timeout", "float"))
    listing = Func(name=f"list_{noun}s", body="listing", ret="list_str",
                   doc=f"Return the ids of every {noun} the client can see.",
                   params=[Param("client", "client")])
    if lang in _PY_TS:
        listing.params.append(Param("limit", "int", default="50"))
    validate = Func(name=f"validate_{noun}", body="validate", ret="bool",
                    doc=f"Report whether the {noun} is within the accepted range.",
                    params=[Param("value", "float")],
                    bound=float(rng.choice((120, 250, 500, 1000))))
    validate.bound0 = validate.bound
    fmt = Func(name=f"format_{noun}", body="format", ret="str",
               doc=f"Render the {noun} as a single display line.",
               params=[Param("item", "struct")])
    if lang in _PY_TS:
        fmt.params.append(Param("separator", "str", default='" / "'))
    decode = Func(name=f"decode_{noun}", body="decode", ret="struct", public=False,
                  doc=f"Build a {struct} from a decoded response body.",
                  params=[Param("raw", "record")])
    bucket = Func(name="bucket_index", body="bucket", ret="int", public=False,
                  doc="Return the one-based bucket a value falls in.",
                  params=[Param("value", "float")], offby=1)
    m.funcs = [fetch, listing, validate, fmt, decode, bucket]
    return m


# ---- rendering -----------------------------------------------------------------------

def _fn_name(f: Func, m: Module) -> str:
    if m.lang == "python":
        return f.name if f.public else f"_{f.name}"
    if m.lang == "typescript":
        return _camel(f.name)
    return _pascal(f.name) if f.public else _camel(f.name)


def _field_name(name: str, m: Module) -> str:
    if m.lang == "python":
        return name
    if m.lang == "typescript":
        return _camel(name)
    return _pascal(name).replace("Id", "ID")


def _id_param(ps: list[Param]) -> str:
    """The identifier parameter, by name rather than by position: `add_required_param`
    inserts ahead of it, so position is not stable."""
    for p in ps:
        if p.name.endswith("_id"):
            return p.name
    return ps[-1].name


# --- python ---

def _py_params(f: Func, m: Module) -> str:
    out = []
    for p in f.params:
        s = f"{p.name}: {_ty(p.type, m)}"
        if p.widened and p.type == "float":
            s = f"{p.name}: float | int | str"
        if p.default is not None:
            s += f" = {p.default}"
        out.append(s)
    return ", ".join(out)


def _py_body(f: Func, m: Module) -> list[str]:
    ps = f.params
    if f.shim_for:
        args = ", ".join(p.name for p in ps)
        return [f"    return {f.shim_for}({args})"]
    if f.body == "fetch":
        idp = _id_param(ps)
        extra = "".join(f", {p.name}={p.name}" for p in ps if p.name not in ("client", idp))
        out = [f"    if not {idp}:",
               f'        raise ValueError("{idp} is required")']
        if f.log:
            out.append(f'    _log.debug("fetching %s", {idp})')
        out.append(f'    raw = _client_get(client, f"/{m.route}/{{{idp}}}"{extra})')
        if f.ret_optional:
            out += ["    if raw is None:", "        return None"]
        else:
            out += ["    if raw is None:", f'        raise LookupError({idp})']
        out.append(f"    return _decode_{m.noun}(raw)")
        return out
    if f.body == "listing":
        extra = "".join(f", {p.name}={p.name}" for p in ps[1:])
        out = [f'    {f.local} = _client_get(client, "/{m.route}"{extra})']
        if f.log:
            out.append(f'    _log.debug("%d rows", len({f.local}))')
        if f.ret == "list_str":
            out.append(f'    return [row["id"] for row in {f.local}]')
        else:
            out.append(f'    return {{row["id"]: row for row in {f.local}}}')
        return out
    if f.body == "validate":
        v = ps[0].name
        out = []
        if ps[0].widened:
            out.append(f"    num = float({v})")
            v = "num"
        out += [f"    if {v} < 0:", "        return False"]
        if f.log:
            out.append(f'    _log.debug("checking %s", {v})')
        out.append(f"    return {v} <= {f.bound:g}")
        return out
    if f.body == "format":
        first, second = m.fields[0][0], m.fields[1][0]
        out = [f"    parts = [item.{first}, str(item.{second})]"]
        if f.helper:
            out = ["    parts = _display_parts(item)"]
        if f.log:
            out.append('    _log.debug("formatting %s", parts[0])')
        sep = ps[1].name if len(ps) > 1 else '" / "'
        out.append(f"    return {sep}.join(parts)")
        return out
    if f.body == "decode":
        out = [f"    return {m.struct}("]
        for name, ty in m.fields:
            cast = {"float": "float", "int": "int"}.get(ty)
            expr = f'raw["{name}"]' if not cast else f'{cast}(raw["{name}"])'
            if ty == "enum":
                expr = f'{m.enum}(raw["{name}"])'
            if name in m.fresh_fields:
                expr = f'raw.get("{name}")'
            out.append(f"        {name}={expr},")
        out.append("    )")
        return out
    if f.body == "bucket":
        v = ps[0].name
        return [f"    return int({v} // 25) + {f.offby}"]
    if f.body == "added":
        return [f"    return len({f.local})"]
    if f.body == "helper":
        first, second = m.fields[0][0], m.fields[1][0]
        return [f"    return [item.{first}, str(item.{second})]"]
    return ["    raise NotImplementedError"]


def _render_python(m: Module) -> list[str]:
    L = [f'"""{m.pkg}: read and render {m.noun} records."""', "",
         "from __future__ import annotations", "",
         "import logging", "from dataclasses import dataclass",
         "from enum import Enum", "from typing import Any", "",
         "_log = logging.getLogger(__name__)", "", "",
         f"class {m.enum}(str, Enum):"]
    for mem in m.enum_members:
        L.append(f'    {mem.upper()} = "{mem}"')
    L += ["", "", "@dataclass", f"class {m.struct}:"]
    for name, ty in m.fields:
        # an attribute added in this commit is optional: the record is also a parameter
        # (`format_*(item)`), so a required one would break every caller that builds it
        if name in m.fresh_fields:
            L.append(f"    {name}: {_ty(ty, m)} | None = None")
        else:
            L.append(f"    {name}: {_ty(ty, m)}")
    for f in m.funcs:
        L += ["", "", f"def {_fn_name(f, m)}({_py_params(f, m)}) -> "
              f"{_ty(f.ret, m)}{' | None' if f.ret_optional else ''}:",
              f'    """{f.doc}"""']
        L += _py_body(f, m)
    return L


