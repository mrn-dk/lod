def _last_existing_field(m) -> int | None:
    """Index of the last field that was already there when the commit opened.

    `("add_field", "rename_field")` used to rename the field `add_field` had just
    appended, so the two hunks cancelled: the rendered diff showed one added field and
    nothing else, while the label said `major`/breaking because `rename_field` is in the
    list. 247 of 247 such commits in an earlier build carry a label their own diff denies.
    An edit that cannot reach a pre-existing field returns None and the commit is dropped,
    which is this module's contract everywhere else.
    """
    for i in range(len(m.fields) - 1, 1, -1):
        name = m.fields[i][0]
        if name in m.fresh_fields or name in (m.fields[0][0], m.fields[1][0]):
            continue
        return i
    return None


