def _version(rng: random.Random) -> tuple[int, int, int]:
    return (rng.randrange(1, 9), rng.randrange(0, 14), rng.randrange(0, 9))


def bump_to(v: tuple[int, int, int], level: str) -> tuple[int, int, int]:
    a, b, c = v
    return {"major": (a + 1, 0, 0), "minor": (a, b + 1, 0), "patch": (a, b, c + 1)}[level]


def _vstr(v: tuple[int, int, int]) -> str:
    return "{}.{}.{}".format(*v)


