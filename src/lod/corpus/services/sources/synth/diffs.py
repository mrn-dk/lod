@dataclass
class Commit:
    sha: str
    message: str
    diff: str
    kinds: list[Kind]

    @property
    def level(self) -> str:
        return worst_level(self.kinds)

    @property
    def breaking(self) -> bool:
        return any(k.breaking for k in self.kinds)

    @property
    def compat(self) -> str:
        return worst_compat(self.kinds)

    @property
    def risk(self) -> int:
        return max(k.risk for k in self.kinds)

    @property
    def tier(self) -> int:
        return max(k.tier for k in self.kinds)


def _message(rng: random.Random, m: Module) -> str:
    """The subject names the area and nothing else.

    Neither the template nor the conventional type is a function of the edits, so the
    subject line is independent of the label by construction -- which is what makes the
    diff the only evidence. `tests/test_diffs_source.py` measures both: the banned-word
    test and the conventional-parser test.
    """
    area = rng.choice((m.pkg, m.noun, "the client", f"the {m.noun} path",
                       f"the {m.pkg} module"))
    body = rng.choice(VAGUE).format(area=area)
    if rng.random() < 0.5:
        body = f"{rng.choice(CONVENTIONAL)}({m.pkg}): {body}"
    return body


def build_commit(kind_names: tuple[str, ...], rng: random.Random, lang: str) -> Commit | None:
    """Apply the named edits to a fresh module and render the diff. None if any edit
    does not apply -- a commit whose label code cannot derive is dropped, never guessed."""
    m = make_module(rng, lang)
    # The subject is drawn HERE, before a single edit has run. `make_module` consumes a
    # fixed number of draws whatever the spec, but the edits do not, so a subject drawn
    # afterwards sat at a stream position that was itself a function of the edit kind:
    # naive Bayes over the subject alone read semver at 53 % against a 36 % baseline and
    # `breaking` at 64 % against 52 %. Nothing about the wording leaked; the *phase* did.
    message = _message(rng, m)
    before = render(m)
    kinds: list[Kind] = []
    for name in kind_names:
        kind = KINDS[name]
        if lang not in kind.langs:
            return None
        # an edit returns a phrase when it applied and None when it did not; the phrase
        # is deliberately NOT used in the subject line -- see `VAGUE`
        if EDITS[name](m, rng) is None:
            return None
        kinds.append(kind)
    after = render(m)
    if before == after:
        return None
    # Six lines of context, not three. Measured with the Qwen tokenizer over 400 single-
    # edit commits: n=3 gives p50 142 / p95 202 tokens, n=6 gives p50 192 / p95 262, both
    # far inside `ship_v4.sh --max-state-tokens 2304`. The extra context is what lets a
    # reader see whether the symbol a hunk touches is public, so it is worth the tokens.
    diff = "".join(difflib.unified_diff(before, after, f"a/{m.path}", f"b/{m.path}", n=6))
    sha = hashlib.sha256(f"{kind_names}{rng.random()}".encode()).hexdigest()[:10]
    return Commit(sha=sha, message=message, diff=diff, kinds=kinds)


def commit_state(c: Commit, extra: str = "") -> str:
    head = f"commit {c.sha}\n"
    if extra:
        head += extra if extra.endswith("\n") else extra + "\n"
    return f"{head}\n    {c.message}\n\n{c.diff}"


