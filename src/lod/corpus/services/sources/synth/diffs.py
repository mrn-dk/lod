# One row per edit kind. `level`, `breaking`, `compat` and `risk` are the whole of the
# label: a commit is a list of edits, and code takes the worst of each column. Nothing
# about the label is ever read out of the commit message.


@dataclass(frozen=True)
class Kind:
    name: str
    level: str        # patch | minor | major
    breaking: bool    # does an existing, correct caller stop working
    compat: str       # compatible | behaviour | source
    risk: int         # a finer order kept for reference; the risk TARGET uses `tier`
    langs: tuple[str, ...]

    @property
    def tier(self) -> int:
        """The four tiers the risk instructions state, and nothing finer: a caller-visible
        compile/resolve break (3) > same call, different behaviour (2) > additive (1) >
        private (0). The instructions never order two kinds inside one tier, so a target
        that did (`risk` 95 vs 90) was not derivable from the criteria shown."""
        if self.compat == "source":
            return 3
        if self.compat == "behaviour":
            return 2
        return 1 if self.level == "minor" else 0


