def _go_body(f: Func, m: Module) -> list[str]:
    ps = f.params
    zero = {"bool": "false", "int": "0", "str": '""', "float": "0",
            "list_str": "nil", "record": "nil", "struct": "nil"}.get(f.ret, "nil")
    if f.shim_for:
        args = ", ".join(_camel(p.name) for p in ps)
        return [f"\treturn {_pascal(f.shim_for)}({args})"]
    if f.body == "fetch":
        raw_id = _id_param(ps)
        idp = _camel(raw_id)
        extra = "".join(f", {_camel(p.name)}" for p in ps if p.name not in ("client", raw_id))
        out = [f'\tif {idp} == "" {{',
               f'\t\treturn {zero}, errors.New("{raw_id} is required")', "\t}"]
        if f.log:
            out.append(f'\tlog.Printf("fetching %s", {idp})')
        out.append(f'\traw, err := clientGet(client, "/{m.route}/"+{idp}{extra})')
        out += ["\tif err != nil {", f"\t\treturn {zero}, err", "\t}"]
        # The miss branch is rendered in BOTH states. It used to exist only after
        # `raise_instead_of_none`, so the "before" fell through to decoding a nil map --
        # a panic on the type assertions -- and the edit read as a crash turned into an
        # error, not as `nil, nil` turned into an error. Go says "not found" as nil, nil.
        if f.ret_optional:
            out += ["\tif raw == nil {", f"\t\treturn {zero}, nil", "\t}"]
        else:
            out += ["\tif raw == nil {", f'\t\treturn {zero}, errors.New("not found")', "\t}"]
        out.append(f"\treturn decode{m.struct}(raw)")
        return out
    if f.body == "listing":
        extra = "".join(f", {_camel(p.name)}" for p in ps[1:])
        out = [f'\t{f.local}, err := clientGet(client, "/{m.route}"{extra})',
               "\tif err != nil {", f"\t\treturn {zero}, err", "\t}"]
        if f.log:
            out.append(f'\tlog.Printf("%d rows", len({f.local}))')
        if f.ret == "list_str":
            out += ["\tids := make([]string, 0, len(" + f.local + "))",
                    f"\tfor _, row := range {f.local} {{",
                    '\t\tids = append(ids, row["id"].(string))', "\t}",
                    "\treturn ids, nil"]
        else:
            out += ["\tout := map[string]any{}",
                    f"\tfor _, row := range {f.local} {{",
                    '\t\tout[row["id"].(string)] = row', "\t}",
                    "\treturn out, nil"]
        return out
    if f.body == "validate":
        v = _camel(ps[0].name)
        out = []
        if ps[0].widened:
            out.append(f"\tnum := toFloat({v})")
            v = "num"
        out += [f"\tif {v} < 0 {{", "\t\treturn false, nil", "\t}"]
        if f.log:
            out.append(f'\tlog.Printf("checking %v", {v})')
        out.append(f"\treturn {v} <= {f.bound:g}, nil")
        return out
    if f.body == "format":
        first, second = _field_name(m.fields[0][0], m), _field_name(m.fields[1][0], m)
        out = [f"\tparts := []string{{item.{first}, fmt.Sprint(item.{second})}}"]
        if f.helper:
            out = ["\tparts, _ := displayParts(item)"]
        if f.log:
            out.append('\tlog.Printf("formatting %s", parts[0])')
        out.append('\treturn strings.Join(parts, " / "), nil')
        return out
    if f.body == "decode":
        out = [f"\tout := &{m.struct}{{}}"]
        for name, ty in m.fields:
            n = _field_name(name, m)
            if ty in ("float", "int"):
                out.append(f'\tout.{n} = raw["{name}"].(float64)')
            elif ty == "enum":
                out.append(f'\tout.{n} = {m.enum}(raw["{name}"].(string))')
            else:
                out.append(f'\tout.{n} = raw["{name}"].(string)')
        out.append("\treturn out, nil")
        return out
    if f.body == "bucket":
        v = _camel(ps[0].name)
        return [f"\treturn int({v}/25) + {f.offby}, nil"]
    if f.body == "added":
        return [f"\treturn len({f.local}), nil"]
    if f.body == "helper":
        first, second = _field_name(m.fields[0][0], m), _field_name(m.fields[1][0], m)
        return [f"\treturn []string{{item.{first}, fmt.Sprint(item.{second})}}, nil"]
    return ["\tpanic(\"not implemented\")"]


def _render_go(m: Module) -> list[str]:
    L = [f"// Package {m.pkg} reads and renders {m.noun} records.",
         f"package {m.pkg}", "",
         "import (", '\t"errors"', '\t"fmt"', '\t"log"', '\t"strings"', ")", "",
         f"type {m.enum} string", "", "const ("]
    for mem in m.enum_members:
        L.append(f'\t{m.enum}{_pascal(mem)} {m.enum} = "{mem}"')
    L += [")", "", f"type {m.struct} struct {{"]
    for name, ty in m.fields:
        L.append(f"\t{_field_name(name, m)} {_ty(ty, m)}")
    L.append("}")
    for f in m.funcs:
        L += ["", f"// {_fn_name(f, m)}: {f.doc[0].lower()}{f.doc[1:]}",
              f"func {_fn_name(f, m)}({_go_params(f, m)}) {_go_ret(f, m)} {{"]
        L += _go_body(f, m)
        L.append("}")
    return L


