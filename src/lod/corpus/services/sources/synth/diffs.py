def _wording(family: str, rng: random.Random) -> dict:
    return rng.choice(WORDINGS[family])


# ---- phrasing bank (lod/assets/phrasing_specs/d18.json) -----------------------------
# The drawn wording is the template handed to the bank, so with an empty bank nothing
# changes. `breaking` has one template id PER POLARITY: a bank phrasing must never turn a
# "does it preserve" question into a "does it break" one, which is the failure the
# polarity field exists to stop (44.3 % of an earlier build's breaking questions).
_BANK = None


def _phrase(template_id: str, question: str, key: str) -> str:
    global _BANK
    if _BANK is None:
        from lod.phrasings import PhrasingBank
        _BANK = PhrasingBank.load()
    return _BANK.pick(template_id, question, key)


