def _ts_params(f: Func, m: Module) -> str:
    out = []
    for p in f.params:
        t = _ty(p.type, m)
        if p.widened and p.type == "float":
            t = "number | string"
        s = f"{_camel(p.name)}: {t}"
        if p.default is not None:
            d = p.default.replace("'", '"')
            s = f"{_camel(p.name)}: {t} = {d}"
        out.append(s)
    return ", ".join(out)


def _ts_body(f: Func, m: Module) -> list[str]:
    ps = f.params
    if f.shim_for:
        args = ", ".join(_camel(p.name) for p in ps)
        return [f"  return {_camel(f.shim_for)}({args});"]
    if f.body == "fetch":
        raw_id = _id_param(ps)
        idp = _camel(raw_id)
        extra = "".join(f", {_camel(p.name)}" for p in ps if p.name not in ("client", raw_id))
        out = [f"  if (!{idp}) {{", f'    throw new Error("{raw_id} is required");', "  }"]
        if f.log:
            out.append(f'  log.debug("fetching", {idp});')
        out.append(f'  const raw = clientGet(client, `/{m.route}/${{{idp}}}`{extra});')
        if f.ret_optional:
            out += ["  if (raw === null) {", "    return null;", "  }"]
        else:
            out += ["  if (raw === null) {", f"    throw new Error({idp});", "  }"]
        out.append(f"  return decode{m.struct}(raw);")
        return out
    if f.body == "listing":
        extra = "".join(f", {_camel(p.name)}" for p in ps[1:])
        out = [f'  const {f.local} = clientGet(client, "/{m.route}"{extra});']
        if f.log:
            out.append(f'  log.debug("rows", {f.local}.length);')
        if f.ret == "list_str":
            out.append(f'  return {f.local}.map((row) => row.id);')
        else:
            out.append(f'  return Object.fromEntries({f.local}.map((row) => [row.id, row]));')
        return out
    if f.body == "validate":
        v = _camel(ps[0].name)
        out = []
        if ps[0].widened:
            out.append(f"  const num = Number({v});")
            v = "num"
        out += [f"  if ({v} < 0) {{", "    return false;", "  }"]
        if f.log:
            out.append(f'  log.debug("checking", {v});')
        out.append(f"  return {v} <= {f.bound:g};")
        return out
    if f.body == "format":
        first, second = _camel(m.fields[0][0]), _camel(m.fields[1][0])
        out = [f"  const parts = [item.{first}, String(item.{second})];"]
        if f.helper:
            out = ["  const parts = displayParts(item);"]
        if f.log:
            out.append('  log.debug("formatting", parts[0]);')
        sep = _camel(ps[1].name) if len(ps) > 1 else '" / "'
        out.append(f"  return parts.join({sep});")
        return out
    if f.body == "decode":
        out = [f"  return {{"]
        for name, ty in m.fields:
            n = _camel(name)
            expr = f'raw.{n} as string'
            if name in m.fresh_fields:
                expr = f"raw.{n} as string | undefined"
            elif ty in ("float", "int"):
                expr = f"Number(raw.{n})"
            elif ty == "enum":
                expr = f"raw.{n} as {m.enum}"
            out.append(f"    {n}: {expr},")
        out.append("  };")
        return out
    if f.body == "bucket":
        v = _camel(ps[0].name)
        return [f"  return Math.floor({v} / 25) + {f.offby};"]
    if f.body == "added":
        return [f"  return {f.local}.length;"]
    if f.body == "helper":
        first, second = _camel(m.fields[0][0]), _camel(m.fields[1][0])
        return [f"  return [item.{first}, String(item.{second})];"]
    return ["  throw new Error('not implemented');"]


def _render_typescript(m: Module) -> list[str]:
    L = [f"// {m.pkg}: read and render {m.noun} records.", "",
         'import { Client, clientGet, log } from "../runtime";', "",
         f"export enum {m.enum} {{"]
    for mem in m.enum_members:
        L.append(f'  {_pascal(mem)} = "{mem}",')
    L += ["}", "", f"export interface {m.struct} {{"]
    for name, ty in m.fields:
        opt = "?" if name in m.fresh_fields else ""    # see _render_python
        L.append(f"  {_camel(name)}{opt}: {_ty(ty, m)};")
    L.append("}")
    for f in m.funcs:
        ret = _ty(f.ret, m) + (" | null" if f.ret_optional else "")
        export = "export " if f.public else ""
        L += ["", f"/** {f.doc} */",
              f"{export}function {_fn_name(f, m)}({_ts_params(f, m)}): {ret} {{"]
        L += _ts_body(f, m)
        L.append("}")
    return L


