# Nothing in this list may ever appear in a state. The conventional-commit type is drawn
# independently of the label, so `fix:` sits on breaking diffs as often as on patches --
# which is what stops this row from being a conventional-commits parser.
CONVENTIONAL = ("feat", "fix", "refactor", "chore", "perf", "style")
