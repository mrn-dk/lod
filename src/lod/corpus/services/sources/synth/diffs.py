SEMVER_OPTIONS = ["patch", "minor", "major"]
BREAKING_OPTIONS = ["no", "yes"]
COMPAT_OPTIONS = ["no_change_needed", "same_call_different_behaviour", "callers_must_change"]
BUMP_OPTIONS = ["correct", "too_small", "larger_than_necessary"]

_COMPAT_TO_OPTION = {"compatible": 0, "behaviour": 1, "source": 2}


def _q_semver(c: Commit, rng: random.Random, qid: str, key: str = "") -> Question:
    w = _wording("semver", rng)
    return Question(id=qid, question=_phrase("d18.semver", w["question"], key or qid),
                    options=list(SEMVER_OPTIONS),
                    target=LEVELS.index(c.level), instructions=w.get("instructions"),
                    descriptions=[w["descriptions"][o] for o in SEMVER_OPTIONS],
                    meta={"kinds": [k.name for k in c.kinds]})


# Seven of the sixteen `breaking` wordings ask the question the other way round -- "does
# this PRESERVE every correct call", not "does this BREAK one". The descriptions the model
# wrote are all in break-polarity (`yes` is always the one that says something stops
# working), and the target used to be `int(c.breaking)` for every wording, so 2,659 of the
# 6,000 breaking questions in an earlier build (44.3 %) ask one question and score the
# answer to its opposite. The polarity now travels with the wording and both the option
# order and the target follow it, so the question is load-bearing rather than misleading.

def _q_breaking(c: Commit, rng: random.Random, qid: str, key: str = "") -> Question:
    w = _wording("breaking", rng)
    preserve = w.get("polarity") == "preserve"
    tid = "d18.breaking_preserve" if preserve else "d18.breaking"
    descs = w["descriptions"]
    if preserve:
        # "no" now means "no, it is not preserved", i.e. something stops working
        descs = {"no": descs["yes"], "yes": descs["no"]}
    return Question(id=qid, question=_phrase(tid, w["question"], key or qid),
                    options=list(BREAKING_OPTIONS),
                    target=int(not c.breaking) if preserve else int(c.breaking),
                    instructions=w.get("instructions"),
                    descriptions=[descs[o] for o in BREAKING_OPTIONS],
                    meta={"kinds": [k.name for k in c.kinds],
                          "polarity": "preserve" if preserve else "break"})


def _q_compat(c: Commit, rng: random.Random, qid: str, key: str = "") -> Question:
    w = _wording("compat", rng)
    return Question(id=qid, question=_phrase("d18.compat", w["question"], key or qid),
                    options=list(COMPAT_OPTIONS),
                    target=_COMPAT_TO_OPTION[c.compat], instructions=w.get("instructions"),
                    descriptions=[w["descriptions"][o] for o in COMPAT_OPTIONS],
                    meta={"kinds": [k.name for k in c.kinds]})


def _balanced(specs: tuple, classify) -> tuple:
    """Re-order a spec pool so the *label* classes come round evenly.

    There are twelve breaking edit kinds, seven additive and five internal, so cycling the
    pool straight through hands `semver` a 54 % `major` marginal -- a baseline a model can
    reach without reading a diff. Interleaving by the class the spec produces flattens it
    to a third each, and the same helper flattens `breaking` to half and `compat` to a
    third by their own classes.
    """
    buckets: dict[str, list] = {}
    for spec in specs:
        buckets.setdefault(str(classify(spec)), []).append(spec)
    keys = sorted(buckets)
    span = max(len(v) for v in buckets.values()) * len(keys) * 2
    return tuple(buckets[keys[i % len(keys)]][(i // len(keys)) % len(buckets[keys[i % len(keys)]])]
                 for i in range(span))


def _by_level(spec) -> str:
    return worst_level([KINDS[n] for n in spec])


def _by_breaking(spec) -> str:
    return str(any(KINDS[n].breaking for n in spec))


def _by_compat(spec) -> str:
    return worst_compat([KINDS[n] for n in spec])


BALANCE = {"semver": _by_level, "breaking": _by_breaking, "compat": _by_compat}




def _family_loader(family: str, specs: tuple, langs: tuple[str, ...], seed: int, task: str):
    """One question per example: the diff is the state, the family is the question."""
    maker = {"semver": _q_semver, "breaking": _q_breaking, "compat": _q_compat}[family]
    specs = _balanced(specs, BALANCE[family])

    def load(n: int) -> Iterator[Example]:
        made = 0
        for i in range(n * 12):
            if made >= n:
                return
            # A *fresh* stream per example, and the spec drawn from it rather than from
            # `i % len(specs)`. With one shared stream and a cycled spec, the topic, the
            # language and the spec advanced in lockstep: the package name alone then read
            # `breaking` at 98 % against a 52 % baseline, because the balanced pool
            # alternates classes and everything else was phase-locked to it. This is the
            # same failure as the row-36 leak, one layer down -- not in the wording but in
            # the draw order.
            rng = random.Random(f"{seed}:{family}:{task}:{i}")
            spec = specs[rng.randrange(len(specs))]
            lang = langs[rng.randrange(len(langs))]
            c = build_commit(spec, rng, lang)
            if c is None:
                continue
            made += 1
            yield Example(state=commit_state(c), task=task,
                          questions=[maker(c, rng, f"{family}_{i}", f"{task}:{i}")])
    return load


def _bump_loader(specs: tuple, langs: tuple[str, ...], seed: int, task: str):
    """The release tag is in the state; the question is whether it is the right one."""
    pool = _balanced(specs, _by_level)

    def load(n: int) -> Iterator[Example]:
        made = 0
        for i in range(n * 12):
            if made >= n:
                return
            rng = random.Random(f"{seed}:bump:{task}:{i}")
            c = build_commit(pool[rng.randrange(len(pool))], rng,
                             langs[rng.randrange(len(langs))])
            if c is None:
                continue
            required = LEVELS.index(c.level)
            proposed = rng.choice([required] * 2 + [x for x in range(3) if x != required])
            cur = _version(rng)
            new = bump_to(cur, LEVELS[proposed])
            tag = f"Proposed release: {_vstr(cur)} -> {_vstr(new)}"
            target = 0 if proposed == required else (1 if proposed < required else 2)
            w = _wording("bump", rng)
            made += 1
            yield Example(state=commit_state(c, tag), task=task, questions=[Question(
                id=f"bump_{i}", question=_phrase("d18.bump", w["question"], f"{task}:{i}"),
                options=list(BUMP_OPTIONS),
                target=target, instructions=w.get("instructions"),
                descriptions=[w["descriptions"][o] for o in BUMP_OPTIONS],
                meta={"kinds": [k.name for k in c.kinds],
                      "proposed": LEVELS[proposed], "required": c.level})])
    return load


def _risk_loader(specs: tuple, langs: tuple[str, ...], seed: int, task: str):
    """A different *shape*: several candidate commits in one state, pick the worst.

    Row 33's worst held-out result was the family whose shape -- compare across records --
    appeared nowhere else, so one family here is deliberately an aggregation rather than a
    classification. The options are opaque change ids, so nothing in the state names the
    answer.

    The target is the one candidate in the highest of the four tiers the instructions
    state (`Kind.tier`); a set whose top tier is shared is dropped, never broken. It used
    to be the highest `Kind.risk`, a finer order the instructions never state --
    `remove_public_fn` 95 over `rename_public_fn` 90, `raise_instead_of_none` 74 over
    `change_default` 70 -- so in 42 % of risk questions (168 of 400, domain-18 audit)
    the gold and the runner-up sat in one tier and a reader applying the criteria exactly
    could not tell them apart.
    """
    pool = _balanced(specs, _by_level)

    def load(n: int) -> Iterator[Example]:
        made = 0
        for i in range(n * 12):
            if made >= n:
                return
            rng = random.Random(f"{seed}:risk:{task}:{i}")
            lang = langs[rng.randrange(len(langs))]
            k = rng.choice((3, 4, 5, 6))
            cs = []
            for j in range(k):
                c = build_commit(pool[rng.randrange(len(pool))], rng, lang)
                if c is not None:
                    cs.append(c)
            if len(cs) < 3:
                continue
            risks = [c.tier for c in cs]
            top = max(risks)
            if risks.count(top) != 1:
                continue
            ids = [f"C-{rng.randrange(1000, 9999)}" for _ in cs]
            if len(set(ids)) != len(ids):
                continue
            state = "\n\n".join(
                f"=== change {ids[j]} ===\n{commit_state(cs[j])}" for j in range(len(cs)))
            w = _wording("risk", rng)
            made += 1
            yield Example(state=state, task=task, questions=[Question(
                id=f"risk_{i}", question=_phrase("d18.risk", w["question"], f"{task}:{i}"),
                options=list(ids),
                target=risks.index(top), instructions=w.get("instructions"),
                descriptions=[f"the change committed as {x}" for x in ids],
                meta={"kinds": [[kk.name for kk in c.kinds] for c in cs]})])
    return load


