"""Row 40 -- Code and diffs (domain 18).

Change impact: breaking against additive, risky against routine. The state is a unified
diff over a small public module, and the question is what that diff does to the people
who already call it.

**Why this is generated and not scraped.** The domain's planned seed was "public commits
and release tags". There is no such seed on disk -- `gharchive_issues.jsonl` carries
issue metadata only (`repo`, `label`, `title`, `body`, `vocab`), no patch and no
PushEvent payload -- and fetching one would import third-party licences into a corpus
whose licence audit is already 13 % unverified. It would also import a worse label: a
real project's version bump is frequently *wrong*, and the wrongness is not random --
maintainers ship breaking renames as patch releases, which is exactly the mistake the
shipped model makes. Generating the diff makes the label exact and free of licence.

**What the domain is for.** The single most-cited failure of the shipped model is a
semver question: `refactor: rename getUser to fetchUser across the public SDK, no
deprecation shim` -> `patch`. An earlier probe set carried that probe in both forms, and
giving the three options their definitions moved an earlier model from `patch` to `major`
at 0.669. Nothing in the corpus trains it. This row does, and it is deliberately *not*
that probe: the probe is one sentence of prose about a rename, and every state here is a
diff whose commit message is impact-free by construction.

**The design point.** If the commit message says "BREAKING CHANGE" or "fix:", the label
is free and this is a conventional-commits parser. So the message never states impact --
`MESSAGE_BANNED` is asserted against every state in the tests -- and the conventional
type, where there is one, is drawn independently of the true level. The interesting
diffs are the breaking ones that look routine (a renamed public symbol, a default
changed, a validation tightened, a `None` return turned into a raise) and the additive
ones that look alarming (a deprecation that still works, a new optional parameter, a new
enum member).

**Two holdouts, both structural.** Following row 33 and row 36, and for the same reason:
holding out samples leaks, because two diffs of one kind are near-duplicates.

  1. `HELDOUT_COMBOS` -- whole *combinations* of edit kinds, every component of which is
     trained alone. A commit that adds an enum member and removes another is `major`;
     a commit that deprecates with a shim and adds an optional parameter is `minor`.
     Neither pair is ever trained; both halves of each always are. The TRAINED pairs
     include additive-beside-breaking, additive-beside-additive and private-beside-
     private, so worst-of is what training teaches rather than one reading among several
     (see the comment on `TRAINED_COMBOS`).
  2. `HELDOUT_LANG` -- one whole language (`go`), whose edit kinds are all trained in
     `python` and `typescript`. `tests/test_diffs_source.py` asserts both subset
     properties, so a drop on either holdout is a failure to generalise over structure
     rather than an unseen edit.

`DEV_COMBOS` is a third set of never-trained pairings, disjoint from both of the above,
forced to `devreal`: checkpoint selection and the temperature read it, so dev measures
transfer the way test does without sharing a structure with it.

**Criteria as input.** Every question carries one description per option -- the semver
definitions, the compatibility rule, the risk ordering. That is the bet the semver probe
measured (`patch` bare, `major` at 0.669 with the definitions attached), and
this row is where it gets trained rather than probed.

The question wording and the option definitions in `WORDINGS` were written by
`deepseek/deepseek-v4.1-flash` via a one-off generation script. The model never saw a
target: it was given an option *list* and asked for a definition of each, and code picks
a variant and attaches the label it computed from the edit list.
"""

