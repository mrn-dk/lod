# ==== domains =========================================================================
# `records.DOMAINS` carries one measured/limit pair per domain. A rule that compares a
# field with its own limit is the commonest shape a real policy has ("over its weight
# limit", "past its SLA"), so each domain gains two more pairs here -- as new fields of
# this module's own copy of the domain, leaving row 33's records untouched.

@dataclass(frozen=True)
class CDomain:
    dom: Domain
    plural: str
    coll: str                          # the state's key for the list of records
    pairs: tuple[tuple[str, str], ...]  # (measured, limit), both fields of one record

    @property
    def noun(self) -> str:
        return self.dom.noun

    @property
    def idf(self) -> str:
        return self.dom.ids[0]

    def num(self, name: str) -> Num:
        return next(f for f in self.dom.nums if f.name == name)

    @property
    def limits(self) -> set[str]:
        return {b for _, b in self.pairs}

    @property
    def meas(self) -> list[Num]:
        """Numeric fields a constant is compared with: every number but the limits."""
        return [f for f in self.dom.nums if f.name not in self.limits]

    @property
    def enums(self) -> list[Enum]:
        return list(self.dom.enums)


