"""Row 47 -- rules as random compositions, held out by composition and by depth.

Row 33 (`rules.py` over `grammar.py`) showed that primitives compose when the model has
seen the combination: trained rule forms 0.978, held-out forms 0.598, and cross-record
comparison at chance (0.267). But it trains a fixed list of thirteen combinations, holds
out six, never goes past depth two, renders states two ways and words each primitive one
way. A model can learn thirteen templates. This row is built so that it cannot.

**Primitives** (every one trained on its own, at depth 1):

    cmp      a numeric field against a constant   >  <  >=  <=  (and =, != on small counts)
    eq       a categorical field = / != a value
    range    a numeric field inside / outside [lo, hi] (inclusive)
    member   a categorical field in / not in a set
    fref     a field against its limit in the SAME record   (`weight` vs `weight_limit`)
    pref     a field against a bound held in ANOTHER record, the policy / limits record
    all any none atleast   a quantifier over every record shown, of one of the six above
    agg      count / sum / mean / min / max over the records, against a constant
    cross    this record against another: a named record, the max / min, a rank position

**Connectives**: `and`, `or` (2-3 children), `not`, `implies`, `xor` (exactly one of 2-3).

**The split is taken over the signature.** A tree's signature is its operator structure
over primitive kinds, commutative children sorted (`and(cmp,or(agg,member))`). Depth 1
(one primitive) always trains. Depth 2-3 signatures are hashed 80/10/10 into train /
devreal / testreal; every depth-4 signature is hashed 50/50 into devreal / testreal and
never trains. What dev and test hold out is therefore *compositions and depths*, never
primitives: a miss there is a failure to compose things the model has met.

**Paraphrase is held out too.** Every piece of rule text comes from a template bank
(`BANKS`); about a quarter of each bank's templates never reach training. Half of each
dev/test question is worded with held-out templates wherever the bank has one, and
`meta.tpl` says which half a question is in, so dev measures paraphrase transfer beside
composition transfer.

**Labels are computed, balanced clause-first** (the lesson of the v24 audit of row 33:
one clause decided 87-94 % of held-out combinations, and a primitive's constant could be
skipped 81-90 % of the time). The answer each task owes (`no` or `yes`, whichever it has
emitted less) is chosen first; then a truth pattern over the tree's leaves giving that
answer, weighted so a pattern where some single leaf is decisive is ten times as likely
as one where none is; then each leaf is *built* to have its truth, by placing its constant
just either side of the value it reads (the side drawn independently of where the value
sits in its range), or by setting the values its own fields hold. So no leaf, no field and
no constant-free reading of a leaf carries the answer beyond what the tree's structure
gives it, and a shortcut audit measures that.

**Seven state formats**: JSON, YAML, prose, a markdown table, CSV, `key: value` blocks,
and path-flattened lines (`lod.serialize.flatten_paths`). The records of a state always
carry the same fields as each other (row 33's domain-2 audit found records with different
key sets were a tell nobody chose).

**Question shapes**: mostly yes/no, the rule as the `yes` description and its negation as
the `no`; about a third are routing questions (two to four rules as options, exactly one
true). A few questions list a sentinel option (`lod.sentinel`), at rates set so the row
passes the sentinel audit (`lod.corpus.services.audit`) on its own (see
`P_NOUL_SENTINEL`). When the sentinel is the answer, either no rule holds or a field the
rule reads has been removed from the state -- only a field whose absence leaves the rule
truly undecided -- with `meta.abstain = True`.
"""

