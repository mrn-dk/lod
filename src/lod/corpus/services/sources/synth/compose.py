# ==== signatures and the split ========================================================
# A skeleton is a nested tuple: a leaf is its kind string, a node is (op, *children).

def sig_of(sk) -> str:
    if isinstance(sk, str):
        return sk
    op, *kids = sk
    parts = [sig_of(k) for k in kids]
    if op in COMMUTATIVE:
        parts.sort()
    return f"{op}({','.join(parts)})"


def depth_of(sk) -> int:
    return 1 if isinstance(sk, str) else 1 + max(depth_of(k) for k in sk[1:])


def leaves_of(sk) -> list[str]:
    return [sk] if isinstance(sk, str) else [x for k in sk[1:] for x in leaves_of(k)]


def ops_of(sk) -> list[str]:
    return [] if isinstance(sk, str) else [sk[0]] + [o for k in sk[1:] for o in ops_of(k)]


def split_of_sig(sig: str, depth: int) -> str:
    """Depth 1 trains. Depth 2-3: 80/10/10 by hash. Depth 4: dev/test only, 50/50."""
    if depth <= 1:
        return "train"
    h = int.from_bytes(hashlib.sha256(f"compose:{sig}".encode()).digest()[:8], "big") % 100
    if depth <= 3:
        return "train" if h < 80 else ("devreal" if h < 90 else "testreal")
    return "devreal" if h < 50 else "testreal"


def sample_skeleton(rng: random.Random, depth: int, parent: str | None = None):
    """A random tree of exactly `depth`. An associative op never nests in itself (the
    flat n-ary form is used instead, so one composition has one signature), and `not`
    never wraps `not`."""
    if depth == 1:
        return rng.choice(KINDS)
    ops = [o for o in OPS if not (o == parent and o in ("and", "or", "xor", "not"))]
    op = rng.choices(ops, weights=[OP_WEIGHTS[o] for o in ops])[0]
    if op == "not":
        return ("not", sample_skeleton(rng, depth - 1, "not"))
    arity = 2 if op == "implies" or rng.random() < 0.8 else 3
    main = rng.randrange(arity)
    kids = []
    for i in range(arity):
        d = depth - 1 if i == main else (1 if rng.random() < 0.6 else rng.randint(1, depth - 1))
        kids.append(sample_skeleton(rng, d, op))
    return (op, *kids)


def skeleton_for(rng: random.Random, split: str, depth: int, max_leaves: int = MAX_LEAVES):
    for _ in range(4000):
        sk = sample_skeleton(rng, depth)
        if len(leaves_of(sk)) <= max_leaves and split_of_sig(sig_of(sk), depth) == split:
            return sk
    raise RuntimeError(f"no depth-{depth} skeleton lands in {split}")


# ==== evaluation ======================================================================

def _cmp(a: float, op: str, b: float) -> bool:
    eps = 1e-9
    if op == ">":
        return a > b + eps
    if op == "<":
        return a < b - eps
    if op == ">=":
        return a >= b - eps
    if op == "<=":
        return a <= b + eps
    if op == "==":
        return abs(a - b) <= eps
    if op == "!=":
        return abs(a - b) > eps
    raise ValueError(op)


NEG_OP = {">": "<=", "<=": ">", "<": ">=", ">=": "<", "==": "!=", "!=": "=="}
OP_BANK = {">": "gt", "<": "lt", ">=": "ge", "<=": "le", "==": "eq_num", "!=": "ne_num"}


@dataclass
class State:
    cd: CDomain
    recs: list[dict]
    focus: int
    policy: dict
    pname: str

    @property
    def fid(self) -> str:
        return self.recs[self.focus][self.cd.idf]

    def snapshot(self):
        return copy.deepcopy(self.recs), dict(self.policy)

    def restore(self, snap) -> None:
        self.recs, self.policy = copy.deepcopy(snap[0]), dict(snap[1])

    def as_obj(self) -> dict:
        obj = {self.cd.coll: self.recs}
        if self.policy:
            obj[self.pname] = self.policy
        return obj


class Leaf:
    """A primitive. `spec` is JSON-serialisable and is all an independent evaluator
    needs; `reads` names every field (and `policy:<key>`) the leaf looks at."""

    def __init__(self, kind: str, spec: dict, reads: set[str]):
        self.kind, self.spec, self.reads = kind, spec, reads

    def value(self, st: State) -> bool | None:
        return eval_leaf(self.spec, st.as_obj(), st.cd.coll, st.pname, st.cd.idf, st.fid)


def _atom(spec: dict, rec: dict, policy: dict | None) -> bool | None:
    """A record-level primitive on one record; None when a field it reads is absent."""
    k = spec["k"]
    if k == "cmp":
        v = rec.get(spec["f"])
        return None if v is None else _cmp(v, spec["op"], spec["c"])
    if k == "eq":
        v = rec.get(spec["f"])
        return None if v is None else ((v == spec["v"]) == (spec["op"] == "=="))
    if k == "range":
        v = rec.get(spec["f"])
        if v is None:
            return None
        return (spec["lo"] - 1e-9 <= v <= spec["hi"] + 1e-9) == spec["inside"]
    if k == "member":
        v = rec.get(spec["f"])
        return None if v is None else ((v in spec["vals"]) == spec["inside"])
    if k == "fref":
        a, b = rec.get(spec["a"]), rec.get(spec["b"])
        return None if a is None or b is None else _cmp(a, spec["op"], b)
    if k == "pref":
        v = rec.get(spec["f"])
        c = (policy or {}).get(spec["key"])
        return None if v is None or c is None else _cmp(v, spec["op"], c)
    raise ValueError(k)


def eval_leaf(spec: dict, obj: dict, coll: str, pname: str, idf: str, fid) -> bool | None:
    recs = obj[coll]
    policy = obj.get(pname)
    focus = next(r for r in recs if r.get(idf) == fid)
    k = spec["k"]
    if k in RECORD_KINDS:
        return _atom(spec, focus, policy)
    if k in QUANT_KINDS:
        vals = [_atom(spec["phi"], r, policy) for r in recs]
        t, u = vals.count(True), vals.count(None)
        need = {"all": len(vals), "any": 1, "none": 1, "atleast": spec.get("n", 1)}[k]
        if t >= need:
            res = True
        elif t + u < need:
            res = False
        else:
            return None
        return (not res) if k == "none" else res
    if k == "agg":
        if spec["fn"] == "count":
            vals = [r.get(spec["f"]) for r in recs]
            if any(v is None for v in vals):
                return None
            a = sum(v == spec["v"] for v in vals)
        else:
            vals = [r.get(spec["f"]) for r in recs]
            if any(v is None for v in vals):
                return None
            a = {"sum": lambda x: round(sum(x), 6), "mean": lambda x: sum(x) / len(x),
                 "min": min, "max": max}[spec["fn"]](vals)
        return _cmp(a, spec["op"], spec["c"])
    if k == "cross":
        f = spec["f"]
        if any(r.get(f) is None for r in recs):
            return None
        mine = focus[f]
        if spec["mode"] == "named":
            other = next(r for r in recs if r.get(idf) == spec["other"])
            return _cmp(mine, spec["op"], other[f])
        others = [r[f] for r in recs if r is not focus]
        beat = sum((v > mine) if spec["hi"] else (v < mine) for v in others)
        if spec["mode"] == "extreme":
            return beat == 0
        return beat < spec["n"]
    raise ValueError(k)


def eval_tree(tree, st: State) -> bool | None:
    """Kleene three-valued evaluation. Exact here because no field is read by two leaves
    of one tree (`Build.avoid`), so the unknowns are independent."""
    if isinstance(tree, Leaf):
        return tree.value(st)
    op, kids = tree[0], tree[1:]
    vals = [eval_tree(k, st) for k in kids]
    return _combine(op, vals)


def _combine(op: str, vals: list) -> bool | None:
    if op == "not":
        return None if vals[0] is None else not vals[0]
    if op == "and":
        if False in vals:
            return False
        return None if None in vals else True
    if op == "or":
        if True in vals:
            return True
        return None if None in vals else False
    if op == "implies":
        a, b = vals
        return _combine("or", [None if a is None else not a, b])
    if op == "xor":
        t, u = vals.count(True), vals.count(None)
        if t >= 2:
            return False
        if u:
            return None
        return t == 1
    raise ValueError(op)


def spec_of(tree) -> dict:
    if isinstance(tree, Leaf):
        return tree.spec
    return {"op": tree[0], "kids": [spec_of(k) for k in tree[1:]]}


def tree_leaves(tree) -> list[Leaf]:
    return [tree] if isinstance(tree, Leaf) else [x for k in tree[1:] for x in tree_leaves(k)]


def _sk_eval(sk, it) -> bool:
    if isinstance(sk, str):
        return next(it)
    return _combine(sk[0], [_sk_eval(k, it) for k in sk[1:]])


def patterns(sk, want: bool) -> list[tuple[tuple[bool, ...], float]]:
    """Every leaf-truth assignment giving `want`, weighted 1 when flipping some single
    leaf would change the answer, `P_NONCRITICAL` when none would."""
    n = len(leaves_of(sk))
    out = []
    for pat in itertools.product((False, True), repeat=n):
        if _sk_eval(sk, iter(pat)) is not want:
            continue
        crit = any(_sk_eval(sk, iter(pat[:i] + (not pat[i],) + pat[i + 1:])) is not want
                   for i in range(n))
        out.append((pat, 1.0 if crit else P_NONCRITICAL))
    return out


# ==== building leaves that have a given truth =========================================

def _rnd(integral: bool, x: float):
    return int(round(x)) if integral else round(x, 1)


def _gap(span: float, rng: random.Random) -> float:
    if rng.random() < P_TIGHT:
        return rng.uniform(0.005, 0.02) * span
    return rng.uniform(0.02, NEAR) * span


def _side(v, lo, hi, span, integral, below: bool, rng, min_gap: float = 0.0):
    """A constant strictly below (or above) `v`, inside [lo, hi], or None."""
    step = 1 if integral else 0.1
    d = max(_gap(span, rng), min_gap, step)
    room = (v - lo) if below else (hi - v)
    if room < max(step, min_gap):
        return None
    if d > room:
        d = rng.uniform(max(step, min_gap), room)
    c = _rnd(integral, v - d if below else v + d)
    if below and c >= v:
        c = _rnd(integral, v - step)
    if not below and c <= v:
        c = _rnd(integral, v + step)
    if c < lo - 1e-9 or c > hi + 1e-9:
        return None
    return c


def place(v, op, t, lo, hi, span, integral, rng, allow_eq=True, min_gap=0.0):
    """A constant `c` in [lo, hi] with `(v op c) is t`, or None. The side of `v` it sits
    on is fixed by (op, t); how far is drawn, so neither `c` nor `v` alone says which."""
    # which relations of c to v give the truth owed
    rel = {(">", True): "lt", (">", False): "ge", (">=", True): "le", (">=", False): "gt",
           ("<", True): "gt", ("<", False): "le", ("<=", True): "ge", ("<=", False): "lt",
           ("==", True): "eq", ("==", False): "ne", ("!=", True): "ne", ("!=", False): "eq"}
    r = rel[(op, t)]
    if r == "eq" or (r in ("le", "ge") and allow_eq and rng.random() < P_EQ):
        if r == "eq" and not allow_eq:
            return None
        c = _rnd(integral, v)
        return c if _cmp(v, op, c) is t else None
    if r == "ne":
        # equality ops live on small counts: a near miss, one or two either side
        c = v + rng.choice((-2, -1, 1, 2))
        return c if lo <= c <= hi and _cmp(v, op, c) is t else None
    below = r in ("lt", "le")
    c = _side(v, lo, hi, span, integral, below, rng, min_gap)
    if c is None or _cmp(v, op, c) is not t:
        return None
    return c


class Build:
    """Construction context for one example: which fields a tree has already used (a
    field is read by at most one leaf per tree, so evaluation stays exact) and which are
    frozen (read by an earlier tree of the same state, so nothing may change them)."""

    def __init__(self, st: State, rng: random.Random, frozen: set[str]):
        self.st, self.rng, self.frozen = st, rng, frozen
        self.avoid: set[str] = set()

    def pick(self, pool, mutate: bool = False, extra=lambda f: True):
        c = [f for f in pool if f.name not in self.avoid
             and not (mutate and f.name in self.frozen) and extra(f)]
        return self.rng.choice(c) if c else None


def _numops(f: Num) -> list[str]:
    ops = [">", "<", ">=", "<="]
    if f.integral and f.hi - f.lo <= 40:
        ops += ["==", "!="]
    return ops


def _vals(st: State, name: str) -> list:
    return [r[name] for r in st.recs]


def _count_const(vals, op, m, f: Num, rng) -> float | None:
    """A constant making exactly `m` of `vals` satisfy `v op c`."""
    n = len(vals)
    asc = sorted(vals)
    step = 1 if f.integral else 0.1
    span = f.hi - f.lo
    upward = op in (">", ">=")
    for _ in range(8):
        if m in (0, n):
            anchor = asc[-1] if (upward == (m == 0)) else asc[0]
            c = place(anchor, op, m == n, f.lo, f.hi, span, f.integral, rng, allow_eq=False)
        else:
            lo_v, hi_v = (asc[n - m - 1], asc[n - m]) if upward else (asc[m - 1], asc[m])
            if hi_v - lo_v < step - 1e-9:
                return None
            c = _rnd(f.integral, rng.uniform(lo_v, hi_v))
        # never a value some record holds: rounding an interior constant onto one only
        # happens when the count is strictly between 0 and n, so "the rule's number is in
        # the state" separated `none` from its negation (0.60)
        if (c is not None and sum(_cmp(v, op, c) for v in vals) == m
                and all(abs(v - c) > 1e-9 for v in vals)):
            return c
    return None


def _choose_m(q: str, k: int, n: int, t: bool, rng) -> int:
    """How many records satisfy the inner rule. Mostly one step from the boundary, so
    every record has to be read; never 0 or n where the answer does not force it, so the
    focus record can take the side `_focus_side` gives it."""
    near = rng.random() < 0.7
    if q == "all":
        return n if t else (n - 1 if near else rng.randint(1, n - 1))
    if q == "any":
        return (1 if near else rng.randint(1, n - 1)) if t else 0
    if q == "none":
        return 0 if t else (1 if near else rng.randint(1, n - 1))
    if t:
        return k if near or k >= n - 1 else rng.randint(k + 1, n - 1)
    return k - 1 if near or k <= 2 else rng.randint(1, k - 2)


def _focus_side(q: str, m: int, n: int, rng) -> bool:
    """Whether the focus record satisfies the inner rule, chosen so that it says nothing
    about the answer. The question names a record, and a reader who applies the inner
    rule to that record alone answered `all` / `any` / `none` / `atleast` 0.69-0.71 when
    the satisfying records were drawn at random. Where the answer forces the focus's
    side (every record satisfies an `all` that holds), it takes that side in every
    question of the kind; otherwise a coin (`atleast`)."""
    if m == 0:
        return False
    if m == n:
        return True
    if q == "all":
        return True
    if q in ("any", "none"):
        return False
    return rng.random() < 0.5


def _enum_fmt(vals) -> list:
    return sorted(vals)


def build_atom_focus(kind: str, t: bool, b: Build) -> Leaf | None:
    """A record-level primitive about the focus record, true iff `t`."""
    st, rng, cd = b.st, b.rng, b.st.cd
    rec = st.recs[st.focus]
    if kind == "cmp":
        f = b.pick(cd.meas)
        if f is None:
            return None
        op = rng.choice(_numops(f))
        c = place(rec[f.name], op, t, f.lo, f.hi, f.hi - f.lo, f.integral, rng)
        if c is None:
            return None
        return Leaf("cmp", {"k": "cmp", "f": f.name, "op": op, "c": c}, {f.name})
    if kind == "eq":
        e = b.pick(cd.enums)
        if e is None:
            return None
        op = rng.choice(("==", "!="))
        same = (op == "==") == t
        # The value named when it is NOT this record's is one another record holds, so
        # the value appears in the state either way: drawn from the whole enum, "the
        # value the rule names is nowhere in the state" answered `eq` with its op 0.73.
        others = [x for x in e.values if x != rec[e.name]]
        held = [x for x in others
                if any(r[e.name] == x for i, r in enumerate(st.recs) if i != st.focus)]
        v = rec[e.name] if same else rng.choice(held or others)
        return Leaf("eq", {"k": "eq", "f": e.name, "op": op, "v": v}, {e.name})
    if kind == "range":
        f = b.pick(cd.meas)
        if f is None:
            return None
        inside = rng.random() < 0.5
        lohi = _range_for(f, [rec[f.name]], int(t == inside), rng)
        if lohi is None:
            return None
        return Leaf("range", {"k": "range", "f": f.name, "lo": lohi[0], "hi": lohi[1],
                              "inside": inside}, {f.name})
    if kind == "member":
        e = b.pick(cd.enums, extra=lambda e: len(e.values) >= 3)
        if e is None:
            return None
        inside = rng.random() < 0.5
        k = rng.randint(2, len(e.values) - 1)
        others = [x for x in e.values if x != rec[e.name]]
        held = [x for x in others
                if any(r[e.name] == x for i, r in enumerate(st.recs) if i != st.focus)]
        # One anchor the state holds (this record's value, or a value another record
        # holds), then the rest from the same-sized pool either way: the other values
        # minus one held value. With the pool one held value richer when the set
        # contained this record's value, "most of the listed values are in the state"
        # read `member` with its direction 0.62.
        h = rng.choice(held or others)
        pool = [x for x in others if x != h]
        first = rec[e.name] if t == inside else h
        vals = [first] + rng.sample(pool, k - 1)
        return Leaf("member", {"k": "member", "f": e.name, "vals": _enum_fmt(vals),
                               "inside": inside}, {e.name})
    if kind == "fref":
        pairs = [(a, l) for a, l in cd.pairs if a not in b.avoid and l not in b.avoid
                 and l not in b.frozen]
        if not pairs:
            return None
        a, l = rng.choice(pairs)
        fa, fl = cd.num(a), cd.num(l)
        op = rng.choice((">", "<", ">=", "<="))
        c = place(rec[a], op, t, fl.lo, fl.hi, fl.hi - fl.lo, fl.integral, rng)
        if c is None:
            return None
        rec[l] = c
        return Leaf("fref", {"k": "fref", "a": a, "b": l, "op": op}, {a, l})
    if kind == "pref":
        f = b.pick(cd.meas, extra=lambda f: not any(
            f"policy:{bd}_{f.name}" in b.frozen | b.avoid for bd in ("max", "min")))
        if f is None:
            return None
        bound = rng.choice(("max", "min"))
        op = rng.choice((">", "<=") if bound == "max" else ("<", ">="))
        c = place(rec[f.name], op, t, f.lo, f.hi, f.hi - f.lo, f.integral, rng)
        if c is None:
            return None
        key = f"{bound}_{f.name}"
        st.policy[key] = c
        return Leaf("pref", {"k": "pref", "f": f.name, "key": key, "op": op},
                    {f.name, f"policy:{key}"})
    raise ValueError(kind)


def _range_for(f: Num, vals: list, m_inside: int, rng) -> tuple | None:
    """[lo, hi] holding exactly `m_inside` of `vals`, with no value on an edge.

    The band is placed anywhere in the field's range and kept if it holds the owed
    count, as `rules._leaf` learned to: built around the values instead (a window over
    them, or a gap between them), where the band sits said whether it held the value --
    "a band near the middle, and the rule says inside" answered `range` 0.66. The
    window construction below is only the fallback for counts the uniform draw rarely
    hits among clustered values."""
    step = 1 if f.integral else 0.1
    asc = sorted(vals)
    n = len(asc)
    span = f.hi - f.lo
    wlo = 0.10 if n == 1 else 0.03
    for _ in range(80):
        w = rng.uniform(wlo, 0.4) * span
        lo = _rnd(f.integral, rng.uniform(f.lo, f.hi - w))
        hi = _rnd(f.integral, lo + w)
        if hi <= lo or any(abs(v - lo) < step - 1e-9 or abs(v - hi) < step - 1e-9
                           for v in vals):
            continue
        if sum(lo <= v <= hi for v in vals) == m_inside:
            return lo, hi
    for _ in range(20):
        if m_inside == 0:
            gaps = [(f.lo - 0.0, asc[0])] + list(zip(asc, asc[1:])) + [(asc[-1], f.hi)]
            gaps = [(a, b) for a, b in gaps if b - a >= 3 * step]
            if not gaps:
                return None
            a, b = rng.choice(gaps)
            lo = _rnd(f.integral, rng.uniform(a + step, b - step))
            w = rng.uniform(0.05, 0.4) * span
            hi = _rnd(f.integral, min(lo + w, b - step))
            if hi < lo:
                continue
        else:
            i = rng.randint(0, n - m_inside)
            j = i + m_inside - 1
            left = asc[i - 1] if i > 0 else max(f.lo - 0.0, asc[0] - 0.4 * span)
            right = asc[j + 1] if j + 1 < n else min(f.hi, asc[-1] + 0.4 * span)
            if asc[i] - left < 2 * step and i > 0:
                continue
            if right - asc[j] < 2 * step and j + 1 < n:
                continue
            lo = _rnd(f.integral, rng.uniform(left + (step if i > 0 else 0), asc[i] - step))
            hi = _rnd(f.integral, rng.uniform(asc[j] + step, right - (step if j + 1 < n else 0)))
            if lo > asc[i] - step + 1e-9 or hi < asc[j] + step - 1e-9:
                continue
        inside = sum(lo <= v <= hi for v in vals)
        if inside == m_inside and lo < hi and all(abs(v - lo) >= step - 1e-9 and
                                                  abs(v - hi) >= step - 1e-9 for v in vals):
            return lo, hi
    return None


def build_quant(q: str, t: bool, b: Build) -> Leaf | None:
    st, rng, cd = b.st, b.rng, b.st.cd
    n = len(st.recs)
    k = rng.randint(2, n - 1) if q == "atleast" else 0
    m = _choose_m(q, k, n, t, rng)
    inner = rng.choice(RECORD_KINDS)
    extra = {"n": k} if q == "atleast" else {}
    fo = st.focus
    focus_in = _focus_side(q, m, n, rng)
    rest = [i for i in range(n) if i != fo]
    rng.shuffle(rest)
    chosen = set(rest[: m - 1]) | {fo} if focus_in else set(rest[:m])
    if inner in ("cmp", "pref"):
        f = b.pick(cd.meas, mutate=True, extra=(lambda f: True) if inner == "cmp" else (
            lambda f: not any(f"policy:{bd}_{f.name}" in b.frozen | b.avoid
                              for bd in ("max", "min"))))
        if f is None:
            return None
        if inner == "cmp":
            op = rng.choice((">", "<", ">=", "<="))
        else:
            bound = rng.choice(("max", "min"))
            op = rng.choice((">", "<=") if bound == "max" else ("<", ">="))
        c = _count_const(_vals(st, f.name), op, m, f, rng)
        if c is None:
            return None
        if inner == "cmp":
            phi = {"k": "cmp", "f": f.name, "op": op, "c": c}
            reads = {f.name}
        else:
            key = f"{bound}_{f.name}"
            st.policy[key] = c
            phi = {"k": "pref", "f": f.name, "key": key, "op": op}
            reads = {f.name, f"policy:{key}"}
    elif inner == "range":
        f = b.pick(cd.meas, mutate=True)
        if f is None:
            return None
        inside = rng.random() < 0.5
        lohi = _range_for(f, _vals(st, f.name), m if inside else n - m, rng)
        if lohi is None:
            return None
        phi = {"k": "range", "f": f.name, "lo": lohi[0], "hi": lohi[1], "inside": inside}
        reads = {f.name}
    elif inner in ("eq", "member"):
        e = b.pick(cd.enums, mutate=True,
                   extra=lambda e: len(e.values) >= (3 if inner == "member" else 2))
        if e is None:
            return None
        if inner == "eq":
            op = rng.choice(("==", "!="))
            v = rng.choice(e.values)
            yes_set, no_set = ([v], [x for x in e.values if x != v])
            if op == "!=":
                yes_set, no_set = no_set, yes_set
            phi = {"k": "eq", "f": e.name, "op": op, "v": v}
        else:
            inside = rng.random() < 0.5
            kk = rng.randint(2, len(e.values) - 1)
            s = sorted(rng.sample(list(e.values), kk))
            in_s, out_s = s, [x for x in e.values if x not in s]
            yes_set, no_set = (in_s, out_s) if inside else (out_s, in_s)
            phi = {"k": "member", "f": e.name, "vals": s, "inside": inside}
        for i, r in enumerate(st.recs):
            r[e.name] = rng.choice(yes_set if i in chosen else no_set)
        reads = {e.name}
    else:  # fref
        pairs = [(a, l) for a, l in cd.pairs if a not in b.avoid and l not in b.avoid
                 and l not in b.frozen]
        if not pairs:
            return None
        a, l = rng.choice(pairs)
        fl = cd.num(l)
        op = rng.choice((">", "<", ">=", "<="))
        for i, r in enumerate(st.recs):
            c = place(r[a], op, i in chosen, fl.lo, fl.hi, fl.hi - fl.lo, fl.integral, rng)
            if c is None:
                return None
            r[l] = c
        phi = {"k": "fref", "a": a, "b": l, "op": op}
        reads = {a, l}
    # a threshold or band decides which records satisfy by their values: move the focus
    # record to the side `_focus_side` chose by swapping its value with a record on the
    # other side (the count, and so the answer, is unchanged)
    if inner in ("cmp", "pref", "range"):
        fname = phi["f"]
        sat = [bool(_atom(phi, r, st.policy)) for r in st.recs]
        if sat[fo] != focus_in:
            swap = [i for i in range(n) if i != fo and sat[i] == focus_in]
            if not swap:
                return None
            j = rng.choice(swap)
            st.recs[fo][fname], st.recs[j][fname] = st.recs[j][fname], st.recs[fo][fname]
    return Leaf(q, {"k": q, "phi": phi, **extra}, reads)


def build_agg(t: bool, b: Build) -> Leaf | None:
    st, rng, cd = b.st, b.rng, b.st.cd
    n = len(st.recs)
    fn = rng.choice(AGG_FNS)
    op = rng.choice((">", "<", ">=", "<="))
    if fn == "count":
        e = b.pick(cd.enums, mutate=True)
        if e is None:
            return None
        v = rng.choice(e.values)
        cnt = rng.randint(0, n)
        idx = list(range(n))
        rng.shuffle(idx)
        for i, r in enumerate(st.recs):
            r[e.name] = v if i in idx[:cnt] else rng.choice([x for x in e.values if x != v])
        # a constant both answers are possible for, whatever the count: never ">= 0"
        lo, hi = {">": (0, n - 1), ">=": (1, n), "<": (1, n), "<=": (0, n - 1)}[op]
        c = place(cnt, op, t, lo, hi, n, True, rng)
        if c is None:
            return None
        return Leaf("agg", {"k": "agg", "fn": "count", "f": e.name, "v": v, "op": op,
                            "c": c}, {e.name})
    f = b.pick(cd.meas)
    if f is None:
        return None
    vals = _vals(st, f.name)
    span = f.hi - f.lo
    if fn == "sum":
        a = round(sum(vals), 6)
        lo, hi, sp, integral = f.lo * n, f.hi * n, span * n ** 0.5, f.integral
    elif fn == "mean":
        a = sum(vals) / n
        lo, hi, sp, integral = f.lo, f.hi, span, False
    else:
        a = min(vals) if fn == "min" else max(vals)
        lo, hi, sp, integral = f.lo, f.hi, span, f.integral
    exact = fn in ("min", "max")
    c = place(a, op, t, lo, hi, sp, integral, rng, allow_eq=exact,
              min_gap=0 if exact else max(0.015 * sp, 0.2))
    if c is None:
        return None
    return Leaf("agg", {"k": "agg", "fn": fn, "f": f.name, "op": op, "c": c}, {f.name})


def build_cross(t: bool, b: Build) -> Leaf | None:
    st, rng, cd = b.st, b.rng, b.st.cd
    n = len(st.recs)
    mode = rng.choice(CROSS_MODES)
    f = b.pick(cd.meas, mutate=True)
    if f is None:
        return None
    fo = st.focus
    if mode == "named":
        other = rng.choice([i for i in range(n) if i != fo])
        op = rng.choice((">", "<", ">=", "<="))
        c = place(st.recs[fo][f.name], op, t, f.lo, f.hi, f.hi - f.lo, f.integral, rng)
        if c is None:
            return None
        st.recs[other][f.name] = c
        return Leaf("cross", {"k": "cross", "mode": "named", "f": f.name,
                              "other": st.recs[other][cd.idf], "op": op}, {f.name})
    vals = _vals(st, f.name)
    if len(set(vals)) < n:
        return None                              # a tie makes rank and extreme ambiguous
    hi = rng.random() < 0.5
    order = sorted(range(n), key=lambda i: -vals[i] if hi else vals[i])   # rank 1 first
    if mode == "extreme":
        # a false case is mostly the runner-up, which is above the others' mean as the
        # leader is: "above average, so the highest" read `extreme` 0.64 otherwise
        r = 1 if t else (2 if rng.random() < 0.85 else rng.randint(2, n))
        spec = {"k": "cross", "mode": "extreme", "f": f.name, "hi": hi}
    else:
        k = rng.randint(2, n - 1)
        if t:
            r = k if rng.random() < 0.8 else rng.randint(1, k)
        else:
            r = k + 1 if rng.random() < 0.8 else rng.randint(k + 1, n)
        spec = {"k": "cross", "mode": "rank", "f": f.name, "hi": hi, "n": k}
    j = order[r - 1]
    st.recs[fo][f.name], st.recs[j][f.name] = st.recs[j][f.name], st.recs[fo][f.name]
    if mode == "rank":
        # likewise for a rank: "above the others' mean" is a coin, whatever the answer
        mine = st.recs[fo][f.name]
        others = [r[f.name] for i, r in enumerate(st.recs) if i != fo]
        if ((mine > sum(others) / len(others)) == hi) != (rng.random() < 0.5):
            return None
    if mode == "extreme" and not t:
        # the leader is always on the rule's side of the others' mean; so must the focus
        # be when it is not the leader, or "above average" reads the answer
        mine = st.recs[fo][f.name]
        others = [r[f.name] for i, r in enumerate(st.recs) if i != fo]
        if (mine > sum(others) / len(others)) != hi:
            return None
    return Leaf("cross", spec, {f.name})


def build_leaf(kind: str, t: bool, b: Build) -> Leaf | None:
    if kind in RECORD_KINDS:
        lf = build_atom_focus(kind, t, b)
    elif kind in QUANT_KINDS:
        lf = build_quant(kind, t, b)
    elif kind == "agg":
        lf = build_agg(t, b)
    else:
        lf = build_cross(t, b)
    if lf is None or lf.value(b.st) is not t:
        return None
    return lf


def _assemble(sk, it):
    if isinstance(sk, str):
        return next(it)
    return (sk[0], *[_assemble(k, it) for k in sk[1:]])


def build_tree(sk, want: bool, st: State, rng: random.Random, frozen: set[str]):
    """A tree of shape `sk` answering `want`, built leaf by leaf (see the module doc), or
    None. The state is left as the successful build set it, or as it was."""
    pats = patterns(sk, want)
    if not pats:
        return None
    kinds = leaves_of(sk)
    for _ in range(TRIES):
        pat = rng.choices([p for p, _ in pats], weights=[w for _, w in pats])[0]
        snap = st.snapshot()
        b = Build(st, rng, frozen)
        leaves = []
        for kind, t in zip(kinds, pat):
            lf = None
            for _ in range(6):
                lf = build_leaf(kind, t, b)
                if lf is not None:
                    break
            if lf is None:
                break
            b.avoid |= lf.reads
            leaves.append(lf)
        else:
            tree = _assemble(sk, iter(leaves))
            # later leaves may only touch fields no earlier leaf reads, so every leaf
            # still has its truth; checked rather than trusted
            if (all(lf.value(st) is t for lf, t in zip(leaves, pat))
                    and eval_tree(tree, st) is want):
                return tree
        st.restore(snap)
    return None


# ==== records =========================================================================

def make_state(cd: CDomain, rng: random.Random, n: int) -> State:
    """`n` records of one domain. Every measured number is drawn around a centre shared
    by the state, so where a value ranks among the records says nothing about where it
    sits in its range; every limit is drawn near its own reading, either side."""
    recs = [make_record(cd.dom, rng) for _ in range(n)]
    for f in cd.meas:
        span = f.hi - f.lo
        c = rng.uniform(f.lo + CLUSTER * span, f.hi - CLUSTER * span)
        for r in recs:
            r[f.name] = _rnd(f.integral, min(f.hi, max(f.lo, c + rng.uniform(-CLUSTER, CLUSTER) * span)))
    for a, l in cd.pairs:
        fl = cd.num(l)
        for r in recs:
            v = _side(r[a], fl.lo, fl.hi, fl.hi - fl.lo, fl.integral, rng.random() < 0.5, rng)
            for below in (True, False):
                if v is None:
                    v = _side(r[a], fl.lo, fl.hi, fl.hi - fl.lo, fl.integral, below, rng)
            if v is not None:
                r[l] = v
    seen = set()
    for r in recs:
        while r[cd.idf] in seen:
            r[cd.idf] = _ref(rng)
        seen.add(r[cd.idf])
        for it in cd.dom.items:
            if not r[it.name] and rng.random() < 0.5:
                r[it.name] = sorted(rng.sample(it.pool, rng.randint(1, min(it.hi, len(it.pool)))))
    pname = rng.choice(("policy", "limits", "thresholds", "rulebook"))
    return State(cd, recs, rng.randrange(n), {}, pname)


def _policy_distractors(st: State, rng: random.Random, k: int, exclude: set[str]) -> None:
    """Settings no rule reads. Never for a field a rule reads, and never re-adding a
    setting an abstention removed."""
    free = [f for f in st.cd.meas if f.name not in exclude
            and f"max_{f.name}" not in st.policy and f"min_{f.name}" not in st.policy]
    for f in rng.sample(free, min(k, len(free))):
        vals = _vals(st, f.name) if all(f.name in r for r in st.recs) else [f.lo, f.hi]
        mid = sum(vals) / len(vals)
        v = mid + rng.uniform(-0.25, 0.25) * (f.hi - f.lo)
        st.policy[f"{rng.choice(('max', 'min'))}_{f.name}"] = _rnd(
            f.integral, min(f.hi, max(f.lo, v)))


# ==== rendering the state =============================================================

def _cell(v) -> str:
    if isinstance(v, list):
        return ", ".join(v) if v else "none"
    return str(v)


def _plabel(cd: CDomain, key: str) -> str:
    bound, name = key.split("_", 1)
    f = cd.num(name)
    return f"{'maximum' if bound == 'max' else 'minimum'} {_label(f.name, f.label)}"


def render_state(st: State, fmt: str) -> str:
    cd = st.cd
    obj = st.as_obj()
    if fmt == "json":
        return json.dumps(obj, indent=2, ensure_ascii=False)
    if fmt == "yaml":
        # block style or one flow mapping per record, drawn from the state itself so the
        # render stays a function of the state
        flow = None if int(hashlib.md5(st.fid.encode()).hexdigest(), 16) % 2 else False
        return yaml.safe_dump(obj, sort_keys=False, allow_unicode=True,
                              default_flow_style=flow, width=1000).rstrip()
    if fmt == "paths":
        return flatten_paths(obj)
    keys = list(st.recs[0])
    pol = list(st.policy.items())
    if fmt == "prose":
        out = [f"There are {len(st.recs)} {cd.plural} in this batch."]
        out += [as_prose(cd.dom, r) for r in st.recs]
        if pol:
            parts = []
            for k, v in pol:
                unit = cd.num(k.split("_", 1)[1]).unit
                parts.append(f"a {_plabel(cd, k)} of {v}{unit}")
            out.append(f"The {st.pname} record sets " + "; ".join(parts) + ".")
        return "\n\n".join(out)
    if fmt == "table":
        lines = ["| " + " | ".join(keys) + " |", "|" + "---|" * len(keys)]
        lines += ["| " + " | ".join(_cell(r[k]) for k in keys) + " |" for r in st.recs]
        text = f"{cd.coll}:\n\n" + "\n".join(lines)
        if pol:
            text += (f"\n\n{st.pname}:\n\n| setting | value |\n|---|---|\n" +
                     "\n".join(f"| {k} | {v} |" for k, v in pol))
        return text
    if fmt == "csv":
        buf = io.StringIO()
        w = csv.writer(buf, lineterminator="\n")
        w.writerow(keys)
        for r in st.recs:
            w.writerow([";".join(r[k]) if isinstance(r[k], list) else r[k] for k in keys])
        text = f"# {cd.coll}\n" + buf.getvalue().rstrip()
        if pol:
            buf = io.StringIO()
            w = csv.writer(buf, lineterminator="\n")
            w.writerow(["setting", "value"])
            w.writerows(pol)
            text += f"\n\n# {st.pname}\n" + buf.getvalue().rstrip()
        return text
    if fmt == "kv":
        blocks = []
        for i, r in enumerate(st.recs, 1):
            blocks.append(f"[{cd.noun} {i}]\n" + "\n".join(f"{k}: {_cell(v)}" for k, v in r.items()))
        if pol:
            blocks.append(f"[{st.pname}]\n" + "\n".join(f"{k}: {v}" for k, v in pol))
        return "\n\n".join(blocks)
    raise ValueError(fmt)


# ==== rendering the rule ==============================================================

class Renderer:
    """Everything a rule's wording depends on, for one question.

    `heldout` is None in training (held-out templates are never drawn), True for a
    dev/test question worded with held-out templates wherever a bank has them, False for
    one worded with trained templates only. The field-reference templates are drawn once
    per question, so one rule names its fields one way."""

    def __init__(self, st: State, fmt: str, mode: str, rng: random.Random,
                 heldout: bool | None):
        self.st, self.cd, self.rng = st, st.cd, rng
        self.shape = "label" if fmt == "prose" else "key"
        self.mode, self.heldout = mode, heldout
        self.fixed: dict[str, str] = {}
        self.used_heldout = False

    def pick(self, bank: str, numeric: bool = True, fixed: bool = False) -> str:
        if fixed and bank in self.fixed:
            return self.fixed[bank]
        tpls = [t for t in BANKS[bank] if numeric or not t.startswith("#")]
        held = HELDOUT_TEMPLATES[bank]
        seen = [t for t in tpls if t not in held]
        new = [t for t in tpls if t in held]
        pool = new if (self.heldout and new) else seen
        t = self.rng.choice(pool)
        if t in held:
            self.used_heldout = True
        t = t.lstrip("#")
        if fixed:
            self.fixed[bank] = t
        return t

    # -- names ------------------------------------------------------------------------
    def ref(self, name: str, bare: bool = False) -> str:
        """How the rule names a field. `bare` is the form that follows a determiner
        ("the average `transit_days`", not "the average the `transit_days` field")."""
        f = next(x for x in self.cd.dom.fields if x.name == name)
        if self.mode == "indirect" and getattr(f, "gloss", ""):
            unit = getattr(f, "unit", "").strip()
            t = self.pick("ref_ind_bare" if bare else "ref_ind", fixed=True)
            # the unit, which also keeps "how heavy the shipment is is greater" apart
            return t.format(gloss=f.gloss) + (f" (in {unit})" if unit else "")
        if self.shape == "key":
            return f"`{f.name}`" if bare else self.pick("ref_key", fixed=True).format(key=f.name)
        lab = _label(f.name, getattr(f, "label", ""))
        return lab if bare else self.pick("ref_label", fixed=True).format(label=lab)

    def const(self, name: str, v) -> str:
        f = next(x for x in self.cd.dom.fields if x.name == name)
        return f"{v}{getattr(f, 'unit', '')}"

    def self_(self) -> str:
        return self.pick("self", fixed=True).format(noun=self.cd.noun, fid=self.st.fid)

    def cmp(self, x: str, op: str, c: str, numeric: bool = True) -> str:
        return self.pick(OP_BANK[op], numeric).format(x=x, c=c)

    def set_(self, vals) -> str:
        t = self.pick("set_fmt")
        vals = list(vals)
        return t.format(a=", ".join(vals[:-1]), b=vals[-1], l=", ".join(vals))

    # -- leaves -----------------------------------------------------------------------
    def atom(self, s: dict, pol: bool) -> str:
        k = s["k"]
        if k == "cmp":
            op = s["op"] if pol else NEG_OP[s["op"]]
            return self.cmp(self.ref(s["f"]), op, self.const(s["f"], s["c"]))
        if k == "eq":
            op = s["op"] if pol else NEG_OP[s["op"]]
            return self.pick("eq_enum" if op == "==" else "ne_enum").format(
                x=self.ref(s["f"]), c=s["v"])
        if k == "range":
            inside = s["inside"] == pol
            return self.pick("range_in" if inside else "range_out").format(
                x=self.ref(s["f"]), lo=self.const(s["f"], s["lo"]),
                hi=self.const(s["f"], s["hi"]))
        if k == "member":
            inside = s["inside"] == pol
            return self.pick("set_in" if inside else "set_out").format(
                x=self.ref(s["f"]), s=self.set_(s["vals"]))
        if k == "fref":
            op = s["op"] if pol else NEG_OP[s["op"]]
            other = self.pick("same_rec").format(x=self.ref(s["b"]))
            return self.cmp(self.ref(s["a"]), op, other, numeric=False)
        if k == "pref":
            op = s["op"] if pol else NEG_OP[s["op"]]
            bound = "maximum" if s["key"].startswith("max_") else "minimum"
            if self.mode == "indirect":
                c = self.pick("pref_ind").format(bound=bound, P=self.st.pname)
            elif self.shape == "key":
                c = self.pick("pref_key").format(pkey=s["key"], P=self.st.pname)
            else:
                c = self.pick("pref_label").format(plabel=_plabel(self.cd, s["key"]),
                                                   P=self.st.pname)
            return self.cmp(self.ref(s["f"]), op, c, numeric=False)
        raise ValueError(k)

    def leaf(self, s: dict, pol: bool) -> str:
        k, cd = s["k"], self.cd
        common = {"noun": cd.noun, "plural": cd.plural}
        if k in RECORD_KINDS:
            return self.atom(s, pol)
        if k in QUANT_KINDS:
            # the negation of a quantifier is its dual: not all = some fail, not any =
            # none, not none = some, not at-least-k = fewer-than-k
            if k == "all":
                bank, inner = ("all", True) if pol else ("any", False)
            elif k == "any":
                bank, inner = ("any", True) if pol else ("none", True)
            elif k == "none":
                bank, inner = ("none", True) if pol else ("any", True)
            else:
                bank, inner = ("atleast" if pol else "fewer"), True
            n = s.get("n", 1)
            return self.pick(bank).format(p=self.atom(s["phi"], inner), k=n, km1=n - 1,
                                          **common)
        if k == "agg":
            op = s["op"] if pol else NEG_OP[s["op"]]
            if s["fn"] == "count":
                x = self.pick("agg_count").format(x=self.ref(s["f"]), v=s["v"], **common)
                return self.cmp(x, op, str(s["c"]))
            x = self.pick(f"agg_{s['fn']}").format(x=self.ref(s["f"]),
                                                    xb=self.ref(s["f"], bare=True), **common)
            return self.cmp(x, op, self.const(s["f"], s["c"]))
        if k == "cross":
            x = self.ref(s["f"])
            if s["mode"] == "named":
                op = s["op"] if pol else NEG_OP[s["op"]]
                c = self.pick("cross_obj").format(noun=cd.noun, oid=s["other"])
                return self.cmp(x, op, c, numeric=False)
            hl = "hi" if s["hi"] else "lo"
            bank = ("ext_" if s["mode"] == "extreme" else "rank_") + hl + ("" if pol else "_neg")
            n = s.get("n", 1)
            return self.pick(bank).format(self=self.self_(), x=x, xb=self.ref(s["f"], bare=True),
                                          k=n, km1=n - 1, **common)
        raise ValueError(k)

    # -- trees ------------------------------------------------------------------------
    def _items(self, texts: list[str], level: int) -> str:
        mk = MARKERS[min(level, len(MARKERS) - 1)]
        return "; ".join(f"{mk(i)} {t}" for i, t in enumerate(texts))

    def _wrap(self, tree, text: str) -> str:
        # a quantifier carries a clause of its own ("some build job satisfies this: A"),
        # so under a connective it is bracketed too, or "..., together with B" reads as
        # part of the quantified clause
        if isinstance(tree, Leaf) and tree.kind not in QUANT_KINDS:
            return text
        return f"[{text}]"

    def _nary(self, op: str, kids_text: list[str], kids, level: int) -> str:
        wrapped = [self._wrap(k, t) for k, t in zip(kids, kids_text)]
        if len(wrapped) == 2:
            t = self.pick(f"{op}2")
            if "{items}" in t:
                return t.format(items=self._items(wrapped, level))
            # "`mount` is duct or wall or [...]": a leaf with its own and/or, joined by
            # a bare and/or, is bracketed like a subtree
            wrapped = [f"[{w}]" if not w.startswith("[") and
                       re.search(r"\b(and|or)\b", w) else w for w in wrapped]
            return t.format(a=wrapped[0], b=wrapped[1])
        return self.pick(f"{op}n").format(items=self._items(wrapped, level))

    def rule(self, tree, level: int = 0) -> str:
        if isinstance(tree, Leaf):
            return self.leaf(tree.spec, True)
        op, kids = tree[0], list(tree[1:])
        if op == "not":
            return self.pick("not").format(a=self._wrap(kids[0], self.rule(kids[0], level + 1)))
        if op == "implies":
            a, b = (self._wrap(k, self.rule(k, level + 1)) for k in kids)
            return self.pick("implies").format(a=a, b=b)
        texts = [self.rule(k, level + 1) for k in kids]
        return self._nary(op, texts, kids, level)

    def negation(self, tree, level: int = 0) -> str:
        """The rule's complement pushed down to the leaves (De Morgan), so the `no`
        description is a rule in its own right rather than the `yes` one with a prefix."""
        if isinstance(tree, Leaf):
            return self.leaf(tree.spec, False)
        op, kids = tree[0], list(tree[1:])
        if op == "not":
            return self.rule(kids[0], level)
        if op in ("and", "or"):
            dual = "or" if op == "and" else "and"
            texts = [self.negation(k, level + 1) for k in kids]
            return self._nary(dual, texts, kids, level)
        if op == "implies":
            a = self._wrap(kids[0], self.rule(kids[0], level + 1))
            nb = self._wrap(kids[1], self.negation(kids[1], level + 1))
            t = self.pick("and2")
            return t.format(items=self._items([a, nb], level)) if "{items}" in t \
                else t.format(a=a, b=nb)
        wrapped = [self._wrap(k, self.rule(k, level + 1)) for k in kids]   # xor
        return self.pick("xor_neg").format(items=self._items(wrapped, level))

    def negated_rule(self, tree) -> str:
        if isinstance(tree, Leaf) or self.rng.random() < 0.5:
            return self.negation(tree)
        return self.pick("neg_wrap").format(a=f"[{self.rule(tree)}]")


def _sentence(text: str) -> str:
    text = text.strip()
    if text[:1].isalpha():
        text = text[0].upper() + text[1:]
    return text if text.endswith(".") else text + "."


