def _heldout_templates() -> dict[str, frozenset[str]]:
    """A quarter of each bank (rounded, at least one where a bank has three or more),
    chosen by a hash of the template so the choice never moves when a bank grows
    elsewhere. Never drawn in training."""
    out = {}
    for name, tpls in BANKS.items():
        k = max(1, round(len(tpls) / 4)) if len(tpls) >= 3 else 0
        ranked = sorted(tpls, key=lambda t: hashlib.sha256(f"{name}|{t}".encode()).digest())
        out[name] = frozenset(ranked[:k])
    return out


