def _extend(d: Domain) -> CDomain:
    plural, coll, extra = _EXTRA[d.name]
    nums = d.nums + tuple(f for f, _ in extra)
    pairs = tuple((a, b) for a, b, _ in d.pairs) + tuple((a, f.name) for f, a in extra)
    return CDomain(replace(d, nums=nums), plural, coll, pairs)


