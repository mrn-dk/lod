def task_plans() -> list[tuple[str, Plan, str]]:
    """(task name, plan, family). Train: one task per (depth 1-3, format). Dev and test:
    one task per depth bucket (2-3, 4), formats mixed. With equal per-task quotas that is
    21 : 2 : 2, the 30k / 3k / 3k the row is sized for."""
    out = []
    for d in (1, 2, 3):
        for fmt in FORMATS:
            out.append((f"compose_train_d{d}_{fmt}", Plan("train", (d,), (fmt,), "train"),
                        f"compose_train_d{d}"))
    for split, tag in (("devreal", "dev"), ("testreal", "test")):
        for bucket, depths in (("d23", (2, 3)), ("d4", (4,))):
            out.append((f"compose_{tag}_{bucket}", Plan(split, depths, FORMATS, "eval"),
                        f"compose_{split}_{bucket}"))
    return out


def tasks() -> list[RealTask]:
    out = []
    for name, plan, family in task_plans():
        out.append(RealTask(
            row=ROW, name=name, licence=LICENCE, url=URL,
            load=Loader(name, plan, 0), soft=True, real=False,
            per_example_options=True, force_split=plan.split, family=family,
            notes=(f"compositional rules, split {plan.split}, depth {plan.depths}, "
                   f"formats {','.join(plan.formats)}; code-labelled")))
    return out


