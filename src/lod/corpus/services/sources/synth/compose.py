@dataclass
class Plan:
    split: str
    depths: tuple[int, ...]
    formats: tuple[str, ...]
    sentinel_split: str      # which half of the sentinel wording space to draw from


TRACE: list | None = None     # set to a list to capture (question, state, trees) triples


def _drop_for_abstain(st: State, tree, others: set[str], rng: random.Random) -> str | None:
    """Remove one field the tree reads -- from every record, or the policy key -- such
    that the tree's answer is no longer determined. None (and nothing removed) when no
    field can go without deciding the rule anyway."""
    # sorted: `reads` is a set of strings, whose order follows PYTHONHASHSEED, and the
    # corpus must be the same from one process to the next
    cands = [r for lf in tree_leaves(tree) for r in sorted(lf.reads) if r not in others]
    rng.shuffle(cands)
    for name in cands:
        snap = st.snapshot()
        if name.startswith("policy:"):
            st.policy.pop(name.split(":", 1)[1], None)
        else:
            for r in st.recs:
                r.pop(name, None)
        if name != st.cd.idf and eval_tree(tree, st) is None:
            return name
        st.restore(snap)
    return None


def _meta_tree(tree, sk) -> dict:
    lv = tree_leaves(tree)
    return {"sig": sig_of(sk), "depth": depth_of(sk), "leaves": len(lv),
            "kinds": [lf.kind for lf in lv],
            "inner": [lf.spec["phi"]["k"] for lf in lv if lf.kind in QUANT_KINDS],
            "ops": sorted(set(ops_of(sk))), "tree": spec_of(tree)}


class Loader:
    def __init__(self, name: str, plan: Plan, seed: int):
        self.name, self.plan, self.seed = name, plan, seed

    def __call__(self, n: int) -> Iterator[Example]:
        h = hashlib.sha256(f"{self.seed}:{self.name}".encode()).digest()
        rng = random.Random(int.from_bytes(h[:8], "big"))
        bal = [0, 0]
        made = 0
        i = 0
        while made < n:
            cd = CDOMAINS[i % len(CDOMAINS)]
            i += 1
            if i > 20 * n + 100:
                raise RuntimeError(f"{self.name}: {made} of {n} examples after {i} draws")
            ex = self.example(cd, rng, bal)
            if ex is not None:
                made += 1
                yield ex

    def example(self, cd: CDomain, rng: random.Random, bal: list[int]) -> Example | None:
        plan = self.plan
        fmt = rng.choice(plan.formats)
        st = make_state(cd, rng, rng.randint(*N_RECORDS))
        mode = "indirect" if rng.random() < P_INDIRECT else "direct"
        frozen: set[str] = set()
        built = []                    # (kind, payload) per question
        n_q = 2 if rng.random() < P_SECOND else 1
        eff = list(bal)
        for qi in range(n_q):
            depth = rng.choice(plan.depths)
            if rng.random() < P_ROUTE:
                got = self._route(st, rng, frozen, depth)
            else:
                got = self._noul(st, rng, frozen, depth, eff)
            if got is None:
                if qi == 0:
                    return None
                break
            built.append(got)
        # abstention: at most one question per example loses a field it needs
        reads_by_q = [set().union(*[lf.reads for t in trees for lf in tree_leaves(t)])
                      for _, _, trees, *_ in built]
        for qi, b in enumerate(built):
            if b[0] == "noul" and b[3]["sentinel"] and b[3]["abstain_wanted"]:
                others = set().union(*[r for j, r in enumerate(reads_by_q) if j != qi]) \
                    if len(reads_by_q) > 1 else set()
                dropped = _drop_for_abstain(st, b[2][0], others, rng)
                b[3]["abstain"] = dropped
                break
            if b[0] == "route" and b[3]["sentinel"] and b[3]["abstain_wanted"]:
                others = set().union(*[r for j, r in enumerate(reads_by_q) if j != qi]) \
                    if len(reads_by_q) > 1 else set()
                gold_tree = b[2][b[3]["gold"]]
                others |= set().union(*[lf.reads for j, t in enumerate(b[2])
                                        if j != b[3]["gold"] for lf in tree_leaves(t)])
                dropped = _drop_for_abstain(st, gold_tree, others, rng)
                b[3]["abstain"] = dropped
                break
        # policy record: where a rule reads it, plus distractor settings; sometimes present
        # when nothing reads it, so its presence says nothing about the rule
        read_all = set().union(*reads_by_q)
        if st.policy or rng.random() < P_POLICY_DISTRACTOR:
            _policy_distractors(st, rng, rng.randint(1, 3), read_all)
        for f in cd.dom.fields:
            if f.name != cd.idf and f.name not in read_all and rng.random() < P_DROP_DISTRACTOR:
                for r in st.recs:
                    r.pop(f.name, None)
        # every question re-evaluated on the final state: nothing after its build may
        # have moved its answer
        qs = []
        for qi, b in enumerate(built):
            q = self._question(qi, b, st, fmt, mode, rng)
            if q is None:
                return None
            qs.append(q)
        for b in built:
            if b[0] == "noul" and not b[3].get("abstain"):
                bal[int(b[3]["want"])] += 1
        ex = Example(state=render_state(st, fmt), questions=qs, task=self.name)
        if TRACE is not None:
            for q, b in zip(qs, built):
                TRACE.append((q, copy.deepcopy(st), b[2], fmt, mode))
        return ex

    # -- builders ---------------------------------------------------------------------
    def _noul(self, st, rng, frozen, depth, eff):
        want = eff[1] < eff[0] if eff[0] != eff[1] else rng.random() < 0.5
        for _ in range(8):
            sk = skeleton_for(rng, self.plan.split, depth)
            tree = build_tree(sk, want, st, rng, frozen)
            if tree is not None:
                frozen |= set().union(*[lf.reads for lf in tree_leaves(tree)])
                sent = rng.random() < P_NOUL_SENTINEL
                eff[int(want)] += 1       # an earlier question of this example counts too
                info = {"want": want, "sentinel": sent,
                        "abstain_wanted": sent and rng.random() < P_NOUL_ABSTAIN}
                return ("noul", [sk], [tree], info)
        return None

    def _route(self, st, rng, frozen, depth):
        form = rng.choices([f for f, _ in ROUTE_FORMS], weights=[w for _, w in ROUTE_FORMS])[0]
        sent = form == "sentinel"
        if form == "two":
            k = 2
        elif form == "plain":
            k = 3
        else:
            k = 2            # + the sentinel: three options, as every plain one has
        right = sent and rng.random() < P_ROUTE_SENT_RIGHT
        none_apply = right and rng.random() < P_NONE_APPLY
        abstain_wanted = right and not none_apply
        gold = None if none_apply else rng.randrange(k)
        sks, trees = [], []
        local = set(frozen)
        snap = st.snapshot()
        for j in range(k):
            d = depth if j == 0 else rng.randint(max(1, depth - 1), depth)
            if self.plan.split != "train" and d == 1:
                d = depth
            tree = None
            for _ in range(8):
                sk = skeleton_for(rng, self.plan.split, d, ROUTE_MAX_LEAVES)
                tree = build_tree(sk, j == gold, st, rng, local)
                if tree is not None:
                    break
            if tree is None:
                st.restore(snap)
                return None
            local |= set().union(*[lf.reads for lf in tree_leaves(tree)])
            sks.append(sk)
            trees.append(tree)
        frozen |= local
        info = {"gold": gold, "sentinel": sent, "abstain_wanted": abstain_wanted,
                "none_apply": none_apply, "k": k}
        return ("route", sks, trees, info)

    # -- questions --------------------------------------------------------------------
    def _question(self, qi, b, st, fmt, mode, rng) -> Question | None:
        kind, sks, trees, info = b
        heldout = None if self.plan.split == "train" else rng.random() < 0.5
        R = Renderer(st, fmt, mode, rng, heldout)
        cd = st.cd
        meta_common = {"format": fmt, "mode": mode, "split": self.plan.split,
                       "focus": st.fid, "coll": cd.coll, "policy": st.pname,
                       "domain": cd.dom.name, "qshape": kind}
        skey = sdesc = None
        if info["sentinel"]:
            skey, sdesc = sentinel.sample(rng, self.plan.sentinel_split)
        if kind == "noul":
            tree, sk = trees[0], sks[0]
            val = eval_tree(tree, st)
            abstain = bool(info.get("abstain"))
            if abstain != (val is None) or (not abstain and val is not info["want"]):
                return None
            opts = ["no", "yes"]
            desc = [_sentence(R.negated_rule(tree)), _sentence(R.rule(tree))]
            target = [0.0, 0.0] if abstain else [float(not val), float(val)]
            text = R.pick("q_noul").format(noun=cd.noun, fid=st.fid)
            meta = {**meta_common, **_meta_tree(tree, sk)}
            if skey is not None:
                pos = rng.randrange(3)
                opts.insert(pos, skey)
                desc.insert(pos, sdesc)
                target.insert(pos, 1.0 if abstain else 0.0)
                meta["sentinel"] = pos
            if abstain:
                meta.update(abstain=True, reason="field_not_in_state",
                            missing=info["abstain"])
            meta["tpl"] = "train" if heldout is None else ("heldout" if R.used_heldout else "seen")
            return Question(f"q{qi}", text, opts, target, meta, None, desc)
        # routing
        k = info["k"]
        vals = [eval_tree(t, st) for t in trees]
        gold = info["gold"]
        abstain = bool(info.get("abstain"))
        if abstain:
            if vals[gold] is not None or any(v is not False for j, v in enumerate(vals)
                                             if j != gold):
                return None
        elif gold is None:
            if any(v is not False for v in vals):
                return None
        elif vals[gold] is not True or any(v is not False for j, v in enumerate(vals)
                                           if j != gold):
            return None
        keys = rng.sample(ACTIONS, k)
        keys_by_tree = list(keys)
        desc = [_sentence(R.pick("route_desc").format(r=R.rule(t)).rstrip(".")) for t in trees]
        target = [1.0 if (j == gold and not abstain) else 0.0 for j in range(k)]
        sigs = [sig_of(s) for s in sks]
        meta = {**meta_common, "sigs": sigs, "depths": [depth_of(s) for s in sks],
                "depth": max(depth_of(s) for s in sks),
                "sig": sigs[gold] if gold is not None else sigs[0],
                "kinds": [lf.kind for t in trees for lf in tree_leaves(t)],
                "inner": [lf.spec["phi"]["k"] for t in trees for lf in tree_leaves(t)
                          if lf.kind in QUANT_KINDS],
                "ops": sorted({o for s in sks for o in ops_of(s)}),
                "trees": [spec_of(t) for t in trees], "leaves": sum(len(tree_leaves(t)) for t in trees)}
        if skey is not None:
            pos = rng.randrange(k + 1)
            keys.insert(pos, skey)
            desc.insert(pos, sdesc)
            target.insert(pos, 1.0 if (abstain or gold is None) else 0.0)
            meta["sentinel"] = pos
            meta["trees"].insert(pos, None)
            if gold is None:
                meta["none_apply"] = True
        if abstain:
            meta.update(abstain=True, reason="field_not_in_state", missing=info["abstain"],
                        undecided=keys.index(keys_by_tree[gold]))
        meta["tpl"] = "train" if heldout is None else ("heldout" if R.used_heldout else "seen")
        text = R.pick("q_route").format(noun=cd.noun, fid=st.fid)
        return Question(f"q{qi}", text, keys, target, meta, None, desc)


