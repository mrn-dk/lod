def _resolution(p: Plant) -> float:
    return 1.0 if p.integral or p.step >= 1.0 else 0.1


def vary(p: Plant, rng: random.Random) -> Plant:
    """This example's band and critical limit: the plant's own, moved a little.

    The domain calls for "band, limit and horizon vary per example", and before the
    domain-15 audit only the horizon and the run length did -- every jacket loop in the
    corpus had the band 58 to 72 C and the limit 95 C, so for the five trained plants the
    numbers the instructions state were decoration a model could memorise per plant and
    never read. Each edge moves by up to 12 % of the band width and the limit by up to 20 %
    of its distance from the dangerous edge, rounded to the resolution the plant prints at.
    That is small enough that every installation in `FRAMINGS` still genuinely runs there
    and that the ordering `rmin < lo < hi < crit < rmax` (mirrored for a low-side plant)
    cannot break, which the domain-15 audit asserted over a sample.
    """
    res = _resolution(p)
    band = p.hi - p.lo
    gap = (p.crit - p.hi) if p.direction == "high" else (p.lo - p.crit)

    def snap(v: float) -> float:
        return round(round(v / res) * res, 6)

    lo = snap(p.lo + rng.uniform(-0.12, 0.12) * band)
    hi = snap(p.hi + rng.uniform(-0.12, 0.12) * band)
    crit = snap(p.crit + rng.uniform(-0.2, 0.2) * gap)
    return replace(p, lo=lo, hi=hi, crit=crit)


