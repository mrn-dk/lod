"""Row 37 -- Control and sensor (domain 15).

Every other domain in this corpus answers from a snapshot. Row 1 reads a document and
names its class; row 33 reads a record and applies a rule to it; row 36 reads a page and
picks a control. In all of them the state at the moment of the question determines the
answer, and a model that learns "this reading means this label" is right.

Here it is not. **The same reading implies a different action depending on trend and
recent history.** A jacket at 78 C that is falling back toward its band is watched; the
same 78 C rising, in its second reading outside the band, gets a setpoint correction; the
same 78 C rising in its sixth gets an engineer; and a jacket at 68 C -- comfortably
*inside* its band -- gets shut down if it has gained 6 C a reading for the last three and
the critical limit is five readings away. If a reading of 78 always meant the same thing
this would be another label-recovery task and the domain would be worth nothing, so the
generator is built to make history load-bearing and `tests/test_sensors_source.py`
measures that it is: the last reading alone, given an oracle over its position in the
band, predicts the action barely better than the majority class, while the series
predicts it exactly.

**What code does and what the model does.** Code simulates the plant, computes the rate
of change, the consecutive-readings-outside count and the latched-alarm state, and
evaluates the policy. The LLM contributed the `FRAMINGS` table below -- device names,
sites, measurement nouns and unit surface forms -- and nothing else. It never sees a
series and never produces a target, and any framing that failed the validator in
the one-off generation script was dropped rather than repaired.

**Three renderings of one simulation.** `json` (a reading object), `log` (an operator's
prose log) and `table` (a series table). Same values, same question, same answer, so the
shape is a change of surface and not a harder task about parsing.

**What is held out, and why it is a structure rather than a sample.** Two families, each
paired against a trained one so the transfer question is sharp:

    plant      two plant types never simulated in training (`dryer_humidity`,
               `bearing_vibration`), built from the same direction / integrality /
               band-shape primitives as the five trained plants
    trend      `oscillating`, whose segments are `rise` and `fall` -- both trained, in
               `ramp_up` and `ramp_down` -- but whose composition is not

`sensor_action_trained_eval` is the control: trained plants and trained trends, in
`testreal`, unseen instances. A drop from it to `sensor_action_heldout_*` is a failure to
generalise over structure and not a failure on unseen vocabulary.

**Dev holds out structures of its own.** `devreal` selects checkpoints and fits the
temperature, so it has to be as novel as `testreal` -- a dev split of trained plants
measures recall and under-corrects T. It gets its own pair of held-out families, built
the same way and disjoint from the test pair, so selecting on them never touches a
structure the test split reads:

    plant      `tank_level` (low-side, like `cell_soc`) and `motor_current` (high-side,
               like `jacket_temp`) -- `DEV_PLANTS`
    trend      `plateau`, a `rise` that levels off into `flat`; both segments trained,
               the composition not -- `DEV_TRENDS`

`sensor_action_trained_dev` stays as the in-distribution dev read.
"""

