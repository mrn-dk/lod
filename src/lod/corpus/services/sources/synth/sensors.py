# ---- the plant ----------------------------------------------------------------------

@dataclass(frozen=True)
class Plant:
    """One controlled variable, with the band a controller holds it in.

    `direction` is the side the danger is on: `high` for a temperature that runs away
    upward, `low` for a state of charge that runs down. `rmin`/`rmax` are the sensor's
    range, which is what the soft band around a threshold is a fraction of -- the same
    convention as `grammar.soft`, so a borderline reading is borderline by the same
    measure everywhere in the corpus.
    """

    key: str
    measure: str          # "jacket temperature"
    unit: str             # "C"
    lo: float             # normal band, inclusive
    hi: float
    crit: float           # critical limit, on the `direction` side of the band
    direction: str        # "high" | "low"
    rmin: float           # sensor range
    rmax: float
    step: float           # typical magnitude of one reading-to-reading change
    interval: int         # minutes between readings
    integral: bool = False

    @property
    def span(self) -> float:
        return self.rmax - self.rmin


