TRAINED_CAP = 1100
HELDOUT_CAP = 600

FAMILIES = {"gate": _gate_example, "undo": _undo_example, "blast": _blast_example}


def pool_for(family_categories: tuple[str, ...]) -> list[Call]:
    if family_categories == ("http",):
        return _load_http()
    return [c for c in CLI_CALLS if c.category in family_categories]


def _loader(family: str, categories: tuple[str, ...], seed: int, cap: int):
    def load(n: int) -> Iterator[Example]:
        pool = pool_for(categories)
        digest = hashlib.sha256(f"{seed}:{family}:{','.join(categories)}".encode()).digest()
        rng = random.Random(int.from_bytes(digest[:8], "big"))
        want = min(n, cap)
        made = 0
        bal = Balance()   # one tally per task, like chessfacts.reset_balance
        first_bal = FirstBalance()
        for _ in range(want * 12):
            if made >= want:
                return
            shape = "json" if rng.random() < 0.6 else "prose"
            if family in ("gate", "undo"):
                example = FAMILIES[family](pool, rng, f"toolgate_{family}", shape, bal)
            elif family in FAMILIES:
                example = FAMILIES[family](pool, rng, f"toolgate_{family}", shape)
            elif family == "first":
                example = _first_example(pool, rng, "toolgate_first", shape, first_bal)
            elif family.startswith("pair_"):
                example = _pair_example(pool, rng, "toolgate_pair", shape,
                                        family.split("_", 1)[1])
            else:
                raise ValueError(family)
            if example is not None:
                made += 1
                yield example
    return load


def tasks() -> list[RealTask]:
    """Trained CLI categories in `train`, with an eval twin each pinned to `devreal`; the
    HTTP half and the sysadmin category in `testreal`, never trained on.

    The twins were `force_split=None`, so the seed-0 name hash sent `gate` and `pair_tier`
    to `testreal` -- in-distribution CLI rows inside the split that is supposed to hold
    only the held-out structure -- and `undo` and `first` to `train`, where the "eval"
    twin was just more training data. Pinned, they give row 38 devreal coverage (the
    split early stopping selects on) and keep testreal to sysadmin and HTTP only.

    `DEV_CATEGORIES` (`accounts`) is dev's own held-out category: gate, undo and first,
    forced to `devreal`, in neither train nor test. Checkpoints are selected and T fitted
    on it; the twins remain the in-distribution dev read.

    Family: a held-out category is one structure and one call pool, so its gate, undo and
    first tasks share the family `toolgate_<category>`. A twin keeps the default, its
    trained task's name.
    """
    out: list[RealTask] = []
    trained = ("gate", "undo", "blast", "first", "pair_tier", "pair_precondition")
    for family in trained:
        for suffix, split, seed in (("", "train", 0), ("_eval", "devreal", 991)):
            name = f"toolgate_{family}_cli{suffix}"
            out.append(RealTask(
                row=ROW, name=name, licence=LICENCE, url=URL,
                load=_loader(family, TRAINED_CATEGORIES, seed, TRAINED_CAP),
                real=False, force_split=split,
                notes=(f"{family} over the trained CLI categories; code-labelled"
                       + ("; eval twin, examples never trained on" if suffix else ""))))
    for category in HELDOUT_CATEGORIES:
        for family in ("gate", "undo", "blast", "first"):
            if category == "sysadmin" and family == "blast":
                continue  # sysadmin calls carry too few radii to make the family worth it
            name = f"toolgate_{family}_{category}"
            out.append(RealTask(
                row=ROW, name=name, licence=LICENCE, url=URL,
                load=_loader(family, (category,), 7717, HELDOUT_CAP),
                real=False, force_split="testreal", family=f"toolgate_{category}",
                notes=f"{family} over the held-out {category} family; NEVER trained on"))
    for category in DEV_CATEGORIES:
        for family in ("gate", "undo", "first"):
            # no `blast`: like sysadmin, accounts are named units with too few radii
            name = f"toolgate_{family}_{category}"
            out.append(RealTask(
                row=ROW, name=name, licence=LICENCE, url=URL,
                load=_loader(family, (category,), 5309, HELDOUT_CAP),
                real=False, force_split="devreal", family=f"toolgate_{category}",
                notes=f"{family} over the {category} family; " + DEV_NOTE))
    return out
