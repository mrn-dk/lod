@dataclass(frozen=True)
class Call:
    """One call template. `man` is the page that proves the command and its flags exist;
    `argv` is what the agent proposes, with `{target}` filled by the blast radius."""

    key: str
    category: str
    man: str
    argv: str
    effect: str
    reverse: str | None          # a single call that puts it back, or None
    blasts: tuple[str, ...]
    dry_run: str | None = None   # the flag spelling that makes this call a no-op
    flags: tuple[str, ...] = ()
    target_kind: str = "path"

    @property
    def command(self) -> str:
        return self.man

    def flag_spellings(self) -> tuple[str, ...]:
        return tuple(f for f in self.flags + ((self.dry_run,) if self.dry_run else ())
                     if f.startswith("--") or (len(f) == 2 and f[1].isalpha()))


def _c(*args, **kw) -> Call:
    return Call(*args, **kw)


