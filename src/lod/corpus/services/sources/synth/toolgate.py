"""Row 38 -- tool-call and action gating (domain 16).

Reversibility and blast radius before acting: the decision an agent harness makes most
often, and the one a wrong answer costs most.

**The gate is never a property of the command.** `rm` answers `run_now` on a scratch tier
and `refuse` on a production tree; `rm` with a fresh backup covering the target answers
`run_now` in production too. `DELETE /orders/{id}` behaves the same way, and a `GET` is
only safe because its *effect* field says `read`, not because of its verb. If a command
name predicted the answer this module would be a lookup table of command names, so
`tests/test_toolgate_source.py` measures that directly: the best per-command majority
guess must stay under 0.75, and the gold option must never appear verbatim in its own
state or instructions.

**The policy is the criteria.** Every option carries the clause that selects it, the way
`rules.py` puts the rule in the criteria, and the code below is a transcription of those
clauses -- `undoable()` and `gate()` and nothing else. The state carries the facts the
clauses read (effect, the reversing call if there is one, the backup block, the tier, the
target) plus distractors that no clause reads.

**What is held out, and why it is a structure and not a sample.** Two families never enter
training:

  * `http` -- every call derived from a real OpenAPI spec, so the syntax of a call is new;
  * `sysadmin` -- mounts, scheduled jobs and machine power state, so the *category* is new.

Every gating primitive inside them -- each effect, each blast radius, a reversing call
present and absent, a dry-run flag present and absent, all three tiers, all three backup
states -- occurs in the trained CLI categories. A test asserts it, so a drop on the
held-out half is a failure to apply the policy to an unfamiliar tool rather than a missing
primitive.

**Dev holds out a category of its own.** `accounts` -- users, groups and sessions on a
host (`useradd`, `usermod`, `chage`, `loginctl`, ...) -- is in neither train nor test and
is built only from primitives the trained categories carry (the same test asserts it).
`devreal` selects checkpoints and fits T on it, so dev is as novel as test without
sharing a structure with it. The `_eval` twins stay as the in-distribution dev read.

**Licence.** No third-party prose reaches the corpus. From the local man pages the
build takes two facts only, both code-extracted: that a command exists, and which flag
spellings it really accepts (`scripts/fetch_data.py --only toolgate_http` verifies both and prints what it
could not verify). Effect classes come from `CLI_CALLS`, a table written here, because a
keyword rule over the NAME line tags only 55 % of pages and puts `cut`, `colrm` and
`clear` in the destructive bucket. The HTTP half keeps `(method, path template)` from
twelve Apache-2.0 / MIT OpenAPI specs -- interface surface both licences permit
redistributing, attributed per API in `toolgate_http.json` -- and discards every
description, summary, schema and example. All prose in the corpus is generated here or by
the scenario pass, which writes settings and never an answer.
"""

