def phrase(template_id: str, key: str, **fmt) -> str:
    """The question for one record: a frozen phrasing picked by the record's own state."""
    global _BANK
    if _BANK is None:
        from lod.phrasings import PhrasingBank
        _BANK = PhrasingBank.load()
    digest = hashlib.sha1(key.encode("utf-8")).hexdigest()
    text = _BANK.pick(f"d16.{template_id}", TEMPLATES[template_id], digest)
    return text.format(**fmt) if fmt else text


