# ==== tokens ==========================================================================

_TOK = None


def tokenizer():
    """The backbone's tokenizer from a local cache (the default HF cache, then the shared
    one HF_HOME points at), so a build never needs the network."""
    global _TOK
    if _TOK is None:
        from transformers import AutoTokenizer
        errs = []
        for kw in ({},):
            try:
                _TOK = AutoTokenizer.from_pretrained(TOKENIZER, local_files_only=True, **kw)
                break
            except Exception as e:  # noqa: BLE001 - try the next cache location
                errs.append(e)
        if _TOK is None:
            raise RuntimeError(f"no local {TOKENIZER} tokenizer: {errs}")
    return _TOK


def token_starts(text: str) -> list[int]:
    """Start character of every token of `text` (Qwen3, no special tokens)."""
    enc = tokenizer()(text, add_special_tokens=False, return_offsets_mapping=True)
    return [a for a, _ in enc["offset_mapping"]]


def n_tokens(text: str) -> int:
    return len(tokenizer()(text, add_special_tokens=False)["input_ids"])


def token_at(starts: list[int], char: int) -> int:
    """Index of the token that contains character `char`."""
    return max(0, bisect_right(starts, char) - 1)


# ==== sampling lengths and depths =====================================================

def sample_length(rng: random.Random) -> int:
    return int(math.exp(rng.uniform(math.log(MIN_TOKENS), math.log(MAX_TOKENS))))


def sample_depth(rng: random.Random, length: int) -> float:
    """Depth as a fraction of the state. Past the old 2,304-token prefix unless the
    state is too short to have a past, or the P_ANY_DEPTH draw says anywhere."""
    lo = PREFIX_TOKENS + 100
    if rng.random() < P_ANY_DEPTH or length < lo + 400:
        return rng.random()
    return rng.uniform(lo, length) / length


def _seed(*parts) -> int:
    return int.from_bytes(hashlib.sha256(":".join(map(str, parts)).encode()).digest()[:8], "big")


def _near_id(ident: str, taken: set[str], rng: random.Random) -> str:
    """`birch-4417` -> `birch-4471` / `birch-4917`: one or two digits moved."""
    word, num = ident.rsplit("-", 1)
    for _ in range(200):
        d = list(num)
        if rng.random() < 0.5:
            i, j = rng.sample(range(len(d)), 2)
            d[i], d[j] = d[j], d[i]
        else:
            i = rng.randrange(1, len(d))
            d[i] = rng.choice([c for c in "0123456789" if c != d[i]])
        cand = f"{word}-{''.join(d)}"
        if cand != ident and cand not in taken:
            return cand
    raise RuntimeError("no near id")


def _id_pattern(ident: str) -> re.Pattern:
    return re.compile(r"(?<![\w-])" + re.escape(ident) + r"(?![\w-])")


# ==== record rules ====================================================================

OPWORD = {">": "above", "<": "below", ">=": "at least", "<=": "at most"}


def eval_leaf(leaf: dict, rec: dict) -> bool:
    k = leaf["kind"]
    if k == "cmp":
        return C._cmp(rec[leaf["field"]], leaf["op"], leaf["value"])
    if k == "fref":
        return rec[leaf["field"]] > rec[leaf["limit"]]
    if k == "eq":
        return rec[leaf["field"]] == leaf["value"]
    raise ValueError(k)


def eval_rule(rule: dict, rec: dict) -> bool:
    vals = [eval_leaf(l, rec) for l in rule["leaves"]]
    return all(vals) if rule["op"] == "and" else any(vals)


def _gap(f: Num, rng: random.Random) -> float:
    span = f.hi - f.lo
    g = rng.uniform(0.02, 0.08) * span
    return max(1.0, round(g)) if f.integral else max(0.1, round(g, 1))


def _rnd(f: Num, x: float):
    return int(round(x)) if f.integral else round(x, 1)


def _make_leaf(cd, rec: dict, truth: bool, rng: random.Random, avoid: set[str]) -> dict:
    """A leaf that `rec` satisfies iff `truth`, built by placing its constant (cmp) or by
    setting the record's own fields (fref, eq)."""
    kinds = ["cmp", "cmp", "fref", "eq"]
    rng.shuffle(kinds)
    for kind in kinds:
        if kind == "cmp":
            fs = [f for f in cd.meas if f.name not in avoid]
            if not fs:
                continue
            f = rng.choice(fs)
            op = rng.choice(list(OPWORD))
            v, g = rec[f.name], _gap(f, rng)
            up = (op in (">", ">=")) != truth       # constant above the value?
            c = _rnd(f, v + g if up else v - g)
            if not f.lo <= c <= f.hi:
                op = {">": "<", "<": ">", ">=": "<=", "<=": ">="}[op]
                up = not up
                c = _rnd(f, v + g if up else v - g)
            leaf = {"kind": "cmp", "field": f.name, "op": op, "value": c}
        elif kind == "fref":
            ps = [(a, l) for a, l in cd.pairs if a not in avoid and l not in avoid]
            if not ps:
                continue
            a, l = rng.choice(ps)
            fl = cd.num(l)
            g = _gap(fl, rng)
            rec[l] = _rnd(fl, rec[a] - g if truth else rec[a] + g)
            leaf = {"kind": "fref", "field": a, "limit": l}
        else:
            es = [e for e in cd.enums if e.name not in avoid]
            if not es:
                continue
            e = rng.choice(es)
            if truth:
                val = rec[e.name]
            else:
                val = rng.choice([x for x in e.values if x != rec[e.name]])
            leaf = {"kind": "eq", "field": e.name, "value": val}
        if eval_leaf(leaf, rec) == truth:
            return leaf
    raise RuntimeError("no leaf")


def force_leaf(cd, rec: dict, leaf: dict, truth: bool, rng: random.Random) -> None:
    """Set `rec`'s fields so `leaf` evaluates to `truth` (the constant stays put)."""
    k = leaf["kind"]
    if k == "cmp":
        f = cd.num(leaf["field"])
        g = _gap(f, rng)
        up = (leaf["op"] in (">", ">=")) == truth   # value above the constant?
        rec[f.name] = _rnd(f, leaf["value"] + g if up else leaf["value"] - g)
    elif k == "fref":
        fl = cd.num(leaf["limit"])
        g = _gap(fl, rng)
        rec[fl.name] = _rnd(fl, rec[leaf["field"]] - g if truth else rec[leaf["field"]] + g)
    else:
        e = next(x for x in cd.enums if x.name == leaf["field"])
        rec[e.name] = leaf["value"] if truth else rng.choice(
            [x for x in e.values if x != leaf["value"]])
    assert eval_leaf(leaf, rec) == truth


def _pattern(op: str, n: int, want: bool, rng: random.Random) -> list[bool]:
    if n == 1:
        return [want]
    if op == "and":
        if want:
            return [True] * n
        p = [True] * n
        p[rng.randrange(n)] = False
        if rng.random() < 0.2:
            p = [False] * n
        return p
    if not want:
        return [False] * n
    p = [False] * n
    p[rng.randrange(n)] = True
    if rng.random() < 0.2:
        p = [True] * n
    return p


def leaf_text(cd, leaf: dict, shape: str, mode: str) -> str:
    f = next(x for x in cd.dom.fields if x.name == leaf["field"])
    ref = field_ref(f, shape, mode)
    if leaf["kind"] == "cmp":
        return f"{ref} is {OPWORD[leaf['op']]} {leaf['value']}{f.unit}"
    if leaf["kind"] == "fref":
        return f"{ref} is above {field_ref(cd.num(leaf['limit']), shape, mode)}"
    return f"{ref} is {leaf['value']}"


def rule_text(cd, rule: dict, shape: str, mode: str) -> str:
    parts = [leaf_text(cd, l, shape, mode) for l in rule["leaves"]]
    return f" {rule['op']} ".join(parts)


def rule_fields(rule: dict) -> set[str]:
    out = set()
    for l in rule["leaves"]:
        out.add(l["field"])
        if l["kind"] == "fref":
            out.add(l["limit"])
    return out


# ==== record states ===================================================================

@dataclass
class RecState:
    cd: object
    fmt: str
    recs: list[dict]
    keep: list[str]                   # the fields rendered; questions read only these
    used: set[int] = field(default_factory=set)
    scan_fields: set[str] = field(default_factory=set)
    starts: list[int] = field(default_factory=list)   # token starts of the first render
    pos: list[int] = field(default_factory=list)      # char offset of each record's id

    def render(self) -> str:
        keys = [self.cd.idf] + [k for k in self.recs[0] if k in self.keep]
        recs = [{k: r[k] for k in keys} for r in self.recs]
        st = C.State(self.cd, recs, 0, {}, "policy")
        return C.render_state(st, self.fmt)


def _keep_fields(cd, rng: random.Random) -> list[str]:
    """A random field subset that still lets every family ask its questions: two
    measured numbers, two categorical fields, one measured/limit pair."""
    meas = [f.name for f in cd.meas]
    enums = [e.name for e in cd.enums]
    a, l = rng.choice(cd.pairs)
    # nested randint: small subsets are commoner, so compact records (and so states of
    # many hundreds of records) are too
    keep = set(rng.sample(meas, rng.randint(2, rng.randint(2, len(meas)))))
    keep |= set(rng.sample(enums, rng.randint(2, rng.randint(2, len(enums)))))
    keep |= {a, l}
    rest = [f.name for f in cd.dom.fields if f.name not in keep]
    keep |= set(rng.sample(rest, rng.randint(0, rng.randint(0, len(rest)))))
    return sorted(keep)


def _record_state(cd, fmt: str, length: int, rng: random.Random) -> tuple[RecState, str, list[int]]:
    """Records of `cd` rendered in `fmt` to about `length` tokens: -> (state, text,
    token starts). Three passes at most: estimate tokens per record from a 2- and a
    12-record render, then rescale the record count on the measured total."""
    keep = _keep_fields(cd, rng)
    trial = RecState(cd, fmt, C.make_state(cd, rng, 12).recs, keep)
    t12 = n_tokens(trial.render())
    trial.recs = trial.recs[:2]
    t2 = n_tokens(trial.render())
    per = max(5.0, (t12 - t2) / 10)
    over = max(0.0, t2 - 2 * per)
    n = max(4, int((length - over) / per))
    for _ in range(3):
        rs = RecState(cd, fmt, C.make_state(cd, rng, n).recs, keep)
        text = rs.render()
        starts = token_starts(text)
        total = len(starts)
        if abs(total - length) <= 0.05 * length and total <= HARD_CAP:
            break
        n = max(4, int(n * (length - over) / max(1.0, total - over)))
    return rs, text, starts


def _positions(text: str, idents: list[str]) -> list[int]:
    return [_id_pattern(i).search(text).start() for i in idents]


def _choose_index(rs: RecState, starts: list[int], pos_chars: list[int], depth_tok: float,
                  rng: random.Random) -> int:
    toks = [token_at(starts, c) for c in pos_chars]
    free = [i for i in range(len(rs.recs)) if i not in rs.used]
    return min(free, key=lambda i: (abs(toks[i] - depth_tok), rng.random()))


def _like_target(rs: RecState, rng: random.Random, k: int, exclude: set[int]) -> list[int]:
    """k more option records placed by the same depth law as the target. Uniform
    positions would put the target (past the old prefix 85 % of the time) later than its
    rivals, and "the option that appears last" would find it."""
    out: list[int] = []
    total = len(rs.starts)
    for _ in range(k):
        rs.used |= set(exclude) | set(out)
        i = _choose_index(rs, rs.starts, rs.pos, sample_depth(rng, total) * total, rng)
        out.append(i)
    return out


def _free(rs: RecState, rng: random.Random, k: int, exclude: set[int] = frozenset()) -> list[int]:
    free = [i for i in range(len(rs.recs)) if i not in rs.used and i not in exclude]
    return rng.sample(free, k)


def _q_lookup(rs: RecState, t: int, rng: random.Random, split: str, qid: str) -> tuple[Question, list[int]]:
    cd = rs.cd
    rec = rs.recs[t]
    want = rng.random() < 0.5
    op = rng.choice(("and", "or"))
    n = 1 if rng.random() < 0.5 else 2
    pat = _pattern(op, n, want, rng)
    leaves, avoid = [], {f.name for f in cd.dom.fields} - set(rs.keep)
    for truth in pat:
        leaf = _make_leaf(cd, rec, truth, rng, avoid)
        leaves.append(leaf)
        avoid |= rule_fields({"leaves": [leaf]})
    rule = {"op": op, "leaves": leaves}
    assert eval_rule(rule, rec) == want
    decoys = _free(rs, rng, 2, {t})
    taken = {r[cd.idf] for r in rs.recs}
    for d in decoys:
        drec = rs.recs[d]
        drec[cd.idf] = _near_id(rec[cd.idf], taken, rng)
        taken.add(drec[cd.idf])
        # a decoy's answer is a fair coin, independent of the target's: forcing it
        # opposite would make "find the near-twin, flip its answer" a shortcut
        dwant = rng.random() < 0.5
        for leaf, truth in zip(leaves, _pattern(op, n, dwant, rng)):
            force_leaf(cd, drec, leaf, truth, rng)
        assert eval_rule(rule, drec) == dwant
    shape = "label" if rs.fmt == "prose" else "json"
    mode = rng.choice(("direct", "indirect"))
    text = rule_text(cd, rule, shape, mode)
    q = Question(
        id=qid,
        question=f"Does the {cd.noun} {rec[cd.idf]} meet this condition: {text}?",
        options=["no", "yes"], target=int(want),
        meta={"family": "lookup", "rule": rule, "target_id": rec[cd.idf],
              "decoys": [rs.recs[d][cd.idf] for d in decoys]})
    return q, [t] + decoys, [t]


def _q_cross(rs: RecState, t: int, rng: random.Random, split: str, qid: str):
    cd = rs.cd
    f = rng.choice([f for f in cd.meas if f.name in rs.keep])
    k = rng.randint(2, 4)
    others = _like_target(rs, rng, k - 1, {t})
    named = [t] + others
    hi = rng.random() < 0.5
    step = 1.0 if f.integral else 0.1
    # the winner beats the best other by a margin of 1-8 % of the range
    best_other = (max if hi else min)(rs.recs[i][f.name] for i in others)
    g = max(step, _gap(f, rng))
    rs.recs[t][f.name] = _rnd(f, best_other + g if hi else best_other - g)
    win = rs.recs[t][f.name]
    assert all((rs.recs[i][f.name] < win) if hi else (rs.recs[i][f.name] > win) for i in others)
    taken = {r[cd.idf] for r in rs.recs}
    # ...a near-id twin of a random named record (not always the winner's: that would
    # make "the option whose twin is extreme" a shortcut) that would win if read instead
    d = _free(rs, rng, 1, set(named))[0]
    rs.recs[d][cd.idf] = _near_id(rs.recs[rng.choice(named)][cd.idf], taken, rng)
    rs.recs[d][f.name] = _rnd(f, win + g if hi else win - g)
    ids = [rs.recs[i][cd.idf] for i in named]
    order = list(range(k))
    rng.shuffle(order)
    options = [ids[i] for i in order]
    shape = "label" if rs.fmt == "prose" else "json"
    ref = field_ref(f, shape, rng.choice(("direct", "indirect")))
    word = "highest" if hi else "lowest"
    q = Question(
        id=qid,
        question=f"Of the {cd.plural} {', '.join(options[:-1])} and {options[-1]}, which has "
                 f"the {word} value of {ref}?",
        options=options, target=options.index(ids[0]),
        meta={"family": "cross", "field": f.name, "highest": hi, "target_id": ids[0],
              "decoys": [rs.recs[d][cd.idf]]})
    return q, named + [d], named


def _q_pick(rs: RecState, t: int, rng: random.Random, split: str, qid: str):
    cd = rs.cd
    rec = rs.recs[t]
    leaves, avoid = [], {f.name for f in cd.dom.fields} - set(rs.keep)
    for _ in range(3):
        leaf = _make_leaf(cd, rec, True, rng, avoid)
        leaves.append(leaf)
        avoid |= rule_fields({"leaves": [leaf]})
    rule = {"op": "and", "leaves": leaves}
    k = rng.randint(4, 5)
    others = _like_target(rs, rng, k - 1, {t})
    for j, o in enumerate(others):
        fail = j % 3 if j < 3 else rng.randrange(3)
        for li, leaf in enumerate(leaves):
            force_leaf(cd, rs.recs[o], leaf, li != fail, rng)
        assert not eval_rule(rule, rs.recs[o])
    named = [t] + others
    ids = [rs.recs[i][cd.idf] for i in named]
    options = ids[:]
    rng.shuffle(options)
    shape = "label" if rs.fmt == "prose" else "json"
    mode = rng.choice(("direct", "indirect"))
    reqs = "; ".join(leaf_text(cd, l, shape, mode) for l in leaves)
    q = Question(
        id=qid,
        question=f"Which of these {cd.plural} meets every one of these requirements: {reqs}?",
        options=options, target=options.index(ids[0]),
        meta={"family": "pick", "rule": rule, "target_id": ids[0]})
    return q, named, named


def _q_scan(rs: RecState, t: int, rng: random.Random, split: str, qid: str):
    cd = rs.cd
    e = rng.choice([e for e in cd.enums if e.name in rs.keep and e.name not in rs.scan_fields])
    rs.scan_fields.add(e.name)
    val = rng.choice(e.values)
    for r in rs.recs:
        if r[e.name] == val:
            r[e.name] = rng.choice([x for x in e.values if x != val])
    count = rng.randrange(len(COUNT_WORDS)) + 1
    # every hit placed by the same depth law as the target: hits packed before the
    # target made "hits seen in the prefix, scaled up" a count estimate (audit: +0.215)
    extra = _like_target(rs, rng, count - 1, {t})
    hits = [t] + extra
    count = len(hits)
    for i in hits:
        rs.recs[i][e.name] = val
    assert sum(r[e.name] == val for r in rs.recs) == count
    shape = "label" if rs.fmt == "prose" else "json"
    ref = field_ref(e, shape, "direct")
    q = Question(
        id=qid,
        question=f"How many of the {cd.plural} in this state have {ref} {val}?",
        options=list(COUNT_WORDS), target=count - 1,
        meta={"family": "scan", "field": e.name, "value": val,
              "target_id": rs.recs[t][cd.idf],
              "hit_ids": [rs.recs[i][cd.idf] for i in hits]})
    return q, hits, hits


RECORD_Q = {"lookup": _q_lookup, "cross": _q_cross, "pick": _q_pick, "scan": _q_scan}


def record_example(fam: str, dom: str, rng: random.Random, split: str, task: str,
                   lengths: list[int] | None = None, depths: list[float] | None = None,
                   n_q: int = QUESTIONS_PER_EXAMPLE, fmt: str | None = None) -> Example:
    """One records state with `n_q` questions of family `fam`. `length`/`depths` fix the
    state length (tokens) and each question's evidence depth (fraction); the depth check
    passes them, training draws them."""
    cd = CDOMS[dom]
    length = lengths[0] if lengths else sample_length(rng)
    depths = depths or [sample_depth(rng, length) for _ in range(n_q)]
    fmt = fmt or rng.choice(C.FORMATS)
    rs, text, starts = _record_state(cd, fmt, length, rng)
    pos = _positions(text, [r[cd.idf] for r in rs.recs])
    rs.starts, rs.pos = starts, pos
    total = len(starts)
    questions, evid = [], []
    for j, frac in enumerate(depths):
        t = _choose_index(rs, starts, pos, frac * total, rng)
        q, used, ev = RECORD_Q[fam](rs, t, rng, split, f"q{j}")
        rs.used |= set(used)
        questions.append(q)
        evid.append([rs.recs[i][cd.idf] for i in ev])
    text = rs.render()
    while n_tokens(text) > HARD_CAP:
        spare = [i for i in range(len(rs.recs) - 1, -1, -1) if i not in rs.used]
        drop = set(spare[: max(1, len(spare) // 50)])
        rs.recs = [r for i, r in enumerate(rs.recs) if i not in drop]
        rs.used = {i - sum(1 for d in drop if d < i) for i in rs.used}
        text = rs.render()
    # every label re-derived from the final records
    by_id = {r[cd.idf]: r for r in rs.recs}
    for q in questions:
        assert rederive_records(q, list(by_id.values()), cd.idf) == q.target, q.meta
    starts = token_starts(text)
    for q, ev in zip(questions, evid):
        ptoks = [token_at(starts, _id_pattern(i).search(text).start()) for i in ev]
        _set_gen(q, ptoks, len(starts), fam, dom, fmt, n_records=len(rs.recs))
    return Example(state=text, questions=questions, task=task)


def rederive_records(q: Question, recs: list[dict], idf: str) -> int:
    """The target, recomputed from records alone (the tests call this on re-parsed
    states)."""
    m = q.meta
    by_id = {r[idf]: r for r in recs}
    fam = m["family"]
    if fam == "lookup":
        return int(eval_rule(m["rule"], by_id[m["target_id"]]))
    if fam == "pick":
        ok = [i for i, o in enumerate(q.options) if eval_rule(m["rule"], by_id[o])]
        assert len(ok) == 1
        return ok[0]
    if fam == "cross":
        vals = [by_id[o][m["field"]] for o in q.options]
        best = (max if m["highest"] else min)(vals)
        assert vals.count(best) == 1
        return vals.index(best)
    if fam == "scan":
        return sum(r[m["field"]] == m["value"] for r in recs) - 1
    raise ValueError(fam)


def _set_gen(q: Question, ptoks: list[int], total: int, fam: str, variant: str, fmt: str,
             n_records: int) -> None:
    depth = max(ptoks) if ptoks else total
    q.meta["gen"] = {
        "family": fam, "variant": variant, "format": fmt,
        "depth_tokens": depth, "state_tokens": total,
        "depth_frac": round(depth / total, 4) if total else 0.0,
        "evidence_tokens": sorted(ptoks), "n_records": n_records,
    }


