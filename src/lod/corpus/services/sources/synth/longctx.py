@dataclass(frozen=True)
class Spec:
    name: str
    kind: str          # "records" | "doc"
    fam: str
    variant: str       # domain name, or doc format
    split: str


def specs() -> list[Spec]:
    out = []
    for fam in RECORD_FAMILIES:
        for dom, split in DOMAIN_SPLIT.items():
            out.append(Spec(f"longctx_{fam}_{dom}", "records", fam, dom, split))
    for kind, fmts in DOC_FORMATS.items():
        for fmt, split in fmts:
            out.append(Spec(f"longctx_{kind}_{fmt}", "doc", kind, fmt, split))
    return out


def make(spec: Spec, rng: random.Random, **kw) -> Example:
    if spec.kind == "records":
        return record_example(spec.fam, spec.variant, rng, spec.split, spec.name, **kw)
    return doc_example(spec.fam, spec.variant, rng, spec.split, spec.name, **kw)


def generate(spec: Spec, n: int, seed_tag: str = "build") -> Iterator[Example]:
    for i in range(min(n, CAP[spec.split])):
        rng = random.Random(_seed(seed_tag, spec.name, i))
        yield make(spec, rng)


def _loader(spec: Spec):
    def load(n: int) -> Iterator[Example]:
        return generate(spec, n)
    return load


def tasks() -> list[RealTask]:
    out = []
    for s in specs():
        out.append(RealTask(
            row=ROW, name=s.name, licence=LICENCE, url=URL, load=_loader(s),
            per_example_options=s.fam in ("cross", "pick"), real=False,
            force_split=s.split, family=s.name,
            notes=f"long-context {s.fam} over {s.variant}; evidence depth recorded in meta.gen"))
    return out
