"""Row 51 -- long-context reading with the evidence at a controlled depth (domain 25).

The model trained on states of at most 2,304 tokens while its backbone reads 32,768
positions. The final runs raise the state budget to ~30k tokens, and this row is the long
tail that has to teach the model to *use* evidence anywhere in a long state, not merely
to tolerate length. Every question here is decided by one record, line, section or clause
(or a handful of them) placed at a depth the generator chooses, inside a state of 2k-30k
Qwen3 tokens that is otherwise distractor.

Two kinds of state:

    records   many records of one `records.py` domain (the `compose.py` extension of it,
              values clustered per state as `compose.make_state` draws them), rendered in
              one of `compose.FORMATS`, 15 to ~1,500 records depending on format and field
              subset. Families:
                lookup  does record <id> satisfy a 1-2 clause rule?        (yes/no)
                cross   which of 2-4 named records has the highest/lowest <field>?
                pick    which of 4-5 named records meets every one of 3 requirements?
                        (a catalog in the state, not in the options: an option is a bare id)
                scan    how many records carry <field> = <value>? (1-5, every hit placed by the depth law)
    documents distractor-heavy text with one relevant piece:
                log     the final status of one job among thousands of log lines
                config  one setting of one service section in a long config file
                policy  who signs off a request under one clause of a long policy

**Code owns the target.** Every answer is computed from the records or pieces the
generator placed, and re-evaluated against the final state before an example is emitted.

**Near-miss decoys.** A lookup target has two decoy records whose ids differ from it by
one or two digits; log jobs, config sections and policy clauses have the same, and a cross
question has a near-twin of one option holding a value that would win. A decoy's answer
is drawn independently of the target's -- forced opposite, "find the twin and flip it"
would be a shortcut a prefix reader could use half the time -- so approximate
retrieval ("the record that looks like birch-4417") is right only at chance.

**Depth.** The state length is log-uniform over [2,500, 29,000] tokens. With probability
`P_ANY_DEPTH` the evidence depth is uniform over the whole state; otherwise it is uniform
over the part past the first `PREFIX_TOKENS` (2,304, the old state budget), because a
question whose answer sits in a short prefix teaches nothing a 2k model does not already
do. `meta.gen = {depth_tokens, state_tokens, depth_frac, n_records, family, ...}` is
measured with the Qwen3 tokenizer on the final state, not estimated.

**Held out by structure.** Record families hold out whole domains (`order` -> devreal,
`vehicle` -> testreal: unseen field names, nouns and value ranges); document families hold
out whole formats (log `bracket` and policy `markdown` -> devreal, config `toml` and policy
`legal` -> testreal). Every task is `force_split` and is its own `family`.
A shortcut audit measures the shortcuts; `scripts/build_corpus.py probes`
builds the controlled length x depth grid from the devreal structures.
"""

