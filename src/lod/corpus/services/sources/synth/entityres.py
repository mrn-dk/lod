"""Row 39 -- entity resolution (domain 17).

Two records, or one record and a roster of forty: are these one entity or two? The
corruption that built the pair decides the label, and the *matching policy* -- what
counts as the same entity, which field settles it, what a missing field means -- is
written into the criteria, the way `rules.py` writes the rule into the criteria.

**The trap this module is built around.** Corrupt a matched pair by one character and
leave unmatched pairs as two unrelated records, and edit distance solves the task: you
have a string-similarity benchmark wearing a reasoning benchmark's clothes. So both
halves are built the other way round.

- Matched pairs are driven *apart* on the surface: transliterated surnames, `SURNAME,
  Given` order, a nickname, initials, a married name, a new address, the date written
  three ways.
- Unmatched pairs are pulled *together*: a father and a son at one address, twins, a
  namesake in a large city, two branches of one company, parts I and II of one paper.

`_similarity_baseline` in the tests measures what is left: the best accuracy any
threshold on character similarity can reach, maximised over the threshold *and* over the
direction of the comparison, so a merely inverted signal counts as solved too.

**The policy is the program.** Three clauses, the same shape for each record type:

  1. If both records carry the strong identifier -- national insurance number,
     registration number, DOI -- it settles the question by itself. It is recorded
     reliably, so only its punctuation and case vary.
  2. If at least one record lacks it, fall back to the date both records carry -- date of
     birth, date of incorporation, year of publication -- together with the name.
  3. Address, telephone, employer, sector, venue and the record key never decide
     anything. People move, companies re-register an office, a paper is re-typeset.

A field present in only one record is not evidence either way, which is why clause 2 has
a hole in it: when neither the identifier nor the fallback date is in *both* records, the
records genuinely do not settle the question. Those pairs are drawn one-entity exactly
half the time and carry the soft target `[0.5, 0.5]`. That is the true conditional
probability under the generating distribution, not manufactured softness.

**What is held out.** Fourteen atomic corruption operations, and families that combine
them. Twenty-two families are trained, six are reserved whole to `testreal`, five more
(`DEV_FAMILIES`) whole to `devreal`, and every operation inside a reserved family appears
alone in a trained one -- the `rule_transfer` pattern. Dev's five share no composition with
test's six, so selecting a checkpoint on them never reads a structure test measures.
`("translit", "reorder")` is read against trained `("translit", "punct")` and `("reorder",
"drop")`; `("surname_change", "relocate")` against `("surname_change", "phone_style")` and
`("abbrev", "relocate")`.

**Why no LLM call.** `entityres_` is in `PROTECTED_PREFIXES`, so the enricher never sees
these tasks -- it must not, because it keys on `(task, option keys)` and a roster's option
keys are per example. Field formatting, field order and the question stem are therefore
varied in code, deterministically and from a seed. The question stems below were drafted
as paraphrases and then fixed here as literals: the model proposes wording, code owns
everything else, and here the wording is frozen at review time rather than at build time.
"""

