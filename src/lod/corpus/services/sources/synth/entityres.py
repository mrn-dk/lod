def typo(text: str, rng: random.Random) -> str:
    """One keyboard slip: a transposition, a doubling, a drop or a neighbour."""
    s = str(text)
    idx = [i for i, c in enumerate(s) if c.isalnum()]
    if len(idx) < 3:
        return s
    i = rng.choice(idx[1:-1])
    kind = rng.choice(("swap", "double", "drop", "sub"))
    if kind == "swap" and i + 1 < len(s):
        return s[:i] + s[i + 1] + s[i] + s[i + 2:]
    if kind == "double":
        return s[:i] + s[i] + s[i:]
    if kind == "drop":
        return s[:i] + s[i + 1:]
    near = "qwertyuiopasdfghjklzxcvbnm"
    return s[:i] + rng.choice(near) + s[i + 1:]


