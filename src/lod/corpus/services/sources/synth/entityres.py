MODES = ("id", "date", "none")


def _force_mode(rec_a: dict, rec_b: dict, mode: str, rng: random.Random) -> None:
    """Make the records carry exactly what the mode says they carry."""
    t = rec_a["_type"]
    idf, datef = ID_FIELD[t], DATE_FIELD[t]
    for r in (rec_a, rec_b):
        r["_style"].setdefault("dropped", set()).discard(idf)
        r["_style"]["dropped"].discard(datef)
    if mode == "id":
        return
    if mode == "date":
        rng.choice((rec_a, rec_b))["_style"]["dropped"].add(idf)
        if rng.random() < 0.35:
            rng.choice((rec_a, rec_b))["_style"]["dropped"].add(idf)
        return
    for r in (rec_a, rec_b):
        r["_style"]["dropped"].add(idf)
    rng.choice((rec_a, rec_b))["_style"]["dropped"].add(datef)
    if rng.random() < 0.4:
        for r in (rec_a, rec_b):
            r["_style"]["dropped"].add(datef)


def vary_against(base: dict, other: dict, rng: random.Random) -> None:
    """Make `other` write its identifier and its date in a different style from `base`.

    Applied to every pair, whatever its label, and to every roster entry against the
    query. Without it a quarter of the identifier-mode pairs render the deciding field
    as the *same string* in both records, and `state.count(gold)` solves them.
    """
    styles = {"person": NINO_STYLES, "company": REGNO_STYLES,
              "publication": DOI_STYLES}[base["_type"]]
    if other["_style"].get("id") == base["_style"].get("id"):
        other["_style"]["id"] = rng.choice([x for x in styles
                                            if x != base["_style"].get("id")])
    if other["_style"].get("date") == base["_style"].get("date"):
        other["_style"]["date"] = rng.choice([x for x in DATE_STYLES
                                              if x != base["_style"].get("date")])


def drift(rec: dict, rng: random.Random) -> None:
    """Move what the policy says never decides: a new number, a new job, a new address.

    Clause 4 is only worth stating if it is exercised. It is also what stops matched
    pairs sitting at a high character similarity: without it the duplicate shares its
    address, telephone and employer with the original word for word, and a similarity
    threshold reads a duplicate off those three fields alone.
    """
    t = rec["_type"]
    if t in ("person", "company") and rng.random() < 0.6:
        rec["_phone"] = (f"{rng.randrange(11, 99)}", f"{rng.randrange(1000000, 9999999)}")
    if t == "person" and rng.random() < 0.45:
        rec["_employer"] = rng.choice(EMPLOYERS)
    if t == "company" and rng.random() < 0.3:
        rec["_sector"] = rng.choice(SECTORS)
    if t in ("person", "company") and rng.random() < 0.45:
        rec["_address"] = _address(rng)
    if t == "publication":
        if rng.random() < 0.5:
            rec["_venue"] = rng.choice(VENUES)
        if rng.random() < 0.6:
            rec["_volume"] = rng.randrange(1, 60)
            rec["_pages"] = rng.randrange(1, 900)


def copy_entity(rec: dict, rng: random.Random) -> dict:
    out = dict(rec)
    out["_style"] = {}
    out["_address"] = dict(rec["_address"]) if "_address" in rec else None
    if out["_address"] is None:
        out.pop("_address")
    out["_authors"] = list(rec["_authors"]) if "_authors" in rec else None
    if out["_authors"] is None:
        out.pop("_authors")
    # A fresh key, drawn like any other record's. The duplicate's key used to be
    # `(original + 7717) % 90000 + 10000`: a fixed function of the original's that no
    # near miss or filler ever satisfied, so "the keys are 7717 apart" labelled 100 % of
    # resolved pairs (measured by a shortcut audit) with clause 4 saying the
    # record key never decides.
    out["_record_key"] = f"{rec['_record_key'][:2]}{rng.randrange(10000, 99999)}"
    return out


# The fields clause 4 says never decide, per record type. A duplicate starts with all of
# them and `drift` moves some; a near miss does the same (`near_miss`), so whether two
# records share a telephone, an address or an employer carries no information about the
# label. It used to: every near miss kept the original's telephone ("one household, one
# line") and employer, while a duplicate drifted its telephone 60 % of the time, so a
# telephone that differed meant one entity on 100 % of the pairs where it happened.
SOFT_FIELDS = {"person": ("_phone", "_address", "_employer"),
               "company": ("_phone", "_address", "_sector"),
               "publication": ("_venue", "_volume", "_pages")}


def share_then_drift(src: dict, other: dict, rng: random.Random) -> None:
    for f in SOFT_FIELDS[src["_type"]]:
        v = src[f]
        other[f] = dict(v) if isinstance(v, dict) else v
    drift(other, rng)


NEAR = {
    "person": ("household", "twin", "namesake", "sibling"),
    "company": ("branch", "successor", "rename_clash"),
    "publication": ("series", "homonym", "preprint"),
}


# The near miss that keeps the *name* the same: a namesake, a branch trading under the
# identical name, the preprint of the same paper. Every other kind changes the name
# (a different given name, a different legal suffix, a part number or another first
# author). Drawn uniformly, those were two in three of the unmatched pairs, and a matched
# pair almost never changes its name, so "same name -> one entity" -- reading neither the
# identifier nor the date -- scored 0.83 on resolved pairs against a majority of 0.51.
# Half of the near misses now keep the name, so the name stops standing in for clauses 1
# and 2.
SAME_NAME_NEAR = {"person": "namesake", "company": "branch", "publication": "preprint"}
P_SAME_NAME_NEAR = 0.5


# The near misses that keep the date and change the name. Under clause 2 a pair is one
# entity only when the date AND the name agree, so the two single steps should each be
# right about as often: with same-name near misses always on another date and a person's
# other near misses mostly on another date too, "same date -> one entity" scored 0.83-0.87
# on date-mode pairs against 0.74 for the name. In date mode the name-changing near miss
# is now the same-date kind most of the time.
SAME_DATE_NEAR = {"person": "twin", "company": "rename_clash", "publication": "series"}
P_SAME_DATE_NEAR = 0.7


def near_kind(rt: str, rng: random.Random, mode: str | None = None) -> str:
    if rng.random() < P_SAME_NAME_NEAR:
        return SAME_NAME_NEAR[rt]
    if mode == "date" and rng.random() < P_SAME_DATE_NEAR:
        return SAME_DATE_NEAR[rt]
    return rng.choice([k for k in NEAR[rt] if k != SAME_NAME_NEAR[rt]])


def near_miss(rec: dict, kind: str, rng: random.Random) -> dict:
    """A *different* entity that looks as much like `rec` as the world allows."""
    t = rec["_type"]
    other = NEW[t](rng)
    other["_entity"] = _key(rng)
    # What clause 4 says never decides is shared exactly as a duplicate shares it: all of
    # it, then `drift`. A household, a branch or a preprint still often sits at the same
    # address or under the same switchboard -- as often as a duplicate does, no more.
    share_then_drift(rec, other, rng)
    if t == "person":
        other["_surname"] = rec["_surname"]
        if kind == "household":                            # a parent and a child
            other["_given"] = rng.choice([i for i in range(len(GIVEN))
                                          if i != rec["_given"]])
            shift = rng.randrange(18, 42) * 365
            other["_dob"] = rec["_dob"] - timedelta(days=shift)
        elif kind == "twin":                               # same roof, same day
            other["_given"] = rng.choice([i for i in range(len(GIVEN))
                                          if i != rec["_given"]])
            other["_dob"] = rec["_dob"]
        elif kind == "sibling":
            other["_given"] = rng.choice([i for i in range(len(GIVEN))
                                          if i != rec["_given"]])
            other["_dob"] = rec["_dob"] - timedelta(days=rng.randrange(400, 1400))
            d, letter, prefix = rec["_nino"]               # consecutive registrations
            other["_nino"] = (f"{(int(d) + rng.choice((-1, 1))) % 1000000:06d}",
                              letter, prefix)
        else:                                              # namesake in a large city
            other["_given"] = rec["_given"]
            other["_dob"] = date(rng.randrange(1938, 2006), rng.randrange(1, 13),
                                 rng.randrange(1, 29))
    elif t == "company":
        other["_head"], other["_mid"] = rec["_head"], rec["_mid"]
        if kind == "branch":                               # two branches, one name
            other["_tail"] = rec["_tail"]
            other["_dob"] = rec["_dob"] + timedelta(days=rng.randrange(400, 5000))
        elif kind == "successor":                          # X Ltd and X Holdings Ltd
            other["_tail"] = rng.choice([x for x in COMPANY_TAILS if x != rec["_tail"]])
            other["_dob"] = rec["_dob"] + timedelta(days=rng.randrange(900, 7000))
        else:                                              # same office, same day
            other["_tail"] = rng.choice([x for x in COMPANY_TAILS if x != rec["_tail"]])
            other["_dob"] = rec["_dob"]
    else:
        if kind == "series":                               # Part I and Part II
            other["_title"] = rec["_title"]
            other["_authors"] = list(rec["_authors"])
            # Only a record not yet written down may gain its `Part I`. A roster query is
            # materialised before its near misses are drawn, so setting it there moved
            # the query's hidden name away from what its surface says: `verdict` then
            # called the query's own duplicate `two_entities` and the roster was redrawn
            # -- silently, every time a publication roster matched by date also drew a
            # `series` distractor.
            if rec["_part"] is None and "_surf" not in rec:
                rec["_part"] = "I"
            other["_part"] = "II"
            other["_year"] = rec["_year"]
            other["_dob"] = date(other["_year"], 1, 1)
        elif kind == "homonym":                            # one title, other authors
            other["_title"] = rec["_title"]
            other["_year"] = rec["_year"]
            other["_dob"] = date(other["_year"], 1, 1)
        else:                                              # preprint and journal version
            other["_title"] = rec["_title"]
            other["_authors"] = list(rec["_authors"])
            other["_year"] = rec["_year"] + rng.randrange(1, 4)
            other["_dob"] = date(other["_year"], 1, 1)
    return other


# Clause 1 is only worth stating if it is ever needed. Without these, a pair in which
# both records carry the identifier always had the date and the name agreeing with it --
# duplicates never disagreed about a date, and no near miss shared both name and date --
# so "skip clause 1, read the date and the name" scored 0.93-0.96 on identifier-mode
# pairs (only `surname_change` ever separated the two readings;
# measured by a shortcut audit). Now, in that share of identifier-mode pairs,
# clauses 2 and 3 read the other way from clause 1: a duplicate whose second system keyed
# the date wrong, or a namesake / same-named branch / preprint on the same date under
# another identifier. Only the identifier gets these right, which is what clause 1 says.
# Outside identifier mode such a pair is not drawn: clause 2 would read it the other way
# and `verdict` would refuse it.
P_ID_CONFLICT = 0.45


def miskey_date(rec: dict, rng: random.Random) -> None:
    """One system keyed the date wrong: day and month swapped, a day or a year off."""
    d = rec["_dob"]
    if rec["_type"] == "publication":
        rec["_year"] = rec["_year"] + rng.choice((-1, 1))
        rec["_dob"] = date(rec["_year"], 1, 1)
        return
    kinds = ["days", "year"] + (["swap"] if d.day <= 12 and d.day != d.month else [])
    kind = rng.choice(kinds)
    if kind == "swap":
        rec["_dob"] = date(d.year, d.day, d.month)
    elif kind == "year":
        rec["_dob"] = date(d.year + rng.choice((-10, -1, 1, 10)), d.month, d.day)
    else:
        rec["_dob"] = d + timedelta(days=rng.choice((-1, 1)) * rng.randrange(1, 30))


def same_date_as(rec: dict, src: dict) -> None:
    rec["_dob"] = src["_dob"]
    if rec["_type"] == "publication":
        rec["_year"] = src["_year"]


def build_pair(rt: str, family: tuple[str, ...], want: str, mode: str,
               rng: random.Random) -> tuple[dict, dict] | None:
    """One pair. `want` is the label being aimed at; the label shipped is `verdict`'s.

    Returns None when the draw did not land on `want` -- the caller redraws rather than
    relabelling, which is what keeps the corruption in charge of the label.
    """
    a = NEW[rt](rng)
    randomise_style(a, rng)
    conflict = mode == "id" and rng.random() < P_ID_CONFLICT
    if want == OPT_ONE:
        b = copy_entity(a, rng)
        randomise_style(b, rng)
        drift(b, rng)
        apply_family(family, b, rng)
        if "surname_change" in family and mode != "id":
            return None                        # clause 3: unconfirmable without the id
        if conflict:
            miskey_date(b, rng)
    else:
        b = near_miss(a, SAME_NAME_NEAR[rt] if conflict else near_kind(rt, rng, mode),
                      rng)
        if conflict:
            same_date_as(b, a)
        randomise_style(b, rng)
        # the noise sits on both halves, so "the messy one is the duplicate" is not a tell
        apply_family(family, rng.choice((a, b)), rng)
        if "surname_change" in family and mode != "id":
            return None
    _force_mode(a, b, mode, rng)
    vary_against(a, b, rng)
    materialise(a, rng)
    materialise(b, rng)
    if pair_is_unreadable(a, b):
        return None
    got, _ = verdict(a, b)
    if mode == "none":
        return (a, b) if got is None else None
    return (a, b) if got == want else None


def draw_pair(rt: str, family: tuple[str, ...], want: str, mode: str,
              rng: random.Random, tries: int = 40) -> tuple[dict, dict]:
    for _ in range(tries):
        got = build_pair(rt, family, want, mode, rng)
        if got is not None:
            return got
    # every family has at least one mode it always lands in; `id` is it
    for _ in range(tries):
        got = build_pair(rt, family, want, "id", rng)
        if got is not None:
            return got
    raise RuntimeError(f"could not build a {want} {rt} pair for {slug(family)}")


# ---- states ------------------------------------------------------------------------------

def render_pair(a: dict, b: dict, shape: str, rng: random.Random) -> str:
    if shape == "json":
        return json.dumps({"record_from_system_a": a["_surf"],
                           "record_from_system_b": b["_surf"]}, indent=2,
                          ensure_ascii=False)
    return (f"Record from system A. {_prose(a)}\n\n"
            f"Record from system B. {_prose(b)}")


def _prose(rec: dict) -> str:
    parts = []
    for k, v in rec["_surf"].items():
        label = k.replace("_", " ")
        text = ", ".join(v) if isinstance(v, list) else v
        parts.append(f"{label}: {text}")
    return "; ".join(parts) + "."


def _row(rec: dict, columns: tuple[str, ...], compact: bool = False) -> str:
    cells = []
    for c in columns:
        if compact and isinstance(rec["_surf"].get(c), list):
            # forty full author lists do not fit the state budget, and the policy only
            # ever reads the first author
            names = rec["_surf"][c]
            cells.append(names[0] + (" et al." if len(names) > 1 else ""))
            continue
        if c not in rec["_surf"]:
            # a blank cell would read as an empty value, and an empty value that matched
            # another empty value would be clause 1 firing on nothing
            cells.append("(not recorded)")
            continue
        v = rec["_surf"][c]
        cells.append("; ".join(v) if isinstance(v, list) else str(v))
    return " | ".join(cells)


TABLE_COLUMNS = {
    "person": ("full_name", "date_of_birth", "national_insurance_no", "address", "city",
               "postcode", "telephone", "employer", "record_key"),
    "company": ("legal_name", "incorporated_on", "registration_number",
                "registered_office", "city", "postcode", "sector", "telephone",
                "record_key"),
    "publication": ("title", "authors", "year_published", "doi", "venue", "volume",
                    "pages", "record_key"),
}


def render_roster(query: dict, keys: list[str], cands: list[dict], shape: str) -> str:
    rt = query["_type"]
    if shape == "json":
        return json.dumps({"query": query["_surf"],
                           "roster": {k: c["_surf"] for k, c in zip(keys, cands)}},
                          indent=2, ensure_ascii=False)
    # forty rows of nine columns is 3,600 tokens, over `ship_v4.sh --max-state-tokens`.
    # A wide roster drops the columns clause 4 says never decide anyway.
    compact = len(cands) > 12
    cols = NARROW_COLUMNS[rt] if compact else TABLE_COLUMNS[rt]
    head = "entry | " + " | ".join(c.replace("_", " ") for c in cols)
    lines = [f"Query record: {_prose(query)}", "", "Roster.", head,
             "-" * min(len(head), 90)]
    lines += [f"{k} | {_row(c, cols, compact)}" for k, c in zip(keys, cands)]
    return "\n".join(lines)


NARROW_COLUMNS = {
    "person": ("full_name", "date_of_birth", "national_insurance_no", "address", "city"),
    "company": ("legal_name", "incorporated_on", "registration_number", "city"),
    "publication": ("title", "authors", "year_published", "doi"),
}

