def name_key(rec: dict) -> tuple:
    """What the policy means by "the same name", reached without parsing the surface.

    Case, punctuation, initials, nicknames, romanisation, abbreviation and a single
    keyboard slip are all listed in clause 3 as renderings of one name, and none of them
    moves this key. A marriage name and a different given name do move it -- which is
    exactly the pair of cases clause 3 refuses to reconcile without the identifier.
    """
    t = rec["_type"]
    if t == "person":
        return ("person", rec["_given"], rec["_married"] if rec["_married"] is not None
                else rec["_surname"])
    if t == "company":
        return ("company", rec["_head"], rec["_mid"], rec["_tail"])
    return ("publication", rec["_title"], rec["_part"], tuple(rec["_authors"][:1]))


# ---- rendering -------------------------------------------------------------------------

def _given_text(rec: dict, rng: random.Random) -> str:
    style = rec["_style"].get("given", "full")
    group = GIVEN[rec["_given"]]
    if style == "full":
        return group[0]
    if style == "nickname":
        return group[rec["_style"].get("nick_i", 1) % len(group)]
    return group[0][0] + "."                                  # "initial"


def _surname_text(rec: dict) -> str:
    idx = rec["_married"] if rec["_married"] is not None else rec["_surname"]
    variants = SURNAME[idx]
    return variants[rec["_style"].get("translit", 0) % len(variants)]


def person_name(rec: dict, rng: random.Random) -> str:
    given, sur = _given_text(rec, rng), _surname_text(rec)
    order = rec["_style"].get("order", "given_first")
    if order == "surname_first":
        text = f"{sur.upper()}, {given}"
    elif order == "surname_plain":
        text = f"{sur} {given}"
    else:
        text = f"{given} {sur}"
    return _finish(text, rec, "name")


def company_name(rec: dict) -> str:
    return _finish(f"{rec['_head']} {rec['_mid']} {rec['_tail']}", rec, "name")


def publication_title(rec: dict) -> str:
    a, b, c = rec["_title"]
    text = f"{a} {b} {c}" + (f", Part {rec['_part']}" if rec["_part"] else "")
    return _finish(text, rec, "name")


def author_list(rec: dict, rng: random.Random) -> list[str]:
    out = []
    order = rec["_style"].get("order", "given_first")
    initials = rec["_style"].get("given") == "initial"
    for g, s in rec["_authors"]:
        sur = SURNAME[s][rec["_style"].get("translit", 0) % len(SURNAME[s])]
        given = GIVEN[g][0][0] + "." if initials else GIVEN[g][0]
        out.append(f"{sur.upper()}, {given}" if order == "surname_first"
                   else f"{given} {sur}")
    # The keyboard slip lands on ONE string. Every author used to share the title's
    # `name` slot, so one `typo` op put a slip in the title and another in every author
    # with the same seed -- two slips in what the policy reads (title, first author)
    # where clause 3 allows "a single slip of the keyboard". A reader holding the policy
    # to the letter called 45 % of `typo`-family publication duplicates two works.
    return [_finish(x, rec, "name", slot="author" if i == 0 else "author_rest")
            for i, x in enumerate(out)]


def _finish(text: str, rec: dict, kind: str, slot: str | None = None) -> str:
    """Case, punctuation, abbreviation and the keyboard slip, applied to a rendered
    string rather than to the record, so they never move `name_key`. `slot` is where a
    `typo` may land; it defaults to `kind`."""
    st = rec["_style"]
    if st.get("abbrev") and kind in ("name", "street", "venue"):
        text = abbreviate(text)
    if st.get("punct") and kind == "name":
        text = depunct(text)
    if st.get("case") == "upper":
        text = text.upper()
    elif st.get("case") == "lower":
        text = text.lower()
    if st.get("typo_field") == (slot or kind):
        seed = st.get("typo_seed", 0)
        slipped = typo(text, random.Random(seed))
        if kind == "name":
            # A slip that happens to spell another real name is not a slip to a reader:
            # `OZDEMIR, Rick` with its R turned to M reads as Michael, not as Richard
            # mistyped. Re-draw the slip, deterministically, until it spells nothing new.
            for k in range(1, 16):
                if not (_tokens(slipped) - _tokens(text)) & KNOWN_NAME_TOKENS:
                    break
                slipped = typo(text, random.Random(seed + k))
        text = slipped
    return text


def _tokens(text: str) -> set[str]:
    return set(depunct(text).lower().replace(",", " ").split())


KNOWN_NAME_TOKENS = frozenset(
    tok for grp in GIVEN + SURNAME for form in grp for tok in _tokens(form))


def surface(rec: dict, rng: random.Random) -> dict:
    """The record as it is actually written down. Hidden keys never appear."""
    t, st = rec["_type"], rec["_style"]
    ds = st.get("date", "iso")
    out: dict = {}
    if t == "person":
        out["full_name"] = person_name(rec, rng)
        if "date_of_birth" not in st.get("dropped", ()):
            out["date_of_birth"] = fmt_date(rec["_dob"], ds)
        if "national_insurance_no" not in st.get("dropped", ()):
            d, letter, prefix = rec["_nino"]
            out["national_insurance_no"] = fmt_nino(d, letter, prefix,
                                                    st.get("id", "spaced"))
        a = rec["_address"]
        out["address"] = _finish(a["street"], rec, "street")
        out["city"] = a["city"]
        out["postcode"] = a["postcode"]
        out["telephone"] = fmt_phone(*rec["_phone"], st.get("phone", "plain"))
        out["employer"] = _finish(rec["_employer"], rec, "employer")
        out["record_key"] = rec["_record_key"]
    elif t == "company":
        out["legal_name"] = company_name(rec)
        if "incorporated_on" not in st.get("dropped", ()):
            out["incorporated_on"] = fmt_date(rec["_dob"], ds)
        if "registration_number" not in st.get("dropped", ()):
            out["registration_number"] = fmt_regno(*rec["_regno"], st.get("id", "spaced"))
        a = rec["_address"]
        out["registered_office"] = _finish(a["street"], rec, "street")
        out["city"] = a["city"]
        out["postcode"] = a["postcode"]
        out["sector"] = rec["_sector"]
        out["telephone"] = fmt_phone(*rec["_phone"], st.get("phone", "plain"))
        out["record_key"] = rec["_record_key"]
    else:
        out["title"] = publication_title(rec)
        out["authors"] = author_list(rec, rng)
        if "year_published" not in st.get("dropped", ()):
            out["year_published"] = str(rec["_year"])
        if "doi" not in st.get("dropped", ()):
            out["doi"] = fmt_doi(rec["_doi"], st.get("id", "bare"))
        out["venue"] = _finish(rec["_venue"], rec, "venue")
        out["volume"] = str(rec["_volume"])
        out["pages"] = f"{rec['_pages']}-{rec['_pages'] + rng.randrange(3, 22)}"
        out["record_key"] = rec["_record_key"]
    order = list(out)
    rng.shuffle(order)
    return {k: out[k] for k in order}


# ---- corruption operations --------------------------------------------------------------
# An operation writes into `_style` or into a non-deciding field. None of them moves
# `_entity`, and none of them moves `name_key` except `surname_change` (a married surname,
# or a company re-registered under another legal suffix), which is only ever drawn where
# the identifier is in both records to confirm it.

OP_TYPES = {
    "typo": RECORD_TYPES, "case": RECORD_TYPES, "abbrev": RECORD_TYPES,
    "initial": ("person", "publication"), "nickname": ("person",),
    "reorder": ("person", "publication"), "date_style": RECORD_TYPES,
    "translit": RECORD_TYPES, "punct": RECORD_TYPES,
    "phone_style": ("person", "company"), "drop": RECORD_TYPES,
    "relocate": ("person", "company"), "surname_change": ("person", "company"),
    "id_style": RECORD_TYPES,
}
OPS = tuple(OP_TYPES)

# `year_published` has no styles to vary, so `date_style` is a no-op on publications; it
# is still a legal member of a publication family, it simply does nothing there.
TYPO_FIELDS = {"person": ("name", "street", "employer"),
               "company": ("name", "street"),
               "publication": ("name", "author", "venue")}   # title, first author, venue
DROPPABLE = {"person": ("employer", "telephone"),
             "company": ("sector", "telephone"),
             "publication": ("volume", "pages")}


def apply_op(op: str, rec: dict, rng: random.Random) -> None:
    t, st = rec["_type"], rec["_style"]
    if t not in OP_TYPES[op]:
        return
    if op == "typo":
        st["typo_field"] = rng.choice(TYPO_FIELDS[t])
        st["typo_seed"] = rng.randrange(1 << 30)
    elif op == "case":
        st["case"] = rng.choice(("upper", "lower"))
    elif op == "abbrev":
        st["abbrev"] = True
    elif op == "initial":
        st["given"] = "initial"
    elif op == "nickname":
        st["given"] = "nickname"
        st["nick_i"] = rng.randrange(1, 4)
    elif op == "reorder":
        st["order"] = rng.choice(("surname_first", "surname_plain"))
    elif op == "date_style":
        st["date"] = rng.choice([s for s in DATE_STYLES if s != st.get("date")])
    elif op == "translit":
        st["translit"] = rng.randrange(1, 3)
    elif op == "punct":
        st["punct"] = True
    elif op == "phone_style":
        st["phone"] = rng.choice(PHONE_STYLES)
    elif op == "drop":
        st.setdefault("dropped", set()).add(rng.choice(DROPPABLE[t]))
    elif op == "relocate":
        rec["_address"] = _address(rng)
    elif op == "surname_change":
        if t == "company":
            # The company's version of a married name: re-registered under another legal
            # suffix. Clause 3 names exactly this ("`Holdings Limited` where the other
            # record says `Limited` is not the same company unless the registration
            # number says so"), and until this existed no company duplicate ever changed
            # its name, so "the names differ -> two companies" was never wrong, even
            # where the policy says the registration number decides.
            rec["_tail"] = rng.choice([x for x in COMPANY_TAILS if x != rec["_tail"]])
        else:
            cur = rec["_surname"]
            rec["_married"] = rng.choice([i for i in range(len(SURNAME)) if i != cur])


TRAINED_FAMILIES: tuple[tuple[str, ...], ...] = (
    ("typo",), ("case",), ("abbrev",), ("initial",), ("nickname",), ("reorder",),
    ("date_style",), ("translit",), ("punct",), ("phone_style",), ("drop",),
    ("relocate",), ("surname_change",), ("id_style",),
    ("typo", "case"), ("nickname", "date_style"), ("abbrev", "relocate"),
    ("translit", "punct"), ("initial", "id_style"), ("reorder", "drop"),
    ("surname_change", "phone_style"), ("typo", "abbrev", "date_style"),
)

# Never trained on. Every operation inside these appears alone in TRAINED_FAMILIES, so a
# drop here is a failure to compose operations the model has, not a failure to recognise
# an operation it has never met. Each is read against a trained neighbour:
# translit+reorder against translit+punct and reorder+drop; surname_change+relocate
# against surname_change+phone_style and abbrev+relocate.
#
# Two of the original six were trained families in disguise, and are replaced.
# `("nickname", "initial", "date_style")`: `initial` overwrites the given-name style
# `nickname` just set, and `date_style` changes nothing `vary_against` had not already
# changed, so on a person it *was* `("initial",)`. `("date_style", "phone_style",
# "drop")` was `("drop",)` for the same reason. See `NULL_OPS`.
HELDOUT_FAMILIES: tuple[tuple[str, ...], ...] = (
    ("translit", "reorder"),
    ("nickname", "reorder", "typo"),
    ("surname_change", "relocate"),
    ("translit", "typo", "punct"),
    ("abbrev", "id_style", "case"),
    ("drop", "case", "nickname"),
)

# Held out of train *and* test: the dev split's own unseen compositions, so checkpoint
# selection and the temperature read transfer without reading a family test measures.
# Same rule as `HELDOUT_FAMILIES` -- every operation appears alone in a trained family,
# and `combos` keeps a (record type, family) only where it composes at least two
# operations no trained family composes -- and no dev family does to any record type
# what a held-out one does (`test_dev_families_are_disjoint_from_trained_and_heldout`).
DEV_FAMILIES: tuple[tuple[str, ...], ...] = (
    ("initial", "relocate"),
    ("typo", "relocate"),
    ("case", "reorder"),
    ("abbrev", "translit", "drop"),
    ("punct", "surname_change"),
)
DEV_NOTE = "held out of train and test; a dev structure -- selects checkpoints and fits T"


def slug(family: tuple[str, ...]) -> str:
    return "_".join(family)


# An operation that does not apply to a record type is a no-op on it: a company has no
# nickname, a year of publication has no format to vary. That matters for the held-out
# families and not much else -- `("nickname", "initial", "date_style")` over a company
# record *is* `("date_style",)`, which is trained, so scoring it as held-out would be
# scoring a trained family under a held-out name.
# A company name has no romanisation to vary (`company_name` never reads `translit`), so
# `("translit",)` over a company was a baseline pair filed under a corruption's name.
NO_EFFECT = {("publication", "date_style"), ("company", "translit")}


def effective(family: tuple[str, ...], rt: str) -> tuple[str, ...]:
    return tuple(op for op in family
                 if rt in OP_TYPES[op] and (rt, op) not in NO_EFFECT)


# Operations that change nothing a baseline pair does not already vary. Every record gets
# its own random date, identifier and telephone style (`randomise_style`), and
# `vary_against` forces the date and identifier styles of the two records apart in every
# pair and every roster entry. Re-drawing one of those styles is therefore a draw from
# the distribution the baseline already has: the singleton families still train (as
# pairs that differ in formatting only), but a held-out family is not new because it
# contains one of these.
NULL_OPS = frozenset({"date_style", "id_style", "phone_style"})


def substantive(family: tuple[str, ...], rt: str) -> frozenset[str]:
    """The operations of `family` that actually move a `rt` record off the baseline."""
    eff = set(effective(family, rt)) - NULL_OPS
    if "initial" in eff:
        eff.discard("nickname")      # `initial` overwrites the given-name style
    return frozenset(eff)


def combos(rtypes: tuple[str, ...], families: tuple[tuple[str, ...], ...],
           heldout: bool) -> tuple[tuple[str, tuple[str, ...]], ...]:
    """The (record type, family) pairs a task may draw, with the degenerate ones gone.

    A held-out (record type, family) is kept only when what it does to that record type
    is a combination of at least two operations that no trained family does."""
    out = []
    for rt in rtypes:
        trained = {substantive(f, rt) for f in TRAINED_FAMILIES}
        for f in families:
            eff = effective(f, rt)
            if not eff:
                continue
            if heldout:
                sub = substantive(f, rt)
                if eff in TRAINED_FAMILIES or len(sub) < 2 or sub in trained:
                    continue
            out.append((rt, f))
    if not out:
        raise ValueError(f"no usable family for {rtypes}")
    return tuple(out)


def apply_family(family: tuple[str, ...], rec: dict, rng: random.Random) -> None:
    for op in family:
        if op == "id_style":
            rec["_style"]["id"] = rng.choice(
                {"person": NINO_STYLES, "company": REGNO_STYLES,
                 "publication": DOI_STYLES}[rec["_type"]])
        else:
            apply_op(op, rec, rng)


def randomise_style(rec: dict, rng: random.Random) -> None:
    """The baseline formatting of a record, before any corruption. Two records of two
    different systems disagree about formatting whether or not they are the same entity,
    so this runs on every record, not only on corrupted ones."""
    st = rec["_style"]
    st["date"] = rng.choice(DATE_STYLES)
    st["id"] = rng.choice({"person": NINO_STYLES, "company": REGNO_STYLES,
                           "publication": DOI_STYLES}[rec["_type"]])
    st["phone"] = rng.choice(PHONE_STYLES)


# ---- the policy, executed ---------------------------------------------------------------

def verdict(a: dict, b: dict) -> tuple[str | None, str]:
    """Run the policy over the two records. -> (option key or None, decisive clause).

    `None` is clause 5: the records do not settle it. The label the corpus carries is
    this function's output, never the construction that produced the pair -- so a
    corruption that accidentally destroyed the evidence is caught here rather than
    shipped with a label the state does not support.
    """
    t = a["_type"]
    idf, datef = ID_FIELD[t], DATE_FIELD[t]
    sa, sb = a["_surf"], b["_surf"]
    if idf in sa and idf in sb:
        same = norm_id(sa[idf]) == norm_id(sb[idf])
        return (OPT_ONE if same else OPT_TWO), "strong_identifier"
    if datef in sa and datef in sb:
        if parse_date(sa[datef]) != parse_date(sb[datef]):
            return OPT_TWO, "fallback_date"
        return (OPT_ONE if name_key(a) == name_key(b) else OPT_TWO), "fallback_date"
    return None, "names_alone"


def materialise(rec: dict, rng: random.Random) -> dict:
    rec["_surf"] = surface(rec, rng)
    return rec


NAME_FIELD = {"person": "full_name", "company": "legal_name",
              "publication": "title"}


def _surface_name(rec: dict) -> tuple:
    """The deciding name as a *reader* sees it: case and punctuation folded away, and
    for a publication the first author beside the title."""
    surf = rec["_surf"]
    out = [depunct(str(surf.get(NAME_FIELD[rec["_type"]], ""))).lower().strip()]
    if rec["_type"] == "publication":
        authors = surf.get("authors") or [""]
        out.append(depunct(str(authors[0])).lower().strip())
    return tuple(out)


def _evidence(query: dict, cand: dict) -> tuple:
    """What the policy actually reads off the two surfaces, as a hashable tuple.

    `verdict` compares hidden indices, so it separates `Theodore Ozdemir` from
    `Thandiwe Ozdemir` even when both records write `T. Ozdemir` and carry the same date
    of birth. A reader cannot, and four rosters in an earlier build have two defensible
    answers for exactly that reason. Two candidates that present the same evidence must
    therefore carry the same verdict. The fold is exact-string after case and punctuation,
    which catches the collisions that actually occur; it does not claim to enumerate every
    rendering the policy calls one name.
    """
    t = query["_type"]
    idf, datef = ID_FIELD[t], DATE_FIELD[t]
    sq, sc = query["_surf"], cand["_surf"]
    if idf in sq and idf in sc:
        return ("id", norm_id(sq[idf]), norm_id(sc[idf]))
    if datef in sq and datef in sc:
        return ("date", parse_date(sq[datef]), parse_date(sc[datef]),
                _surface_name(query), _surface_name(cand))
    return ("unresolved",)


def roster_is_ambiguous(query: dict, cands: list[dict], verdicts: list) -> bool:
    seen: dict[tuple, object] = {}
    for c, v in zip(cands, verdicts):
        e = _evidence(query, c)
        if e in seen and seen[e] != v:
            return True
        seen[e] = v
    return False


def one_slip(x: str, y: str) -> bool:
    """Damerau-Levenshtein distance of at most one: the policy's "single slip"."""
    if x == y:
        return True
    if abs(len(x) - len(y)) > 1:
        return False
    if len(x) == len(y):
        d = [i for i in range(len(x)) if x[i] != y[i]]
        return len(d) == 1 or (len(d) == 2 and d[1] == d[0] + 1
                                and x[d[0]] == y[d[1]] and x[d[1]] == y[d[0]])
    if len(x) > len(y):
        x, y = y, x
    return any(y[:i] + y[i + 1:] == x for i in range(len(y)))


def _shown_given(g: int, rec: dict, author: bool) -> str:
    """The given name as the record writes it, before case, punctuation or a slip."""
    st = rec["_style"].get("given", "full")
    if st == "initial":
        return GIVEN[g][0][0] + "."
    if author or st == "full":
        return GIVEN[g][0]
    return GIVEN[g][rec["_style"].get("nick_i", 1) % len(GIVEN[g])]


def _givens_confusable(ga: int, ta: str, gb: int, tb: str) -> bool:
    """Two *different* given names that clause 3's allowances would reconcile.

    `T.` is the initial of Theodore and of Thandiwe; `Mick` (Michael) is one slip from
    `Nick` (Nikolaos) and `Rick` (Richard). A twin written `T. Ozdemir` beside a
    `Theodore Ozdemir` with the same date of birth is one person under the policy as
    written, whatever the generator knows about her; so is `ZHĀNG, Mick` beside
    `Richard Zhāng`, by way of `Rick` and one slip."""
    if ga == gb:
        return False
    if ta.endswith(".") and ta[0] == GIVEN[gb][0][0]:
        return True
    if tb.endswith(".") and tb[0] == GIVEN[ga][0][0]:
        return True
    return (any(one_slip(ta.lower(), f.lower()) for f in GIVEN[gb])
            or any(one_slip(tb.lower(), f.lower()) for f in GIVEN[ga]))


def names_confusable(a: dict, b: dict) -> bool:
    """True when the hidden names differ but the written ones are reconcilable."""
    t = a["_type"]
    if t == "person":
        sur_a = a["_married"] if a["_married"] is not None else a["_surname"]
        sur_b = b["_married"] if b["_married"] is not None else b["_surname"]
        if sur_a != sur_b:
            return False
        return _givens_confusable(a["_given"], _shown_given(a["_given"], a, False),
                                  b["_given"], _shown_given(b["_given"], b, False))
    if t == "publication":
        if a["_title"] != b["_title"] or a["_part"] != b["_part"]:
            return False
        (ga, sa), (gb, sb) = a["_authors"][0], b["_authors"][0]
        if sa != sb:
            return False
        return _givens_confusable(ga, _shown_given(ga, a, True),
                                  gb, _shown_given(gb, b, True))
    return False


def pair_is_unreadable(a: dict, b: dict) -> bool:
    """True when clause 2 falls through to the names and the policy's own allowances make
    two different entities read as one name: the same written name, or an initial or a
    one-slip spelling that reaches the other's given name. Nothing in the state supports
    a `two_entities` label there, so the draw is discarded rather than shipped."""
    t = a["_type"]
    idf, datef = ID_FIELD[t], DATE_FIELD[t]
    sa, sb = a["_surf"], b["_surf"]
    if idf in sa and idf in sb:
        return False
    if not (datef in sa and datef in sb):
        return False
    if parse_date(sa[datef]) != parse_date(sb[datef]):
        return False
    if name_key(a) == name_key(b):
        return False
    return _surface_name(a) == _surface_name(b) or names_confusable(a, b)


