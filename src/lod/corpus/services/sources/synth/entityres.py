_MONTHS = ("January", "February", "March", "April", "May", "June", "July", "August",
           "September", "October", "November", "December")


def fmt_date(d: date, style: str) -> str:
    if style == "iso":
        return d.isoformat()
    if style == "dmy_slash":
        return f"{d.day:02d}/{d.month:02d}/{d.year}"
    if style == "dmy_dot":
        return f"{d.day:02d}.{d.month:02d}.{d.year}"
    if style == "long":
        return f"{d.day} {_MONTHS[d.month - 1]} {d.year}"
    if style == "short":
        return f"{d.day:02d} {_MONTHS[d.month - 1][:3]} {d.year}"
    return f"{_MONTHS[d.month - 1]} {d.day}, {d.year}"  # "us_long"


DATE_STYLES = ("iso", "dmy_slash", "dmy_dot", "long", "short", "us_long")

_ISO = re.compile(r"^(\d{4})-(\d{2})-(\d{2})$")
_NUM = re.compile(r"^(\d{1,2})[/.](\d{1,2})[/.](\d{4})$")
_LONG = re.compile(r"^(\d{1,2})\s+([A-Za-z]+)\s+(\d{4})$")
_USL = re.compile(r"^([A-Za-z]+)\s+(\d{1,2}),\s*(\d{4})$")


def parse_date(text: str) -> tuple[int, int, int]:
    """Any style this module writes, back to (y, m, d). Numeric forms are day first,
    which is the convention the policy states rather than one the reader must guess."""
    s = str(text).strip()
    if s.isdigit() and len(s) == 4:            # a publication year
        return (int(s), 0, 0)
    m = _ISO.match(s)
    if m:
        return (int(m[1]), int(m[2]), int(m[3]))
    m = _NUM.match(s)
    if m:
        return (int(m[3]), int(m[2]), int(m[1]))
    m = _LONG.match(s)
    if m:
        return (int(m[3]), _month(m[2]), int(m[1]))
    m = _USL.match(s)
    if m:
        return (int(m[3]), _month(m[1]), int(m[2]))
    raise ValueError(f"unparsable date {text!r}")


def _month(word: str) -> int:
    w = word[:3].lower()
    for i, name in enumerate(_MONTHS, start=1):
        if name[:3].lower() == w:
            return i
    raise ValueError(f"unknown month {word!r}")


