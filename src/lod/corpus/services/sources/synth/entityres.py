def norm_id(text: str) -> str:
    """Identifiers compare after their punctuation, case and URL dress are removed."""
    s = str(text).strip().lower()
    for lead in ("https://doi.org/", "http://doi.org/", "doi:", "doi "):
        if s.startswith(lead):
            s = s[len(lead):]
    return re.sub(r"[^0-9a-z]", "", s)


