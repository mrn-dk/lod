    out.append(RealTask(
        row=ROW, name="entityres_dev_roster", licence=LICENCE, url=URL,
        load=_loader("roster", RECORD_TYPES, DEV_FAMILIES, "entityres_dev_roster", 5502),
        real=False, per_example_options=True, family="entityres_dev",
        force_split="devreal",
        notes="dev-held families over rosters; " + DEV_NOTE))
