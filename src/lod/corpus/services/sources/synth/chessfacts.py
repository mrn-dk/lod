def _b_legal_move(boards, rng, want) -> Spec | None:
    import chess

    board = boards[0]
    legal = list(board.legal_moves)
    if not legal:
        return None
    legal_set = {m.uci() for m in legal}
    illegal = []
    # the interesting illegal move is one that is pseudo-legal and leaves the king
    # attacked -- "looks like a move, is not one". Those come first.
    for m in board.pseudo_legal_moves:
        if m.uci() not in legal_set:
            illegal.append(m)
    if not illegal:
        for sq in board.piece_map():
            if board.piece_at(sq).color != board.turn:
                continue
            for to in rng.sample(range(64), 12):
                m = chess.Move(sq, to)
                if sq != to and m.uci() not in legal_set:
                    illegal.append(m)

    def key(m):
        p = board.piece_at(m.from_square)
        return (_pclass(p.piece_type) if p else -1,
                bool(board.attackers(not board.turn, m.to_square)),
                board.is_check(), min(len(legal) // 15, 2), board.gives_check(m),
                board.is_capture(m))
    # matched on piece class and whether the destination is attacked (0.757 from shallow
    # features before matching); a pin stays out of the key -- it is the rule itself
    mv = _matched([(m, True, key(m)) for m in legal] + [(m, False, key(m)) for m in illegal],
                  want, rng)
    if mv is None:
        return None
    ok = mv in legal
    side = "White" if board.turn == chess.WHITE else "Black"
    return Spec(
        boards=[board], keys=None,
        question=_ask("legal_move", [board], mover=side, move=mv.uci()),
        options=["no", "yes"],
        descriptions=[f"{mv.uci()} is not a legal move here.",
                      f"{mv.uci()} is a legal move here."],
        instructions=_instructions("attacked", "legal", "check"),
        target=int(ok), meta={"move": mv.uci()})


