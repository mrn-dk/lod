_BANK = None


def _ask(family: str, boards: list, key_extra: str = "", **slots: str) -> str:
    """The question for one record: a bank phrasing of the family's template, filled.

    The key is the record's own identity -- its positions and slot values -- so a rebuild
    picks the same wording and two records of one family usually pick different ones.
    """
    global _BANK
    if _BANK is None:
        from lod.phrasings import PhrasingBank
        _BANK = PhrasingBank.load()
    key = "|".join(b.fen() for b in boards) + "|" + "|".join(
        f"{k}={v}" for k, v in sorted(slots.items())) + "|" + key_extra
    return _BANK.pick(f"d04.chessfact_{family}", TEMPLATES[family], key).format(**slots)


# ---- position pool -------------------------------------------------------------------

_POOL: list[str] | None = None
_POOL_MIX: dict[str, int] = {}


def _reserved_pool(puzzle_id: str) -> bool:
    """Row 13's partition, reproduced so the puzzle half drawn here is the *trained* half.

    `lichess._reserved_pool` is the authority; this is deliberately a copy rather than an
    import, because importing it would couple a generator to a real loader that raises
    when its cache is short. `tests/test_chessfacts_source.py` asserts the two agree on
    every cached puzzle.
    """
    return hashlib.sha256(str(puzzle_id).encode()).digest()[0] % 2 == 1


def _puzzle_positions(limit: int) -> list[str]:
    """FENs from lichess puzzles, from the trained half, after the setup move.

    A lichess puzzle's FEN is the position *before* the opponent's move; the first entry
    of `Moves` is that move, and the puzzle proper starts after it. Playing it is both
    the right position to ask about and the thing that guarantees no FEN emitted by this
    row is a FEN any lichess task states.
    """
    import chess

    key = POOL_KEY if store.has(POOL_KEY) else PUZZLE_KEY
    if not store.has(key):
        return []
    out: list[str] = []
    for raw in store.load(key):
        if len(out) >= limit:
            break
        pid = raw.get("PuzzleId")
        if pid is None or _reserved_pool(pid):
            continue
        fen, moves = raw.get("FEN"), str(raw.get("Moves") or "").split()
        if not fen or not moves:
            continue
        try:
            board = chess.Board(fen)
            board.push(chess.Move.from_uci(moves[0]))
        except (ValueError, AssertionError):
            continue
        if board.is_game_over() or not any(board.legal_moves):
            continue
        out.append(board.fen())
    return out


def _playout_positions(limit: int, seed: int) -> list[str]:
    """Ordinary positions: random legal moves from the start, stopped at a random ply."""
    import chess

    rng = random.Random(seed)
    out: list[str] = []
    while len(out) < limit:
        board = chess.Board()
        plies = rng.randint(*PLAYOUT_PLIES)
        for _ in range(plies):
            moves = list(board.legal_moves)
            if not moves:
                break
            board.push(rng.choice(moves))
        if board.is_game_over() or not any(board.legal_moves):
            continue
        if len(board.piece_map()) < 8:          # a bare endgame has little to ask about
            continue
        out.append(board.fen())
    return out


def _reserved_fen(fen: str) -> bool:
    """Which half of the pool a position belongs to, stable under rebuilds."""
    return hashlib.sha256(fen.encode()).digest()[0] % 2 == 1


def _dev_fen(fen: str) -> bool:
    """A quarter of the *unreserved* half, for `DEV_HELDOUT`. Taken from the trained side
    so that test's half -- and so every testreal state -- is exactly what it was."""
    h = hashlib.sha256(fen.encode()).digest()
    return h[0] % 2 == 0 and h[1] % 4 == 0


def dev_pool() -> list[str]:
    """The dev families' positions: disjoint from `pool(reserved=True)` and from
    `pool(reserved=False)`, for the reason `pool` gives."""
    return [f for f in pool() if _dev_fen(f)]


def pool(reserved: bool | None = None) -> list[str]:
    """The FEN pool. `reserved` selects the held-out half, `False` the trained half
    (less `dev_pool()`, which the dev families draw from).

    **The halves must be disjoint.** Eighteen families asking eighteen questions about
    one pool of positions means a trained task and a held-out task state the same board
    in the same rendering, and `dedup_against_train` -- doing exactly its job -- deletes
    the held-out copy. Measured on the first build of this row: 1,947 of 5,000 testreal
    examples dropped, 39 % of the holdout, silently. `lichess.py` partitions its puzzles
    by `PuzzleId` for the same reason and `base.disjoint_slice` records the same
    accident on three other rows.

    `None` returns everything, for the tests and the contamination audit.
    """
    global _POOL, _POOL_MIX
    if _POOL is None:
        puzzles = _puzzle_positions(N_PUZZLE_POSITIONS)
        plays = _playout_positions(N_PLAYOUT_POSITIONS, seed=43_2026)
        _POOL_MIX = {"puzzle": len(puzzles), "playout": len(plays)}
        merged: list[str] = []
        i = j = 0
        # interleave in proportion, so a task that stops early still sees both kinds
        while i < len(puzzles) or j < len(plays):
            if i < len(puzzles):
                merged.append(puzzles[i]); i += 1
            for _ in range(3):
                if j < len(plays):
                    merged.append(plays[j]); j += 1
        _POOL = merged
    if reserved is None:
        return _POOL
    return [f for f in _POOL if _reserved_fen(f) is reserved and not _dev_fen(f)]


def pool_mix() -> dict[str, int]:
    pool()
    return dict(_POOL_MIX)


def reset_pool() -> None:
    global _POOL, _POOL_MIX
    _POOL, _POOL_MIX = None, {}


# ---- rendering -----------------------------------------------------------------------

def _piece_map(board) -> dict[str, str]:
    import chess

    out = {}
    for sq in sorted(board.piece_map(), key=lambda s: (chess.square_rank(s), chess.square_file(s))):
        p = board.piece_at(sq)
        out[chess.square_name(sq)] = f"{'white' if p.color else 'black'} {PIECE_WORDS[p.piece_type]}"
    return out


def _ascii(board) -> str:
    import chess

    rows = []
    for rank in range(7, -1, -1):
        cells = []
        for file in range(8):
            p = board.piece_at(chess.square(file, rank))
            cells.append(p.symbol() if p else ".")
        rows.append(f"{rank + 1} " + " ".join(cells))
    rows.append("  a b c d e f g h")
    return "\n".join(rows)


def _one(board, shape: str) -> dict[str, Any]:
    """One position as a dict. Every shape carries the same information."""
    import chess

    fields = board.fen().split()
    d: dict[str, Any] = {"side_to_move": "white" if board.turn == chess.WHITE else "black",
                         "castling_rights": fields[2], "en_passant_target": fields[3]}
    if shape in ("fen", "both"):
        d["fen"] = board.fen()
    if shape in ("map", "both"):
        d["pieces"] = _piece_map(board)
    if shape in ("ascii", "both"):
        d["board"] = _ascii(board)
        d["board_key"] = ("upper case is white, lower case is black; "
                          "P pawn N knight B bishop R rook Q queen K king; "
                          "a dot is an empty square")
    return d


def render(boards: list, keys: list[str] | None, shape: str) -> str:
    if keys is None:
        return json.dumps(_one(boards[0], shape), ensure_ascii=False, indent=1)
    return json.dumps({k: _one(b, shape) for k, b in zip(keys, boards)},
                      ensure_ascii=False, indent=1)


# ---- a built question, before it is rendered ------------------------------------------

@dataclass
class Spec:
    """Everything a question is, with the position still a `chess.Board`.

    Keeping this separate from the text is what lets the same values be rendered four
    ways and lets a test assert the target does not move when the rendering does.
    """
    boards: list
    keys: list[str] | None
    question: str
    options: list[str]
    target: int
    descriptions: list[str]
    instructions: str
    meta: dict[str, Any] = field(default_factory=dict)


def _example(spec: Spec, task: str, shape: str, qid: str = "q0") -> Example:
    meta = dict(spec.meta)
    meta["shape"] = shape
    return Example(
        task=task,
        state=render(spec.boards, spec.keys, shape),
        questions=[Question(id=qid, question=spec.question, options=list(spec.options),
                            target=spec.target, meta=meta,
                            instructions=spec.instructions,
                            descriptions=list(spec.descriptions))])


# ---- board helpers --------------------------------------------------------------------

def _defenders(board, sq) -> list[int]:
    p = board.piece_at(sq)
    if p is None:
        return []
    return [a for a in board.attackers(p.color, sq) if a != sq]


def _enemies(board, sq) -> list[int]:
    p = board.piece_at(sq)
    if p is None:
        return []
    return list(board.attackers(not p.color, sq))


def _is_hanging(board, sq) -> bool:
    return bool(_enemies(board, sq)) and not _defenders(board, sq)


def _pclass(piece_type: int) -> int:
    """Coarse piece class for matching keys: pawn, minor, major."""
    return 0 if piece_type == 1 else 1 if piece_type in (2, 3) else 2


# Per-(family, split) tally of accepted answers per shallow-feature key; see `_matched`.
_LEDGER: dict | None = None
_SEEN: dict = {}


def clear_balance() -> None:
    """No tally: builders fall back to per-board matching."""
    global _LEDGER
    _LEDGER = None


def reset_balance() -> None:
    """Start a fresh answer-per-key tally. The loader calls this once per task."""
    global _LEDGER, _SEEN
    _LEDGER = {}
    _SEEN = {}


def _matched(cands, want, rng, per_board: bool = False):
    """Answer-blind shallow features, balanced across the whole task.

    With a tally active (`reset_balance`): take a candidate with label `want` only if
    its key has not already had more `want` answers than the other answer, so every key
    ends with as many yes as no (+-1) across the task and says nothing about the answer.
    A board need not hold both answers under one key, which is what let the keys carry
    every predictive feature without starving the family.

    Without a tally (direct calls, tests): fall back to per-board matching -- a key that
    occurs with both labels on this board, chosen uniformly.

    Without it, the composite families were answerable from partial computations
    (measured by a shortcut audit): `hanging_defender` from "is any defender
    attacked" at 0.82, `defended_by_pinned` from defender count and attack status at
    0.88, `after_move_attacked` from whether the square was attacked BEFORE the move at
    0.91. One earlier model scored 0.993 on held-out `hanging_defender` by riding that cue
    and another 0.139 by riding its opposite -- the family measured which way a model
    leaned, not the composition it is named for.

    `per_board=True` forces per-board matching. The rare compositions need it: a
    `hanging_defender` "no" whose key matches a "yes" needs one defender attacked and a
    DIFFERENT one undefended, which real games barely produce, so the task-wide tally
    refused nearly every "yes" (9 examples in 180,000 boards).

    cands: [(choice, label, key)]. Returns a choice, or None.
    """
    if _LEDGER is not None and not per_board:
        # Every candidate seen counts, taken or not. A key may take a `want` example only
        # when the OTHER answer has been seen under it more often than `want` has been
        # taken: a key that only ever occurs with one answer never contributes. Without
        # that, each such key added one unmatched example, and hundreds of sparse keys
        # summed to a clear correlation (0.688 on defended_by_pinned).
        for _, lab, k in cands:
            _SEEN[(k, bool(lab))] = _SEEN.get((k, bool(lab)), 0) + 1
        w = bool(want)
        ok = [(c, k) for c, lab, k in cands if bool(lab) == w
              and _LEDGER.get((k, w), 0) <= _LEDGER.get((k, not w), 0)
              and _SEEN.get((k, not w), 0) > _LEDGER.get((k, w), 0)]
        if not ok:
            return None
        choice, k = ok[rng.randrange(len(ok))]
        _LEDGER[(k, bool(want))] = _LEDGER.get((k, bool(want)), 0) + 1
        return choice
    yes_keys = {k for _, lab, k in cands if lab}
    no_keys = {k for _, lab, k in cands if not lab}
    shared = sorted(yes_keys & no_keys, key=repr)
    if not shared:
        return None
    key = rng.choice(shared)
    pick = [c for c, lab, k in cands if bool(lab) == bool(want) and k == key]
    return rng.choice(pick)


def _material(board) -> tuple[int, int]:
    w = b = 0
    for _, p in board.piece_map().items():
        v = PIECE_VALUES[p.piece_type]
        if p.color:
            w += v
        else:
            b += v
    return w, b


def _pinned_squares(board, color) -> list[int]:
    return [sq for sq in board.piece_map()
            if board.piece_at(sq).color == color and board.is_pinned(color, sq)]


def _name(board, sq) -> str:
    import chess

    p = board.piece_at(sq)
    return f"{'white' if p.color else 'black'} {PIECE_WORDS[p.piece_type]} on {chess.square_name(sq)}"


def _sq(sq) -> str:
    import chess

    return chess.square_name(sq)


def _shuffled(rng: random.Random, items: list) -> list:
    out = list(items)
    rng.shuffle(out)
    return out


def _place(rng, options, descs, gold_idx) -> tuple[list[str], list[str], int]:
    """Shuffle an option list, carrying its descriptions and its gold index with it."""
    order = list(range(len(options)))
    rng.shuffle(order)
    return ([options[i] for i in order], [descs[i] for i in order],
            order.index(gold_idx))


