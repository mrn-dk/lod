    sq = _matched(cands, want, rng, per_board=True)
    if sq is None:
        return None
    return Spec(
        boards=[board], keys=None,
        question=_ask("hanging_defender", [board], square=_sq(sq)),
        options=["no", "yes"],
        descriptions=[f"Every piece that defends {_sq(sq)} is either unattacked or "
                      f"defended by a piece of its own colour.",
                      f"At least one piece that defends {_sq(sq)} is attacked by the "
                      f"other side and has no defender of its own."],
        instructions=_instructions("attacked", "defended", "undefended"),
        target=int(want), meta={"square": _sq(sq)})


