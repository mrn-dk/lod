def _b_defended_by_pinned(boards, rng, want) -> Spec | None:
    """Two hops: the defenders of a square, and whether any of them is pinned.

    Both answers are drawn from squares that *have* a defender, so `no` means "it is
    defended, and none of its defenders is pinned" rather than "nothing defends it".
    """
    board = boards[0]
    cands = []
    for sq in board.piece_map():
        p = board.piece_at(sq)
        if p.piece_type == 6:
            continue
        ds = _defenders(board, sq)
        if not ds:
            continue
        label = any(board.is_pinned(p.color, d) for d in ds)
        # the features that predicted the answer (0.875 before matching), and no more: a
        # seven-part key left ~1 % of boards qualifying and the family repeating them
        key = (min(len(ds), 2), any(_enemies(board, d) for d in ds),
               any(not _defenders(board, d) for d in ds),
               min(len(_enemies(board, sq)), 2), board.turn == p.color,
               board.is_pinned(p.color, sq), _pclass(p.piece_type),
               min(len(board.piece_map()) // 12, 2))
        cands.append((sq, label, key))
    sq = _matched(cands, want, rng)
    if sq is None:
        return None
    return Spec(
        boards=[board], keys=None,
        question=_ask("defended_by_pinned", [board], square=_sq(sq)),
        options=["no", "yes"],
        descriptions=[f"Every piece that defends {_sq(sq)} is free to move; none of them "
                      f"is pinned against its own king.",
                      f"At least one piece that defends {_sq(sq)} is itself pinned "
                      f"against its own king."],
        instructions=_instructions("attacked", "defended", "pinned"),
        target=int(want), meta={"square": _sq(sq), "n_defenders": len(_defenders(board, sq))})


def _b_hanging_square(boards, rng, want, split: str) -> Spec | None:
    """Which listed piece is attacked and undefended -- or none of them.

    Every option is a square that carries a piece of the same colour and appears in the
    state, so "the only option present in the state" is never a signal.
    """
    board = boards[0]
    color = rng.choice([True, False])
    squares = [sq for sq in board.piece_map()
               if board.piece_at(sq).color == color and board.piece_at(sq).piece_type != 6]
    if len(squares) < 5:
        return None
    hang = [sq for sq in squares if _is_hanging(board, sq)]
    safe = [sq for sq in squares if not _is_hanging(board, sq)]
    # the hanging piece occupies one of the k slots when there is one, so the option
    # count is bounded by the *safe* squares available, not by the piece count
    hi = min(7, len(safe) + (1 if want else 0))
    if hi < 4 or (want and not hang):
        return None
    k = rng.randint(4, hi)
    if want:                       # exactly one hanging piece among the options
        chosen = [rng.choice(hang)] + rng.sample(safe, k - 1)
        gold = 0
    else:                          # none of them: the sentinel is the answer
        chosen = rng.sample(safe, k)
        gold = None
    opts = [_sq(s) for s in chosen]
    descs = [f"The {_name(board, s)}." for s in chosen]
    key, desc = sentinel.sample(rng, split)
    opts.append(key)
    descs.append(desc)
    gold_idx = len(opts) - 1 if gold is None else gold
    opts, descs, target = _place(rng, opts, descs, gold_idx)
    side = "white" if color else "black"
    return Spec(
        boards=[board], keys=None,
        question=_ask("hanging_square", [board], side=side, key_extra="|".join(opts)),
        options=opts, descriptions=descs,
        instructions=_instructions("attacked", "defended", "undefended"),
        target=target, meta={"sentinel": gold is None, "n_options": len(opts)})


def _b_most_attacked(boards, rng, want) -> Spec | None:
    """Extremum over an attack map: which listed piece the enemy hits most often."""
    board = boards[0]
    color = rng.choice([True, False])
    squares = [sq for sq in board.piece_map()
               if board.piece_at(sq).color == color and board.piece_at(sq).piece_type != 6]
    if len(squares) < 4:
        return None
    k = rng.randint(4, min(6, len(squares)))
    chosen = rng.sample(squares, k)
    counts = [len(_enemies(board, s)) for s in chosen]
    top = max(counts)
    if top < 1 or counts.count(top) != 1:
        return None                 # a tie has no single answer: drop it
    gold = counts.index(top)
    opts = [_sq(s) for s in chosen]
    descs = [f"The {_name(board, s)}." for s in chosen]
    opts, descs, target = _place(rng, opts, descs, gold)
    side = "white" if color else "black"
    other = "black" if color else "white"
    return Spec(
        boards=[board], keys=None,
        question=_ask("most_attacked", [board], side=side, other=other,
                      key_extra="|".join(opts)),
        options=opts, descriptions=descs,
        instructions=_instructions("attacked"),
        target=target, meta={"counts": sorted(counts, reverse=True)})


_POS_KEYS = ["position_a", "position_b", "position_c", "position_d"]


def _multi(boards, values, question, instr, rng, margin: int,
           desc: Callable[[str], str]) -> Spec | None:
    top = max(values)
    if values.count(top) != 1:
        return None
    rest = sorted(values, reverse=True)[1]
    if top - rest < margin:
        return None                 # a one-move gap is noise, not an extremum
    keys = list(_POS_KEYS[:len(boards)])
    return Spec(
        boards=list(boards), keys=keys,
        question=question, options=list(keys),
        descriptions=[desc(k) for k in keys],
        instructions=instr, target=values.index(top),
        meta={"values": list(values)})


