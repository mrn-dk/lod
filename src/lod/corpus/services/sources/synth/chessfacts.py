"""Row 43 -- chess positions as facts (domain 4).

A formal state with no natural-language shortcut, asked about as *facts to compose*
rather than as a search problem.

The distinction is the whole design. "Find the winning move" is search depth, and a
0.6B prefill-only scorer does not do lookahead in one forward pass -- an earlier model
sat at chance on every balanced lichess theme while reporting 0.80 confidence on two of
them, which is the confidently-wrong behaviour this project most wants gone. Training a
scorer to guess a best move teaches exactly that. So every question here is an **exact
lookup over the position, composed two or three deep**, and python-chess derives the
answer definitively:

    attacked     which pieces attack a square
    defended     which pieces of the occupant's own colour attack it
    pinned       an enemy slider attacks it along a line holding its own king
    legal        is this move in `legal_moves`
    gives_check  does this move leave the other king attacked
    material     the usual 1/3/3/5/9 sum
    mobility     how many legal moves the side to move has
    count        how many of a set satisfy a predicate
    extremum     which of several positions, or pieces, maximises one of the above

Nothing else. No evaluation, no "best move", no lookahead past one legal move.

**The holdout is a composition depth, not a sample.** Thirteen families of depth 1 and 2
are trained; five families of depth 3 go to `testreal` and are never trained on. Every
primitive in a held-out family appears alone, or in a two-deep pair, in a trained family
-- `test_chessfacts_source.py` asserts it, primitive by primitive, and names the trained
control each held-out family is paired against. That asks the transfer question worth
asking: not "have you met a discovered check" but "can you compose two lookups you know".
Three more depth-3 families (`DEV_HELDOUT`) go to `devreal`, built the same way and
disjoint from test's, on their own quarter of the trained half of the position pool
(`dev_pool`): the split that selects checkpoints and fits T then measures transfer too.

**The definitions are input, not assumed knowledge.** What "defended" and "pinned" mean
is written into the option criteria and the instructions, the way `rules.py` writes the
rule into its criteria. A model that has to be *told* what a pin is and then apply it to
a board is the bet this corpus is making; a model that has memorised the word `pin` from
lichess theme labels is the thing it is trying not to be.

**Two renderings of the same values.** Each position is emitted as a FEN, as a JSON
square -> piece map, as an ASCII board, or as a combination, drawn independently of the
question. The label is computed from the `chess.Board`, never from the text, so the same
question in another shape is the same question and not a harder exercise in parsing FEN.

**Seeds.** A mix, on purpose. Real lichess puzzle positions are tactically dense and
unusual; positions from random legal playouts are ordinary. A model that only ever sees
tactical positions learns a skewed prior about how often anything is pinned or hanging.
The puzzle half is drawn only from the *trained* half of row 13's puzzle pool
(`lichess._reserved_pool`), and the puzzle's first move -- the opponent move that sets
the puzzle -- is played before the position is used, so no FEN emitted here is a FEN in
any lichess task, reserved or trained. `tests/test_chessfacts_source.py` measures that
overlap and asserts it is zero: row 13 reserves eight themes to `testreal`, and reusing
their positions would leak a held-out eval set into training.

`chess` is imported **inside** the loaders, the way `gefs.py` imports xarray, so
`pytest`, `--help` and every build that does not select row 43 run without the extra.
The build box needs `uv sync --extra chess`.
"""

