def _b_after_move_attacked(boards, rng, want) -> Spec | None:
    """One legal move, then a lookup on a square the move did not touch.

    The square asked about is never the move's origin or destination. The first version of
    this family asked *which piece is giving check* after the move, and the answer was the
    move's own destination square in every direct check -- so the move written in the
    question contained the gold option verbatim, and the whole family was 100 % solvable
    by copying the last two characters of the move. That is the row 36 failure exactly.
    """
    import chess

    board = boards[0]
    legal = list(board.legal_moves)
    if not legal:
        return None
    rng.shuffle(legal)
    for mv in legal[:20]:
        after = board.copy(stack=False)
        mover = after.turn
        after.push(mv)
        touched = {mv.from_square, mv.to_square}
        cands = [(sq, bool(after.attackers(mover, sq)),
                  # attacked BEFORE the move, and the piece: the answer must not be
                  # readable off the position as given
                  (bool(board.attackers(mover, sq)), after.piece_at(sq).piece_type))
                 for sq in after.piece_map()
                 if sq not in touched and after.piece_at(sq).piece_type != 6
                 and after.piece_at(sq).color != mover]
        sq = _matched(cands, want, rng)
        if sq is None:
            continue
        side = "White" if mover == chess.WHITE else "Black"
        return Spec(
            boards=[board], keys=None,
            question=_ask("after_move_attacked", [board], mover=side, move=mv.uci(),
                          square=_sq(sq), side=side.lower()),
            options=["no", "yes"],
            descriptions=[f"After {mv.uci()}, no {side.lower()} piece attacks {_sq(sq)}.",
                          f"After {mv.uci()}, at least one {side.lower()} piece attacks "
                          f"{_sq(sq)}."],
            instructions=_instructions("attacked", "legal"),
            target=int(want), meta={"move": mv.uci(), "square": _sq(sq)})
    return None


