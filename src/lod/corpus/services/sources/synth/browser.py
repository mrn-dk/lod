OWNERS = tuple(f"{c}. {n}" for n in SURNAMES for c in "ABCDEFGHJKLMNPRSTVW")
# Not "open": every control is labelled "Open <ref>", so a goal naming Status 'open' matched
# every record to a case-blind reader (4.4 % of click questions).
STATUSES = ("active", "pending", "settled", "on hold", "cancelled", "escalated")

# One pool of page titles for every layout. Titles used to name the layout -- "Billing
# wizard", "Search results for billing", "Billing table", "Billing settings" -- and the
# goal of `goal_reached` describes the layout, so "does a title word occur in the goal"
# scored 0.81 on that question against a 0.50 chance, and it would have carried straight
# over to the held-out layouts ("X wizard", "X log") without reading any structure.
TITLE_FORMS = ("{T}", "{T} | Console", "Console / {T}", "{T} workspace", "{T} overview")


def _title(rng: random.Random, topic: str) -> str:
    return rng.choice(TITLE_FORMS).format(T=topic.title())


def _rng(seed: int, salt: str) -> random.Random:
    return random.Random(f"{seed}:{salt}")


def _node(role: str, name: str, **kw) -> dict:
    n = {"role": role, "name": name}
    n.update(kw)
    return n


def _slugify(text: str) -> str:
    return "".join(c.lower() if c.isalnum() else "-" for c in text).strip("-")


# ---- layouts -----------------------------------------------------------------
# Each returns (tree, controls). `controls` is the flat list of clickable nodes in
# document order; the question families index into it, so a layout only has to say
# what is on the page and where.

def _entries(rng: random.Random, n: int, topic: str) -> list[dict]:
    """n records, each an opaque control plus the attributes that identify it.

    The control label carries a reference number and nothing else. What distinguishes one
    record from another lives in sibling nodes, so a goal that names an attribute cannot
    be answered by matching the goal against the option list.
    """
    refs = rng.sample(range(1000, 9999), n)
    sites = rng.sample(SITES, n)
    owners = rng.sample(OWNERS, n)
    # Whether a record's control leads or trails its attributes, drawn once per page. Every
    # layout used to put the control last, so "the first link after the named value in the
    # serialised state" picked the gold on 100 % of `click` questions, held-out layouts
    # included (measured by a shortcut audit) -- a reader that never finds the
    # record's container scored what one that does scores, and the held-out split measured
    # nothing about arrangement. Now that proxy is right on trailing pages and wrong on
    # leading ones, and only the container says which control is the record's.
    lead = rng.random() < 0.5
    out = []
    for i in range(n):
        out.append({
            "attrs": {"Site": sites[i], "Owner": owners[i],
                      "Status": rng.choice(STATUSES), "Count": str(rng.randrange(1, 500))},
            "control": _node("link", f"Open {refs[i]}", href=f"/{topic}/{refs[i]}"),
            "noun": rng.choice(NOUNS),
            "lead": lead,
        })
    return out


def _with_control(e: dict, nodes: list[dict]) -> list[dict]:
    """A record's children: its attribute nodes, with the control before or after them."""
    return [e["control"], *nodes] if e["lead"] else [*nodes, e["control"]]


def _links(rng: random.Random, n: int, topic: str) -> list[dict]:
    return [e["control"] for e in _entries(rng, n, topic)]


def _describe(e: dict) -> str:
    return f"{e['noun']} for {e['attrs']['Owner']}, {e['attrs']['Status']}"


def _search_results(rng, topic, entries):
    items = [_node("listitem", "", children=_with_control(e, [
        _node("heading", e["attrs"]["Site"], level=3),
        _node("paragraph", _describe(e))])) for e in entries]
    return _node("document", _title(rng, topic), children=[
        _node("heading", f"{len(entries)} found", level=1),
        _node("region", topic, children=[_node("list", topic, children=items)])])


def _article(rng, topic, entries):
    body = [_node("heading", f"About {topic}", level=1),
            _node("paragraph", f"This page describes how {topic} works in the console.")]
    for i, e in enumerate(entries):
        # Unnamed: a group named after the Site above a heading naming it again put the
        # value a goal names on the page twice (8 % of click questions, with modal_dialog).
        # Leading, the control is the heading's link; trailing, the paragraph's. Nested
        # either way, so the page's length does not say which (a bare leading control made
        # leading pages ~14 characters a record shorter, and the length bucket alone
        # predicted the gold's side of the value at 0.67).
        if e["lead"]:
            kids = [_node("heading", e["attrs"]["Site"], level=2, children=[e["control"]]),
                    _node("paragraph", _describe(e))]
        else:
            kids = [_node("heading", e["attrs"]["Site"], level=2),
                    _node("paragraph", _describe(e), children=[e["control"]])]
        body.append(_node("group", "", children=kids))
    return _node("document", _title(rng, topic), children=body)


def _settings_form(rng, topic, entries):
    # No `value: ""`: an absent value is an empty field, and at eighty fields the empty
    # strings cost ~400 characters of the state budget.
    fields = [_node("textbox", f"{e['noun'].title()} {i}") for i, e in enumerate(entries)]
    title = _title(rng, topic)
    return _node("document", title, children=[
        _node("heading", title, level=1),
        _node("tablist", "panels", children=[
            _node("tab", "General", selected=True), _node("tab", "Advanced")]),
        _node("form", topic, children=fields + [_node("button", "Save changes")]),
        _node("dialog", "Discard changes?", modal=False, children=[
            _node("button", "Keep editing")])])


def _nav_menu(rng, topic, entries):
    groups, per = [], max(1, len(entries) // 3)
    for g in range(0, len(entries), per):
        kids = [_node("menuitem", e["attrs"]["Site"], children=_with_control(e, [
            _node("paragraph", _describe(e))])) for e in entries[g:g + per]]
        groups.append(_node("menu", rng.choice(TOPICS).title(), children=kids))
    return _node("document", _title(rng, topic), children=[
        _node("navigation", "main", children=groups)])


def _data_table(rng, topic, entries):
    cols = ["Site", "Owner", "Status", "Count"]
    cols = ["Action", *cols] if entries and entries[0]["lead"] else [*cols, "Action"]
    head = _node("row", "", children=[_node("columnheader", h) for h in cols])
    rows = [_node("row", "", children=_with_control(e, [
        _node("cell", e["attrs"]["Site"]), _node("cell", e["attrs"]["Owner"]),
        _node("cell", e["attrs"]["Status"]), _node("cell", e["attrs"]["Count"])]))
        for e in entries]
    return _node("document", _title(rng, topic), children=[
        _node("region", topic, children=[
            _node("table", topic, children=[head] + rows)])])


def _wizard(rng, topic, entries):  # held out
    steps = [_node("tab", f"Step {i + 1}", selected=(i == 1)) for i in range(3)]
    items = [_node("group", e["attrs"]["Site"], children=_with_control(e, [
        _node("paragraph", _describe(e))])) for e in entries]
    return _node("document", _title(rng, topic), children=[
        _node("tablist", "steps", children=steps),
        _node("group", "body", children=items),
        _node("button", "Back"), _node("button", "Next")])


def _modal_dialog(rng, topic, entries):  # held out
    # `group`, not `list`/`listitem`: this layout used to build items byte-identical to
    # `_search_results`' -- heading, paragraph, link, inside a list -- so a modal page
    # satisfied "a list of search results" as well as its own content string. 296 of
    # `browser_goal_modal_dialog`'s 4,000 questions in an earlier build were labelled `no`
    # for a goal the page did in fact show. `listitem` is now unique to `_search_results`.
    items = [_node("group", "", children=_with_control(e, [
        _node("heading", e["attrs"]["Site"], level=3),
        _node("paragraph", _describe(e))])) for e in entries]
    # The paragraph behind the dialog used to read "The page behind the dialog is inert.",
    # which is the goal string's own words; `modal: true` is what says so.
    return _node("document", _title(rng, topic), children=[
        _node("paragraph", f"This page describes how {topic} works in the console."),
        _node("dialog", "Choose a destination", modal=True, children=[
            _node("heading", "Choose a destination", level=2),
            _node("group", "destinations", children=items),
            _node("button", "Cancel")])])


def _paginated_table(rng, topic, entries):  # held out
    # Every `ATTRS` entry has to be on the page. This layout rendered Site and Owner only,
    # so a quarter of `browser_click_paginated_table` (972 of 4,000 in an earlier build)
    # asked for the record whose Status was some value the tree never showed -- an example
    # whose answer the state does not contain, on the held-out side, where it is read as a
    # failure to generalise over layout.
    per, pages = max(1, len(entries) // 3), []
    for i in range(0, len(entries), per):
        rows = [_node("row", "", children=_with_control(e, [
            _node("cell", e["attrs"]["Site"]), _node("cell", e["attrs"]["Owner"]),
            _node("cell", e["attrs"]["Status"])])) for e in entries[i:i + per]]
        pages.append(_node("region", f"Page {len(pages) + 1}",
                           children=[_node("table", topic, children=rows)]))
    return _node("document", _title(rng, topic), children=pages + [
        _node("navigation", "pagination", children=[
            _node("button", "Previous"), _node("button", "Next")])])


def _sections(rng, topic, entries) -> list[tuple[str, list[dict]]]:
    """The records split into two to four named sections, named after distinct topics.
    No topic word occurs in a site, an owner or a status, so a section name never
    collides with a value a goal names."""
    k = min(len(entries), rng.randint(2, 4))
    per = -(-len(entries) // k)
    names = [t.title() for t in rng.sample(TOPICS, k)]
    return [(names[i], entries[i * per:(i + 1) * per]) for i in range(k)
            if entries[i * per:(i + 1) * per]]


def _tabbed_panels(rng, topic, entries):  # held out of train and test (dev)
    # One tab per section and one region per tab, named alike: the pairing is what the
    # page shows. The settings form's two tabs and the wizard's steps have no region.
    secs = _sections(rng, topic, entries)
    on = rng.randrange(len(secs))
    tabs = [_node("tab", name, selected=(i == on)) for i, (name, _) in enumerate(secs)]
    panels = [_node("region", name, children=[
        _node("group", "", children=_with_control(e, [
            _node("heading", e["attrs"]["Site"], level=3),
            _node("paragraph", _describe(e))])) for e in recs]) for name, recs in secs]
    return _node("document", _title(rng, topic), children=[
        _node("tablist", "sections", children=tabs), *panels])


def _accordion(rng, topic, entries):  # held out of train and test (dev)
    # A button per section carrying `expanded`, then that section's region. No heading
    # anywhere, so the page is not an article; one or two collapsed sections carry no
    # region, as a real accordion's closed sections do.
    secs = _sections(rng, topic, entries)
    items = [[_node("button", name, expanded=True),
              # the Site is a paragraph beside the control, not the group's name: a name
              # always precedes the children, which put the gold after the value on 0.76
              # of click questions (shortcut audit, "first link after value")
              _node("region", name, children=[
                  _node("group", "", children=_with_control(e, [
                      _node("paragraph", e["attrs"]["Site"]),
                      _node("paragraph", _describe(e))])) for e in recs])]
             for name, recs in secs]
    used = {n for n, _ in secs}
    for name in rng.sample([t.title() for t in TOPICS if t.title() not in used],
                           rng.randint(1, 2)):
        items.insert(rng.randrange(len(items) + 1), [_node("button", name, expanded=False)])
    return _node("document", _title(rng, topic),
                 children=[n for item in items for n in item])


