"""Row 36 — accessibility trees, and the decisions a navigator makes on them.

The state is a page as an accessibility tree, rendered as JSON. That is the shape a
browser harness already has: roles and names, not pixels and not raw HTML, which is an
order of magnitude fewer tokens and carries the semantics a click decision needs.

Three question families, each a decision a navigator actually makes:

    click_target     the goal and the page -> which control advances toward it
    goal_reached     is the goal already satisfied here, or is another hop needed
    field_for_value  a value to enter -> which field takes it

The pages are generated rather than captured, for two reasons. The navigation tier of
the Decision Index benchmark is scored on a Wikipedia link graph, so training on real pages
from the same web would contaminate the thing it measures. And a generator can hold out
whole *layout families*, which is the split that told us anything about rule transfer:
holding out individual pages leaks, because pages of one layout are near-duplicates of each
other.

`HELDOUT_LAYOUTS` never enter training. They are built from the same controls as the
trained layouts and differ only in how those controls are arranged, so a drop on them
is a failure to generalise over structure rather than a missing widget. `DEV_LAYOUTS` are
a second, disjoint pair of arrangements built the same way, held out of training *and* of
test, for `devreal`: the split that selects checkpoints and fits T then measures transfer
over layout the way test does, without reading test's layouts.

Option counts are drawn wide on purpose. 63 % of the rest of the corpus is binary, and a
page is the natural place to learn that a choice can have eighty candidates.

Pages are built to *fit the state budget*. `ship_v4.sh` trains at `--max-state-tokens
2304`, and `packing.Packer` truncates a long state from the tail, keeping the head. A page
whose gold control sits past the cut is an example whose evidence the model never sees --
it teaches guessing, and it depresses the held-out-layout reading for a reason that has
nothing to do with structure. Measured on the first build, 13 % of `click` lost its gold
control that way. So the tree is rendered compactly and `build_page` narrows the record
count until the rendered state fits `MAX_STATE_CHARS`. The ceiling on option count is
therefore what a page can *show*, not what a draw can name.
"""

