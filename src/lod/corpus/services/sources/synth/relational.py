def _unique_ids(rng: random.Random, n: int) -> list[str]:
    out, seen = [], set()
    while len(out) < n:
        word = rng.choice(ID_WORDS)
        ref = f"{word}-{rng.randrange(1000, 9999)}"
        if ref not in seen:
            seen.add(ref)
            out.append(ref)
    return out


@dataclass
class Universe:
    chain: Chain
    width: tuple[int, ...]                     # records per level
    recs: list[list[dict]] = dc_field(default_factory=list)

    @property
    def n_levels(self) -> int:
        return len(self.chain.levels)

    def all_records(self) -> list[tuple[int, dict]]:
        return [(lv, r) for lv, group in enumerate(self.recs) for r in group]

    def by_id(self, rid: str) -> tuple[int, dict]:
        for lv, group in enumerate(self.recs):
            for r in group:
                if r["record_id"] == rid:
                    return lv, r
        raise KeyError(rid)


def make_universe(chain: Chain, rng: random.Random, width_lo: int = 3,
                  width_hi: int = 5, n_extra: int = 3) -> Universe:
    """Records for every level, ids drawn from one pool, extras as distractors.

    Marks and references are left unset: each family assigns them, because what makes a
    chain load-bearing is exactly which values sit where, and that is family-specific.
    """
    width = tuple(rng.randint(width_lo, width_hi) for _ in chain.levels)
    ids = _unique_ids(rng, sum(width))
    uni = Universe(chain, width)
    cut = 0
    for lv, n in enumerate(width):
        group = []
        pool = list(chain.extras[lv])
        rng.shuffle(pool)
        chosen = pool[:n_extra]
        for _ in range(n):
            rec = {"record_id": ids[cut]}
            cut += 1
            for a in chosen:
                rec[a.name] = a.draw(rng)
            group.append(rec)
        uni.recs.append(group)
    return uni


def wire(uni: Universe, rng: random.Random, paths: list[list[int]]) -> None:
    """Set every reference field. `paths` are index sequences that must be honoured.

    A path is a list of record *indices*, one per level, that the references have to
    follow; everything not on a path points somewhere random at the next level.
    """
    chain = uni.chain
    forced: dict[tuple[int, int], int] = {}
    for path in paths:
        for lv in range(len(path) - 1):
            forced[(lv, path[lv])] = path[lv + 1]
    for lv, step in enumerate(chain.steps):
        for i, rec in enumerate(uni.recs[lv]):
            nxt = forced.get((lv, i))
            if nxt is None:
                nxt = rng.randrange(len(uni.recs[lv + 1]))
            rec[step.field] = uni.recs[lv + 1][nxt]["record_id"]


def wire_free(uni: Universe, rng: random.Random) -> None:
    """Every reference field, with no path forced through it.

    This used to force a path and fill the rest at random, so the record a forced chain
    ends on carried one guaranteed reference *plus* its share of the random ones, and
    each of its siblings only the random share. "Pick the option whose record is
    referenced most" found the `bridge` answer 0.60-0.66 of the time against 0.14
    chance, and the `lookup` answer 0.48-0.50 against 0.26, at every hop count including
    the held-out four (measured by a shortcut audit) -- one glance at the level
    before the end, no chain followed. Here the references are drawn with nothing forced, and
    `_free_path` then picks the answer *uniformly among the records some chain reaches*,
    so how often a record is referenced says nothing about which reachable record is the
    answer.

    The records that chains from the first level pass through point at distinct records
    on the next level for as long as the widths allow, and everything else points at
    random. Left fully random, chains merge and the set of records a chain can reach
    shrinks by about a third per level, which leaves a four-hop answer only one or two
    reachable siblings to hide among.
    """
    reach = set(range(len(uni.recs[0])))
    for lv, step in enumerate(uni.chain.steps):
        src, dst = uni.recs[lv], uni.recs[lv + 1]
        live = sorted(reach)
        rng.shuffle(live)
        free = list(range(len(dst)))
        rng.shuffle(free)
        tgt = {i: (free[j] if j < len(free) else rng.randrange(len(dst)))
               for j, i in enumerate(live)}
        for i in range(len(src)):
            if i not in tgt:
                tgt[i] = rng.randrange(len(dst))
        for i, rec in enumerate(src):
            rec[step.field] = dst[tgt[i]]["record_id"]
        reach = {tgt[i] for i in live}


def _reach(uni: Universe, hops: int) -> dict[int, list[int]]:
    """{index at level `hops`: [indices of the first-level records whose chain ends there]}."""
    pos = [{r["record_id"]: i for i, r in enumerate(g)} for g in uni.recs]
    out: dict[int, list[int]] = collections.defaultdict(list)
    for r0, rec in enumerate(uni.recs[0]):
        i = r0
        for k in range(hops):
            i = pos[k + 1][rec[uni.chain.steps[k].field]]
            rec = uni.recs[k + 1][i]
        out[i].append(r0)
    return out


def _free_path(uni: Universe, rng: random.Random, hops: int):
    """Wire freely, draw the answer uniformly among the end-level records some chain
    reaches, and the root uniformly among the roots that reach it.

    Returns (path, the other reachable end records, the unreachable end records). Only
    the reachable ones may stand as distractors: an unreachable record is one nothing on
    the level before points at, which is one glance, not a chain.
    """
    wire_free(uni, rng)
    reach = _reach(uni, hops)
    ends = sorted(reach)
    gold_i = rng.choice(ends)
    root_i = rng.choice(reach[gold_i])
    path = follow(uni, uni.recs[0][root_i]["record_id"], hops)
    live = [uni.recs[hops][i] for i in ends if i != gold_i]
    dead = [r for i, r in enumerate(uni.recs[hops]) if i not in reach]
    return path, live, dead


def follow(uni: Universe, root_id: str, hops: int) -> list[dict]:
    """The record sequence a reader gets by taking `hops` references, exactly."""
    lv, rec = uni.by_id(root_id)
    out = [rec]
    for k in range(hops):
        nxt_id = rec[uni.chain.steps[lv + k].field]
        _, rec = uni.by_id(nxt_id)
        out.append(rec)
    return out


def assign_marks(uni: Universe, rng: random.Random) -> None:
    """Every record gets every mark. Families overwrite the ones that carry the label."""
    for _lv, rec in uni.all_records():
        for m in uni.chain.marks:
            rec[m.name] = rng.choice(m.values)


