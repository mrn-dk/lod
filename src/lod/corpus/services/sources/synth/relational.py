"""Row 42 -- multi-hop and ranking (domain 20).

The two shapes nothing else in the corpus has, built as **rungs** rather than as more
examples of a shape that already fails.

**Ranking.** An earlier model's rule-transfer report puts the held-out `ranking` family at
0.2667 -- chance, and the worst result in the sweep. Domain 2 diagnosed it exactly: *its
form is different -- compare a field across records rather than evaluate a predicate on
one*. Every trained rule in row 33 evaluates a predicate on a single record, so `ranking`
had no trained parts at all, and adding more ranking rules to row 33 would not have
changed that. So the missing rungs are built here:

    rank_pairwise   of these two records, which ranks higher on X          (trained, 2 options)
    rank_extremum   which of these N ranks highest / lowest / second       (trained, 3-16 options)
    rank_ordering   which of these orderings is correct                    HELD OUT, testreal

`test_relational_source.py` asserts that `rank_ordering` uses no comparison primitive
that `rank_pairwise` and `rank_extremum` do not both already train. Five primitives --
`field`, `ratio`, `mixed_units`, `deviation`, `tiebreak` -- and the comparison rule is
written into the question's `instructions`, the way `rules.py` writes its rule into the
criteria.

**Multi-hop.** Every other domain answers from one record or one passage; nothing asks
the model to follow a reference. Here the state is a universe of five levels of linked
records -- purchase order -> supplier -> certification body -> registry office ->
standards council, and two more chains like it -- and the question names a root and a
number of steps.

    hops 1          one lookup; the trained control                        (trained)
    hops 2, 3       two and three lookups                                  (trained)
    hops 4          four lookups                                           HELD OUT, testreal

The whole universe is rendered whatever the hop count, so a 4-hop question and a 1-hop
question differ **only in the question**. Hop count is the structure being held out, and
nothing else moves with it. It is in `meta.hops`, so a per-hop-count reading needs no
change to the gates.

**The chain is load-bearing by construction, not by hope.** Every stop-early answer is
put in the option list, and it is right exactly as often as any other option -- so a
reader who follows one reference and stops scores **chance**, and so does a reader who
computes the stop-early answer and strikes it out. This used to aim at **zero** (path
marks pairwise distinct; `sameend` wired to agree after one step exactly when the answer
was "no"), and zero is the same shortcut read backwards: the inverted one-hop reader
scored 1.000 on `sameend` and "strike the root's and first hop's marks" 0.87-0.89 on
`lookup`, held-out four hops included (measured by a shortcut audit). The
answer's record is also drawn uniformly among the records some chain reaches, so how
often a record is referenced says nothing either. `tests/test_relational_source.py`
measures both readers.

**The distractors make the wrong hop plausible.** Several suppliers, several certification
bodies, several registry offices; ids are opaque (`kestrel-4471`) and share one pool
across levels, so an option cannot be placed in the chain by the look of its identifier.

Every target is derived by code from the universe. The model's contribution is surface
only -- question stems -- generated once by a one-off generation script,
validated there and pasted here as literals. Two of its seven batches were **dropped
whole** rather than repaired, which is the point of validating at all: the `sameend`
stems put `{noun}` in the wrong grammatical slot ("a chain starting at {a} ... in the
{noun}", which says the chain runs inside a shipment rather than starting at one), and
the fourteen preambles were fourteen paraphrases of "The state <verb>s its records as
...", one memorisable frame rather than fourteen. Those two are hand-written below.
`relational_` is in `PROTECTED_PREFIXES`, so the corpus enricher never rewrites a
question whose wording is part of the task.
"""

