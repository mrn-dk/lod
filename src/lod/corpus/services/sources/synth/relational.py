_SINGULAR = ((re.compile(r"\ball 1 steps\b"), "the single step"),
             (re.compile(r"\b1 steps\b"), "one step"))


def _article(word: str) -> str:
    """"a escalation tier" shipped 126 times in an earlier build because the hand-written
    `sameend` stem hard-coded the article. Four of the six mark names begin with a
    consonant and two do not, so the article is drawn from the noun rather than written
    into the stem."""
    return "an" if word[:1].lower() in "aeiou" else "a"


def _fill_hop(stem: str, hops: int, **kw) -> str:
    out = stem.format(h=hops, **kw)
    for pat, rep in _SINGULAR:
        out = pat.sub(rep, out)
    return out


def said_hops(text: str) -> int | None:
    """The hop count a filled question states, or None if it states none."""
    m = re.search(r"\b(\d+) steps\b", text)
    if m:
        return int(m.group(1))
    if re.search(r"\bthe single step\b|\bone step\b", text):
        return 1
    return None


# ---- the phrasing bank ---------------------------------------------------------------
# Template ids are `d20.<family>` and are specified in lod/assets/phrasing_specs/d20.json.
# The stem drawn from the literal tuples below is passed as the template, so an empty bank
# returns it unchanged and the rng stream -- and so every corpus built before the bank
# existed -- is untouched. A bank phrasing is used only if, once filled, it still asks the
# same thing: every slot value is in the text, and for a chain the stated hop count is
# the real one. Otherwise the drawn stem is used; a phrasing is never repaired.

_BANK = None


def _bank():
    global _BANK
    if _BANK is None:
        from lod.phrasings import PhrasingBank
        _BANK = PhrasingBank.load()
    return _BANK


def worded(family: str, stem: str, key: str, fill, valid) -> str:
    cand = _bank().pick(f"d20.{family}", stem, key)
    if cand != stem:
        try:
            text = fill(cand)
        except (KeyError, IndexError, ValueError):
            text = None
        if text is not None and valid(text):
            return text
    return fill(stem)


def hop_text(stem: str, hops: int, family: str | None = None, **kw) -> str:
    """Fill a stem, then repair the singular. Every stem writes "{h} steps", so the
    one-hop control would read "take all 1 steps" -- and the control has to read like a
    question somebody would ask or it is not a control."""
    if family is None:
        return _fill_hop(stem, hops, **kw)
    key = f"{family}:{hops}:" + ":".join(str(kw[k]) for k in sorted(kw))
    return worded(
        family, stem, key, lambda st: _fill_hop(st, hops, **kw),
        lambda t: (said_hops(t) == hops and "{" not in t and t.rstrip().endswith("?")
                   and all(str(v) in t for k, v in kw.items() if k != "art")))


def _humanise(field: str) -> str:
    return field.replace("_", " ")


def _fields_of(rec: dict) -> list[str]:
    return [k for k in rec if k != "record_id"]


def render(uni: Universe, shape: str, rng: random.Random) -> str:
    pre = rng.choice(PREAMBLES)[shape]
    chain = uni.chain
    if shape == "json":
        body = _json.dumps({g: uni.recs[lv] for lv, g in enumerate(chain.groups)},
                           indent=2)
    elif shape == "table":
        blocks = []
        for lv, g in enumerate(chain.groups):
            group = uni.recs[lv]
            cols = ["record_id"] + _fields_of(group[0])
            widths = [max(len(c), max(len(str(r[c])) for r in group)) for c in cols]
            head = "  ".join(c.ljust(w) for c, w in zip(cols, widths)).rstrip()
            rows = ["  ".join(str(r[c]).ljust(w) for c, w in zip(cols, widths)).rstrip()
                    for r in group]
            blocks.append(f"{_humanise(g)}\n  " + "\n  ".join([head] + rows))
        body = "\n\n".join(blocks)
    else:
        lines = []
        for lv, noun in enumerate(chain.levels):
            for rec in uni.recs[lv]:
                clauses = [f"{_humanise(k)} {rec[k]}" for k in _fields_of(rec)]
                lines.append(f"The {noun} {rec['record_id']} has "
                             + "; ".join(clauses) + ".")
        body = "\n".join(lines)
    return f"{pre}\n\n{body}"


def steps_block(chain: Chain, hops: int, shape: str, mode: str) -> str:
    """What counts as following a reference, written into the criteria.

    `direct` names the reference field the way the state presents it; `indirect` names
    only what the reference means, so locating it is part of the task. Half and half, the
    way `records.field_ref` splits them for row 33.
    """
    out = []
    for k in range(hops):
        st = chain.steps[k]
        here = chain.levels[k]
        if mode == "indirect":
            out.append(f"  step {k + 1}: from the {here} you are on, go to {st.gloss};")
        elif shape == "prose":
            out.append(f"  step {k + 1}: from the {here} you are on, go to the record "
                       f"named under {_humanise(st.field)};")
        else:
            out.append(f"  step {k + 1}: from the {here} you are on, go to the record "
                       f"whose id is in `{st.field}`;")
    out[-1] = out[-1][:-1] + "."
    return ("Every record names the next one along. Take the steps below strictly in "
            "order, one at a time, and do not skip one:\n" + "\n".join(out))


# ---- the three multi-hop families ---------------------------------------------------
# Each returns (question, instructions, options, descriptions, gold, meta) or None.

def _shuffle(rng: random.Random, options, descs, gold: int):
    order = list(range(len(options)))
    rng.shuffle(order)
    return ([options[i] for i in order], [descs[i] for i in order], order.index(gold))


LOOKUP_COPIES = (2, 2, 3)     # how often each option value is printed in the whole state


def _balance_option_counts(uni: Universe, rng: random.Random, mark: Attr, hops: int,
                           path: list[dict], sibs: list[dict], opts: list[str]) -> bool:
    """Make how often, and where, an option is printed say nothing about which it is.

    `plant` puts each stop-early value on a path record *and* on an end-level sibling, so
    it was printed at least twice, while the answer and the spare distractors were printed
    once plus whatever the random fill added. "Pick the option printed least often"
    scored 0.481-0.500 on `lookup` at 2-4 hops against 0.261 chance (domain-20 audit,
    before this fix) without following a single reference. Balancing the counts alone
    moved the leak rather than closing it: the stop-early values are the only ones
    guaranteed to sit on a level *before* the end, so "drop every option printed before
    the end level" then scored 0.341-0.445.

    So every off-path record outside the end level is refilled here. Each option value is
    printed a number of times drawn from `LOOKUP_COPIES` whatever its role, at least once
    on a level before the end (the stop-early values already are, on the path), and every
    other off-path record takes a value that is not an option. The path and the end level
    -- everything the label depends on -- are left exactly as they were.
    """
    on_path = {id(r) for r in path}
    fixed = on_path | {id(r) for r in sibs}
    free = [(lv, r) for lv, r in uni.all_records() if id(r) not in fixed and lv != hops]
    early = [r for lv, r in free if lv < hops]
    late = [r for lv, r in free if lv > hops]
    rest = [v for v in mark.values if v not in opts]
    have = collections.Counter(r[mark.name] for r in path + sibs)
    early_have = {r[mark.name] for r in path[:hops]}
    rng.shuffle(early)
    first: list[str] = []
    extra: list[str] = []
    for o in opts:
        need_early = o not in early_have
        want = max(rng.choice(LOOKUP_COPIES), have[o] + need_early)
        n_new = want - have[o]
        if need_early:
            first.append(o)
            n_new -= 1
        extra += [o] * n_new
    if len(first) > len(early) or len(first) + len(extra) > len(free) or not rest:
        return False
    for rec, v in zip(early, first):
        rec[mark.name] = v
    spare = early[len(first):] + late
    rng.shuffle(spare)
    for rec, v in zip(spare, extra):
        rec[mark.name] = v
    for rec in spare[len(extra):]:
        rec[mark.name] = rng.choice(rest)
    return True


def _f_lookup(uni: Universe, rng: random.Random, hops: int, heldout: bool):
    """The mark on the record at the end of the chain.

    Three things are arranged rather than hoped for. The stop-early marks -- the root's
    own, and the one a step along -- are put in the option list, so a reader who stops
    early is offered the answer that stopping gives. Every option is *also* carried by a
    record at the level the chain ends on, so knowing which group the answer lives in cuts
    nothing out of the field -- without that, a 4-hop question hands away two of its three
    options to anybody who can count. And the stop-early marks are **not always wrong**:
    each is the answer too, one time in k, because the end record happens to carry the
    same mark.

    That last one is a change. They used to be drawn pairwise distinct, so a reader who
    stopped early scored zero -- and a reader who computed the one-hop mark and *struck it
    out* scored far above chance: with three options, the root's mark, the one-hop mark
    and the answer, striking the two found the answer every time. "Never the root's or
    the first hop's mark" found 0.87-0.89 of `lookup` answers at 2-4 hops against 0.26
    chance, after one step of a four-step chain (measured by a shortcut audit).
    Now an option being a stop-early mark says nothing about whether it is the answer.
    The answer's record is drawn uniformly among the records some chain reaches
    (`_free_path`), and only reachable records carry the distractors.
    """
    chain = uni.chain
    path, live, dead = _free_path(uni, rng, hops)
    if len(live) < 2:
        return None
    mark = rng.choice(chain.marks)
    # The sentinel either replaces the answer or joins the field, and the option count
    # must not say which: an earlier build listed k options when the sentinel was the
    # answer and k + 1 when it was a decoy, so "three options, one of them the sentinel"
    # meant the sentinel was right. Both now list k + 1 -- the answer's slot goes to one
    # more distractor -- which needs k real distractors on hand.
    offer = rng.random() < P_SENTINEL_OFFERED
    k = min(rng.choice((3, 3, 4, 4, 5, 6, 8)), len(live) + (0 if offer else 1))
    m = k + offer                                  # options listed
    # which stop-early marks are offered: the root's and the first hop's, or one of them
    # when the field has room for only one beside the answer
    plant_js = list(range(min(2, hops)))
    rng.shuffle(plant_js)
    plant_js = sorted(plant_js[:k - 1])
    # with probability 1/m for each offered stop-early mark, the end record carries it
    u = rng.random()
    same_as = plant_js[int(u * m)] if u < len(plant_js) / m else None

    pool = list(mark.values)
    rng.shuffle(pool)
    path_vals = pool[:hops + 1]
    if same_as is not None:
        path_vals[hops] = path_vals[same_as]
    gold_val = path_vals[hops]
    for rec, v in zip(path, path_vals):
        rec[mark.name] = v

    # `plant` is what makes the stop-early answers plausible: the root's own mark, and
    # the mark one step along, are carried by (reachable) siblings of the final record.
    rng.shuffle(live)
    rng.shuffle(dead)
    sibs = live + dead
    plant = [path_vals[j] for j in plant_js if j != same_as]
    spare = list(pool[hops + 1:])
    sib_vals = plant + [spare.pop() for _ in range(len(sibs) - len(plant))]
    for rec, v in zip(sibs, sib_vals):
        rec[mark.name] = v
    path_ids = {r["record_id"] for r in path}
    for lv, rec in uni.all_records():
        if lv == hops or rec["record_id"] in path_ids:
            continue
        rec[mark.name] = rng.choice(mark.values)

    wrong = sib_vals[:k - 1]
    if (len(set(sib_vals[:k])) != len(sib_vals[:k]) or gold_val in sib_vals[:k]
            or any(p not in wrong for p in plant)):
        return None

    options = list(wrong) + [gold_val]
    descs: list[str | None] = [None] * len(options)
    gold = len(options) - 1
    meta_extra = {"sentinel": "absent"}
    if offer:
        key, desc = sentinel.sample(rng, split="eval" if heldout else "train")
        if rng.random() < 1.0 / m:
            # the real answer is simply not listed; one more distractor takes its slot
            options = list(sib_vals[:k]) + [key]
            descs = [None] * (len(options) - 1) + [desc]
            gold = len(options) - 1
            meta_extra = {"sentinel": "gold"}
        else:
            options.append(key)
            descs.append(desc)
            meta_extra = {"sentinel": "decoy"}
    if not _balance_option_counts(uni, rng, mark, hops, path, sibs,
                                  [o for o in options if o in mark.values]):
        return None
    options, descs, gold = _shuffle(rng, options, descs, gold)
    root = path[0]
    text = hop_text(rng.choice(LOOKUP_STEMS), hops, "lookup",
                    noun=chain.levels[0], rid=root["record_id"], mark=mark.text)
    return (text, mark, options, descs, gold,
            {"family": "lookup", "mark": mark.name, **meta_extra,
             "root": root["record_id"], "gold_record": path[hops]["record_id"],
             "stop_early": list(path_vals[:hops])})


def _f_bridge(uni: Universe, rng: random.Random, hops: int, heldout: bool):
    """Which record the chain finishes on. Ids are the options, so this is the family
    that carries high cardinality: every record in the universe is a candidate.

    The answer is drawn uniformly among the end-level records some chain reaches, and
    only those stand beside it from the end level (`_free_path`): with a forced path, the
    most-referenced end-level option was the answer 0.60-0.66 of the time against 0.14
    chance."""
    chain = uni.chain
    path, live, _dead = _free_path(uni, rng, hops)
    gold_id = path[hops]["record_id"]
    # not path[0]: "which record do you finish on" is never the one you started from,
    # so the root would be a distractor anybody discards without following anything.
    stop_early = [r["record_id"] for r in path[1:hops]]
    siblings = [r["record_id"] for r in live]
    root_id = path[0]["record_id"]
    elsewhere = [r["record_id"] for lv, r in uni.all_records()
                 if lv != hops and r["record_id"] not in stop_early
                 and r["record_id"] not in (gold_id, root_id)]
    avail = len(stop_early) + len(siblings) + len(elsewhere)
    k = min(rng.choice((3, 4, 5, 6, 8, 10, 12, 16, 20, 24)), avail + 1)
    if k < 3:
        return None
    # The record one step along goes in first and unconditionally: it is the answer a
    # reader who follows one reference and stops would give, and if it is missing from
    # the field that reader scores 1/k instead of nothing.
    wrong: list[str] = list(stop_early[:1])
    rest = stop_early[1:]
    for src in (rest, siblings, elsewhere):
        rng.shuffle(src)
    # round-robin over the rest, so a high-cardinality field is not all from one level
    queues = [rest, siblings, elsewhere]
    while len(wrong) < k - 1 and any(queues):
        for qd in queues:
            if qd and len(wrong) < k - 1:
                wrong.append(qd.pop())
    if len(wrong) < k - 1 or len(set(wrong)) != len(wrong):
        return None
    options = wrong + [gold_id]
    descs = [f"the record filed under {o}" for o in options]
    options, descs, gold = _shuffle(rng, options, descs, len(options) - 1)
    text = hop_text(rng.choice(BRIDGE_STEMS), hops, "bridge",
                    noun=chain.levels[0], rid=path[0]["record_id"])
    return (text, None, options, descs, gold,
            {"family": "bridge", "root": path[0]["record_id"], "gold_record": gold_id,
             "stop_early": list(stop_early),
             "one_hop_record": path[1]["record_id"] if hops >= 1 else None})


def _f_sameend(uni: Universe, rng: random.Random, hops: int, heldout: bool):
    """Two chains: do they end on the same mark?

    The one-hop reader is denied the answer: after one step the two paths carry the same
    mark half the time and different marks half the time, *whatever the answer*.

    It used to be given the opposite of the answer instead -- same mark after one step
    exactly when the answer was `no` -- which made the one-hop reader score zero and so
    made the *inverted* one-hop reader score 1.000 at 2, 3 and the held-out 4 hops
    (measured by a shortcut audit): one step, then say the opposite. The trained
    hop counts taught that rule as well as they taught following. And a `yes` built from
    two different end records puts a repeated mark on the end level while a `no` need
    not, so "does the end level repeat a mark" agreed with the label 0.68-0.69; every
    instance now carries a repeat there.
    """
    chain = uni.chain
    if hops < 1 or min(uni.width[:hops + 1]) < 2:
        return None
    # Every universe carries both kinds of pair, whatever the answer: three chains from
    # three roots, node-disjoint up to the last level, two of which then end on one
    # record and the third elsewhere. The question names the merging pair or the other
    # one. Forcing only the named pair in (the way this used to work) wired two
    # references into one end record exactly when the answer was "same record", so how
    # the end level is referenced -- how many of its records nothing points at, whether
    # any is pointed at twice -- leaned towards the label (0.60-0.62 with a three-feature
    # lookup, measured by a shortcut audit).
    if min(uni.width[:hops]) < 3:
        return None
    a_idx = [rng.randrange(len(g)) for g in uni.recs]
    b_idx, c_idx = [], []
    for lv in range(hops):                       # three chains, node-disjoint
        others = [i for i in range(len(uni.recs[lv])) if i != a_idx[lv]]
        rng.shuffle(others)
        b_idx.append(others[0])
        c_idx.append(others[1])
    b_idx.append(a_idx[hops])                    # b ends on a's record
    c_idx.append(rng.choice([i for i in range(len(uni.recs[hops])) if i != a_idx[hops]]))
    wire(uni, rng, [a_idx, b_idx, c_idx])
    want_same = rng.random() < 0.5
    other = b_idx if want_same and rng.random() < 0.5 else c_idx
    if rng.random() < 0.5:
        a_idx, b_idx = other, a_idx
    else:
        b_idx = other

    mark = rng.choice(chain.marks)
    assign_marks(uni, rng)
    pool = list(mark.values)
    rng.shuffle(pool)
    end_a = uni.recs[hops][a_idx[hops]]
    end_b = uni.recs[hops][b_idx[hops]]
    end_a[mark.name] = pool[0]
    end_b[mark.name] = pool[0] if want_same else pool[1]
    # a repeated mark on the end level, whatever the answer: a `yes` over two different
    # end records has one by construction, so every other instance is given one too
    if not (want_same and end_a is not end_b):
        others = [r for r in uni.recs[hops] if r is not end_a and r is not end_b]
        if not others:
            return None
        tgt = rng.choice(others)
        tgt[mark.name] = rng.choice([r for r in uni.recs[hops] if r is not tgt])[mark.name]
    # after one step: agree or disagree by a coin that knows nothing of the answer
    one_a = uni.recs[1][a_idx[1]]
    one_b = uni.recs[1][b_idx[1]]
    one_same = rng.random() < 0.5
    if hops > 1 and one_a["record_id"] != one_b["record_id"]:
        one_a[mark.name] = pool[2]
        one_b[mark.name] = pool[2] if one_same else pool[3]
    options = ["no", "yes"]
    descs = [f"the two chains end on records with different {mark.text}s",
             f"the two chains end on records carrying the same {mark.text}"]
    text = hop_text(
        rng.choice(SAMEEND_STEMS), hops, "sameend", noun=chain.levels[0],
        a=uni.recs[0][a_idx[0]]["record_id"],
        b=uni.recs[0][b_idx[0]]["record_id"], mark=mark.text,
        art=_article(mark.text))
    return (text, mark, options, descs, int(want_same),
            {"family": "sameend", "mark": mark.name,
             "root": uni.recs[0][a_idx[0]]["record_id"],
             "root_b": uni.recs[0][b_idx[0]]["record_id"],
             "one_hop_same": one_same if hops > 1 else want_same})


_HOP_BUILD = {"lookup": _f_lookup, "bridge": _f_bridge, "sameend": _f_sameend}


def hop_instance(chain: Chain, hops: int, family: str, rng: random.Random,
                 heldout: bool) -> list[Example] | None:
    """One universe, one question, three renderings of the same values."""
    width_hi = 6 if family == "bridge" and rng.random() < 0.5 else 5
    uni = make_universe(chain, rng, 3, width_hi, n_extra=rng.randint(2, 4))
    assign_marks(uni, rng)
    built = _HOP_BUILD[family](uni, rng, hops, heldout)
    if built is None:
        return None
    text, mark, options, descs, gold, meta = built
    if len(set(options)) != len(options):
        return None
    out = []
    for shape in SHAPES:
        mode = "indirect" if rng.random() < P_INDIRECT else "direct"
        instr = steps_block(chain, hops, shape, mode)
        if mark is not None and meta["family"] == "lookup":
            instr += (f"\nThe answer is the {mark.text} recorded on the record you "
                      f"finish on, not on any record you pass through on the way.")
        state = render(uni, shape, rng)
        qmeta = {**meta, "hops": hops, "chain": chain.name, "shape": shape,
                 "mode": mode, "n_records": sum(uni.width)}
        if len(state) > MAX_STATE_CHARS:
            return None
        out.append(Example(state=state, questions=[Question(
            id=f"{meta['family']}_h{hops}_{shape}", question=text, options=list(options),
            target=gold, meta=qmeta, instructions=instr,
            descriptions=list(descs) if any(descs) else None)]))
    return out


