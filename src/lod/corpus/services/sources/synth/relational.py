def _fmt_num(v: float) -> str:
    """`%g`, not `%.2f`: a factor of 0.001 printed as "0.00" makes the criteria a lie."""
    return f"{v:g}"


@dataclass
class RankInstance:
    domain: RankDomain
    comparator: str
    names: list[str]
    recs: list[dict]
    keys: list[float]           # the comparison key; larger is better, always
    rule: str                   # the criteria text
    direction: str              # "highest" / "lowest", for the question wording
    surface: list[float]        # the number as printed, for the naive-reader distractor
    surface_high_wins: bool

    def order(self) -> list[int]:
        return sorted(range(len(self.recs)), key=lambda i: -self.keys[i])


def _base_record(d: RankDomain, rng: random.Random, name: str) -> dict:
    rec = {"name": name}
    for n in d.nums:
        rec[n.name] = rng.randint(n.lo, n.hi)
    for e in d.enums:
        rec[e.name] = e.draw(rng)
    return rec


RATIO_MIN_GAP = 0.03          # adjacent quotients differ by at least 3 % of the larger
# Share of the surface-number reader's correct answers that are thrown back on the trained
# rungs, for every comparator except `field` (see `_surface_pick`).
P_SURFACE_REJECT = 0.6


def _surface_order(inst: "RankInstance") -> list[int]:
    """What a reader who ignores the rule and sorts the printed number gets. Stable, so a
    tie on the printed number falls back to the order the state lists the records in."""
    n = len(inst.recs)
    return sorted(range(n), key=lambda i: inst.surface[i], reverse=inst.surface_high_wins)


def make_rank_instance(d: RankDomain, comparator: str, n: int,
                       rng: random.Random) -> RankInstance | None:
    names = rng.sample(list(d.names), n)
    recs = [_base_record(d, rng, nm) for nm in names]
    by = {f.name: f for f in d.nums}
    hi_wins = rng.random() < 0.5

    if comparator == "field":
        wide = [x for x in d.nums if x.hi - x.lo + 1 >= n]
        if not wide:
            return None
        f = rng.choice(wide)
        vals = rng.sample(range(f.lo, f.hi + 1), n)
        for rec, v in zip(recs, vals):
            rec[f.name] = v
        keys = [rec[f.name] * (1 if hi_wins else -1) for rec in recs]
        surface = [float(rec[f.name]) for rec in recs]
        rule = (f"Rank the {d.plural} by `{f.name}`, "
                f"{'highest' if hi_wins else 'lowest'} first.")
        direction = "highest" if hi_wins else "lowest"

    elif comparator == "ratio":
        num, den, gloss = d.ratio
        for rec in recs:
            rec[den] = rng.randint(by[den].lo, by[den].hi)
            rec[num] = rng.randint(by[num].lo, by[num].hi)
        keys = [rec[num] / rec[den] * (1 if hi_wins else -1) for rec in recs]
        surface = [float(rec[num]) for rec in recs]
        rule = (f"Rank the {d.plural} by {gloss} -- that is `{num}` divided by `{den}` "
                f"-- {'highest' if hi_wins else 'lowest'} first.")
        direction = f"{'highest' if hi_wins else 'lowest'} on {gloss}"

    elif comparator == "mixed_units":
        fname, base, units = d.mixed
        f = by[fname]
        if f.hi - f.lo + 1 < n:
            return None
        trues = rng.sample(range(f.lo, f.hi + 1), n)
        pers = []
        for rec, t in zip(recs, trues):
            unit, per_base = rng.choice(units)
            rec[fname] = round(t * per_base, 2)
            rec[f"{fname}_unit"] = unit
            pers.append(per_base)
        keys = [rec[fname] / per * (1 if hi_wins else -1)
                for rec, per in zip(recs, pers)]
        surface = [float(rec[fname]) for rec in recs]
        if len({rec[f"{fname}_unit"] for rec in recs}) < 2:
            return None          # one unit throughout is the `field` comparator again
        table = "; ".join(f"1 {base} = {_fmt_num(p)} {u}" for u, p in units if p != 1.0)
        rule = (f"Each {d.noun} reports `{fname}` in whatever unit it uses, given in "
                f"`{fname}_unit` beside it. Convert every figure to {base} before you "
                f"compare anything ({table}), then rank "
                f"{'highest' if hi_wins else 'lowest'} first.")
        direction = f"{'highest' if hi_wins else 'lowest'} once converted to {base}"

    elif comparator == "deviation":
        fname, tlo, thi = d.deviation
        f = by[fname]
        if f.hi - f.lo + 1 < n:
            return None
        target = rng.randint(tlo, thi)
        vals = rng.sample(range(f.lo, f.hi + 1), n)
        for rec, v in zip(recs, vals):
            rec[fname] = v
        keys = [-abs(rec[fname] - target) for rec in recs]
        surface = [float(rec[fname]) for rec in recs]
        hi_wins = True
        rule = (f"Rank the {d.plural} by how close `{fname}` sits to the target of "
                f"{target}{f.unit}: the closest to the target ranks first, whether it is "
                f"over or under. How far above or below makes no difference, only how "
                f"far away.")
        direction = "closest to the target"

    elif comparator == "tiebreak":
        prim, prim_hi, sec, sec_hi = d.tiebreak
        pf, sf = by[prim], by[sec]
        span = list(range(pf.lo, pf.hi + 1))
        if sf.hi - sf.lo + 1 < n:
            return None
        # deliberate ties on the primary field: at least one pair must need the
        # tiebreaker, or the rule's second clause is decoration.
        base_vals = rng.sample(span, min(len(span), max(2, n - 1)))
        vals = [rng.choice(base_vals) for _ in range(n)]
        if len(set(vals)) == n or len(set(vals)) < 2:
            return None
        secs = rng.sample(range(sf.lo, sf.hi + 1), n)
        for rec, v, s in zip(recs, vals, secs):
            rec[prim] = v
            rec[sec] = s
        keys = [(v * (1 if prim_hi else -1)) * 100000
                + (s * (1 if sec_hi else -1))
                for v, s in zip(vals, secs)]
        surface = [float(rec[prim]) for rec in recs]
        hi_wins = prim_hi
        rule = (f"Rank the {d.plural} by `{prim}`, "
                f"{'highest' if prim_hi else 'lowest'} first. Where two of them have the "
                f"same `{prim}`, the one with the "
                f"{'higher' if sec_hi else 'lower'} `{sec}` ranks ahead.")
        direction = f"{'highest' if prim_hi else 'lowest'} on {prim.replace('_', ' ')}"
    else:
        raise ValueError(comparator)

    if len(set(keys)) != n:
        return None
    if comparator == "ratio":
        # A ratio ranking whose two closest quotients sit within 1 % of each other is a
        # three-significant-figure division test, not a ranking test: 6.9 % of the
        # `rank_ordering:ratio` questions hinged on such a pair (domain-20 audit).
        ks = sorted(abs(k) for k in keys)
        if any((b - a) / b < RATIO_MIN_GAP for a, b in zip(ks, ks[1:])):
            return None
    inst = RankInstance(d, comparator, names, recs, keys, rule, direction, surface,
                        hi_wins)
    # `field` is the only comparator whose printed number *is* the key; the proxies must
    # actually differ from the surface reading, or they train nothing new. `tiebreak` is
    # exempt too: its surface reading is its first clause, and the deliberate tie above
    # already makes the second clause decide something. Held to "differ", its ties were
    # resolved *against* the order the state lists the tied records in whenever there was
    # one tie, so "the tied record listed second wins" found the `rank_pairwise` answer
    # 0.58 of the time and `rank_ordering` leaned the same way
    # (measured by a shortcut audit); now the listing says nothing about a tie.
    if comparator not in ("field", "tiebreak"):
        naive = sorted(range(n), key=lambda i: -surface[i] if hi_wins else surface[i])
        if naive == inst.order():
            return None
    return inst


def render_rank(inst: RankInstance, shape: str, rng: random.Random) -> str:
    d, recs = inst.domain, inst.recs
    pre = rng.choice(RANK_PREAMBLES)
    cols = [k for k in recs[0] if k != "name"]
    if shape == "json":
        body = _json.dumps(recs, indent=2)
    elif shape == "table":
        head_cols = ["name"] + cols
        widths = [max(len(c), max(len(str(r[c])) for r in recs)) for c in head_cols]
        lines = ["  ".join(c.ljust(w) for c, w in zip(head_cols, widths)).rstrip()]
        lines += ["  ".join(str(r[c]).ljust(w) for c, w in zip(head_cols, widths)).rstrip()
                  for r in recs]
        body = "\n".join(lines)
    else:
        body = "\n".join(
            f"{r['name']} reports " + "; ".join(f"{_humanise(c)} {r[c]}" for c in cols)
            + "." for r in recs)
    return f"{pre}\n\n{body}"


def _kendall(a: tuple[str, ...], b: tuple[str, ...]) -> int:
    """Adjacent-transposition distance between two orderings of the same names."""
    pos = {x: i for i, x in enumerate(b)}
    return sum(1 for i in range(len(a)) for j in range(i + 1, len(a))
               if pos[a[i]] > pos[a[j]])


ORDINALS = ("first", "second", "third", "fourth", "fifth", "sixth")


def _ordinal_phrase(k: int, low: bool) -> str:
    return (("last in the ranking", "second from last in the ranking") if low
            else ("first in the ranking", "second in the ranking"))[k]


def rank_instance_examples(d: RankDomain, comparator: str, family: str,
                           rng: random.Random, idx: int) -> list[Example] | None:
    if family == "rank_pairwise":
        n = rng.randint(3, 8)
    elif family == "rank_extremum":
        n = rng.choice((3, 4, 5, 6, 8, 10, 12, 16))
    else:
        n = rng.randint(3, 5)
    inst = make_rank_instance(d, comparator, n, rng)
    if inst is None:
        return None
    order = inst.order()

    if family == "rank_pairwise":
        # The pair is chosen, not drawn. Drawn at random, the pair the rule orders one way
        # was ordered the same way by the printed number alone 0.66-0.88 of the time on the
        # four comparisons that are not `field` (domain-20 audit), so the rung taught
        # "compare the number you see" -- which is exactly the naive distractor that
        # `rank_ordering` plants. Half the pairs are now ones the printed number gets
        # wrong; for `tiebreak`, half are pairs tied on the primary field, the only pairs
        # the rule's second clause decides.
        pairs = [(a, b) for a in range(n) for b in range(a + 1, n)]
        surf = _surface_order(inst)
        rank_s = {x: r for r, x in enumerate(surf)}

        def naive_right(a, b):
            if inst.surface[a] == inst.surface[b]:
                return None
            return (rank_s[a] < rank_s[b]) == (inst.keys[a] > inst.keys[b])
        hard = [p for p in pairs if naive_right(*p) is not True]
        easy = [p for p in pairs if naive_right(*p) is True]
        pool = hard if (hard and (rng.random() < 0.5 or not easy)) else easy
        i, j = rng.choice(pool)
        if rng.random() < 0.5:
            i, j = j, i
        options = [inst.names[i], inst.names[j]]
        gold = 0 if inst.keys[i] > inst.keys[j] else 1
        descs = [f"{o}, as reported above" for o in options]
        options, descs, gold = _shuffle(rng, options, descs, gold)
        a_, b_ = inst.names[i], inst.names[j]
        text = worded("rank_pairwise", rng.choice(PAIRWISE_STEMS), f"pw:{idx}:{a_}:{b_}",
                      lambda st: st.format(a=a_, b=b_),
                      lambda t: a_ in t and b_ in t and t.rstrip().endswith("?"))
        meta = {"family": family, "pair": [inst.names[i], inst.names[j]]}

    elif family == "rank_extremum":
        low = rng.random() < 0.35
        k = 0 if rng.random() < 0.72 else 1
        ranked = order if not low else order[::-1]
        gold_i = ranked[k]
        # Same reason as the pairwise choice above: the printed number alone found the
        # asked-for record 0.33-0.58 of the time against 0.14-0.16 chance.
        if comparator != "field":
            surf = _surface_order(inst)
            if (surf if not low else surf[::-1])[k] == gold_i and rng.random() < P_SURFACE_REJECT:
                return None
        options = list(inst.names)
        descs = [f"{o}, as reported above" for o in options]
        gold = options.index(inst.names[gold_i])
        options, descs, gold = _shuffle(rng, options, descs, gold)
        ord_ = _ordinal_phrase(k, low)
        text = worded("rank_extremum", rng.choice(EXTREMUM_STEMS),
                      f"ex:{idx}:{':'.join(inst.names)}",
                      lambda st: st.format(ord=ord_),
                      lambda t: ord_ in t and t.rstrip().endswith("?"))
        meta = {"family": family, "position": k, "from_bottom": low}

    else:                                              # rank_ordering -- held out
        # The option set is built first, around an arbitrary ordering, and the answer is
        # then drawn uniformly from it; the records are *named* afterwards so that the
        # drawn one is the true order. Nothing about where an ordering sits in the field
        # -- central, reversed by another, one swap from most -- can say it is the
        # answer, because the field was shaped before there was an answer.
        #
        # It used to be built outwards from the true order: adjacent swaps of it, swaps
        # of one of those, its reverse, the order the state lists the records in, and the
        # order the printed number gives. So the answer was always the one whose reverse
        # was also offered, and the listed and printed-number orders were always offered
        # and always wrong; "the option whose reverse is also an option" alone scored
        # 0.38 against 0.29 chance, and a lookup over three such features 0.60-0.72,
        # without a record read (measured by a shortcut audit). The Kendall-
        # median repair that followed made it worse in the other direction: the answer
        # was *never* the consensus of the field, so the consensus was a signal to avoid.
        def swapped(p, a):
            q = list(p)
            q[a], q[a + 1] = q[a + 1], q[a]
            return tuple(q)

        base = tuple(rng.sample(list(inst.names), n))
        cands: list[tuple[str, ...]] = [base]

        def add(p):
            if p not in cands:
                cands.append(tuple(p))

        for a in range(n - 1):                         # one adjacent swap
            add(swapped(base, a))
        pivot = swapped(base, rng.randrange(n - 1))    # and swaps of one of those
        for a in range(n - 1):
            add(swapped(pivot, a))
        add(tuple(reversed(base)))
        k = min(rng.choice((2, 3, 4, 4, 5, 6)), len(cands))
        rng.shuffle(cands)
        rows = cands[:k]
        true_perm = rows[rng.randrange(k)]
        # name the records so that the drawn ordering is the true one: the record that
        # ranks r-th under the rule takes the r-th name of `true_perm`
        new_names = list(inst.names)
        for r, i in enumerate(order):
            new_names[i] = true_perm[r]
        inst.names = new_names
        for rec, nm in zip(inst.recs, new_names):
            rec["name"] = nm
        # The printed-number order is never a *wrong* option where the printed number is
        # only a proxy. `make_rank_instance` makes it differ from the true order there,
        # so wherever it was offered it was wrong: a reader who sorts the printed number
        # and strikes that option out gains, and one who sorts it and picks it scores
        # below chance. It is swapped for an unused candidate, or dropped.
        naive = tuple(sorted(inst.names, key=lambda nm: (
            -1 if inst.surface_high_wins else 1) * inst.surface[inst.names.index(nm)]))
        if comparator in SURFACE_PROXY and naive != true_perm and naive in rows:
            rows.remove(naive)
            spare = [c for c in cands[k:] if c != naive]
            if spare:
                rows.append(spare[0])
            if len(rows) < 2:
                return None
        rows = [p for p in rows if p != true_perm] + [true_perm]
        options = [", ".join(p) for p in rows]
        descs = ["; ".join(f"{nm} {ORDINALS[pos]}" for pos, nm in enumerate(p))
                 for p in rows]
        options, descs, gold = _shuffle(rng, options, descs, len(rows) - 1)
        text = worded("rank_ordering", rng.choice(ORDERING_STEMS),
                      f"or:{idx}:{':'.join(inst.names)}", lambda st: st,
                      lambda t: "{" not in t and t.rstrip().endswith("?"))
        # how far the printed-number order sits from the true order, in adjacent swaps
        meta = {"family": family, "n_ranked": n,
                "surface_distance": _kendall(naive, true_perm)}

    instr = (f"{inst.rule}\n"
             f"Nothing else about a {d.noun} counts towards the ranking, and no "
             f"{d.noun} can be placed without comparing it against the others.")
    out = []
    for shape in SHAPES:
        qmeta = {**meta, "comparator": comparator, "domain": d.name, "shape": shape,
                 "n_records": n}
        out.append(Example(state=render_rank(inst, shape, rng), questions=[Question(
            id=f"{family}_{idx}_{shape}", question=text, options=list(options),
            target=gold, meta=qmeta, instructions=instr, descriptions=list(descs))]))
    return out


