@dataclass(frozen=True)
class Attr:
    """One field of a record. `values` non-empty means categorical."""
    name: str
    values: tuple[str, ...] = ()
    lo: int = 0
    hi: int = 0
    unit: str = ""
    label: str = ""

    @property
    def text(self) -> str:
        return self.label or self.name.replace("_", " ")

    def draw(self, rng: random.Random):
        return rng.choice(self.values) if self.values else rng.randint(self.lo, self.hi)


@dataclass(frozen=True)
class Step:
    field: str      # the reference field carried by the record at the level before it
    gloss: str      # what the reference means, with no field name in it


@dataclass(frozen=True)
class Chain:
    name: str
    levels: tuple[str, ...]           # noun per level
    groups: tuple[str, ...]           # the group heading each level gets in the state
    steps: tuple[Step, ...]           # len(levels) - 1
    marks: tuple[Attr, ...]           # carried by every record at every level
    extras: tuple[tuple[Attr, ...], ...]   # per-level distractor field pools


def _mark(name: str, label: str, prefix: str, words: tuple[str, ...]) -> Attr:
    return Attr(name, tuple(f"{prefix}-{w}" for w in words), label=label)


