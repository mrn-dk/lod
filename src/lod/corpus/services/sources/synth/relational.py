def _hop_loader(chain_name: str, hops: int, seed: int, cap: int = MAX_PER_TASK):
    chain = CHAINS_BY_NAME[chain_name]
    heldout = hops in HELDOUT_HOPS

    def load(n: int) -> Iterator[Example]:
        n = min(n, cap)
        made = 0
        counts = {f: 0.0 for f in HOP_FAMILIES}
        yes_no = [0, 0]
        i = 0
        while made < n and i < n * 30:
            i += 1
            rng = _rng(seed, f"{chain_name}:{hops}:{i}")
            total = sum(counts.values()) or 1.0
            jitter = random.Random(f"o:{seed}:{i}")
            order = sorted(HOP_FAMILIES,
                           key=lambda f: counts[f] / total - HOP_FAMILY_SHARE[f]
                           + jitter.random() * 0.04)
            for family in order:
                batch = hop_instance(chain, hops, family, rng, heldout)
                if batch is None:
                    continue
                if family == "sameend":
                    g = batch[0].questions[0].target
                    if yes_no[g] > yes_no[1 - g] + 1:
                        continue
                    yes_no[g] += 1
                counts[family] += 1
                made += len(batch)
                yield from batch
                break
    return load


# `rank_ordering` comparisons whose printed number is a proxy for the rule rather than a
# clause of it. On these the loader keeps the printed-number order exactly as often d
# adjacent swaps from the reverse of the true order as d swaps from the true order. Left
# to the draw, the printed number (the numerator of a ratio, a figure in whatever unit,
# the raw value whose distance to a target counts) sorts the records close to the true
# order: once the printed-number order was no longer planted as a wrong option, "the
# option nearest the printed-number order" found 0.47-0.55 of answers against 0.29
# chance, and while it *was* planted, "take that option" scored zero -- a reader was
# rewarded or punished for the very heuristic `rank_pairwise` is balanced to leave at a
# coin flip. (`field` and `tiebreak` are exempt: there the printed number is the rule's
# first clause.) `deviation` keeps a residual this cannot reach: ranking by distance to
# a target orders the records as a V over their values, so some orderings are ruled out
# by the value order alone (a shortcut audit reports it).
SURFACE_PROXY = ("ratio", "mixed_units", "deviation")


def _rank_loader(family: str, comparator: str, seed: int, cap: int = MAX_PER_TASK):
    balance = family in HELDOUT_RANK_FAMILIES and comparator in SURFACE_PROXY

    def load(n: int) -> Iterator[Example]:
        n = min(n, cap)
        made = 0
        i = 0
        concord = collections.Counter()
        while made < n and i < n * 30:
            i += 1
            rng = _rng(seed, f"{family}:{comparator}:{i}")
            d = RANK_DOMAINS[i % len(RANK_DOMAINS)]
            batch = rank_instance_examples(d, comparator, family, rng, i)
            if batch is None:
                continue
            if balance:
                # distance d and its mirror D - d (as near the reverse as d is to the
                # true order) are kept equally common, for each number of records
                m = batch[0].questions[0].meta
                k, D = m["n_ranked"], m["n_ranked"] * (m["n_ranked"] - 1) // 2
                key = (k, m["surface_distance"])
                if concord[key] > concord[(k, D - key[1])]:
                    continue
                concord[key] += 1
            made += len(batch)
            yield from batch
    return load


def tasks() -> list[RealTask]:
    """1-, 2- and 3-hop and the two trained ranking shapes go to `train`, each with a
    fresh-seed `_eval` twin forced to `devreal`. 4-hop and full ordering are `testreal`
    and are never trained on; nothing trained reaches `testreal`, so a testreal number on
    this row is a held-out-structure number and nothing else. `DEV_HOP_CELLS` and
    `DEV_RANK_CELLS` are the dev split's own held-out structures: no train task, no twin,
    no test task.

    The 1-hop tasks are the control the brief asks for: same universes, same renderings,
    same families, one reference followed instead of four. A 4-hop drop read against them
    is a failure to chain, not a failure to read a linked record at all.
    """
    out: list[RealTask] = []
    dev_note = "held out of train and test; a dev structure -- selects checkpoints and fits T"
    for chain in CHAINS:
        for hops in TRAINED_HOPS:
            if (chain.name, hops) in DEV_HOP_CELLS:
                out.append(RealTask(
                    row=ROW, name=f"relational_hop{hops}_{chain.name}", licence=LICENCE,
                    url=URL, load=_hop_loader(chain.name, hops, 6363), real=False,
                    force_split="devreal", per_example_options=True,
                    notes=f"{hops}-hop over the {chain.name} chain; {dev_note}"))
                continue
            for suffix, split, seed, cap in (("", "train", 0, MAX_PER_TASK_TRAIN),
                                             ("_eval", "devreal", 4242, MAX_PER_TASK_DEV)):
                name = f"relational_hop{hops}_{chain.name}{suffix}"
                out.append(RealTask(
                    row=ROW, name=name, licence=LICENCE, url=URL,
                    load=_hop_loader(chain.name, hops, seed, cap), real=False,
                    force_split=split, per_example_options=True,
                    notes=f"{hops}-hop over the {chain.name} chain; code-derived"))
        for hops in HELDOUT_HOPS:
            name = f"relational_hop{hops}_{chain.name}"
            out.append(RealTask(
                row=ROW, name=name, licence=LICENCE, url=URL,
                load=_hop_loader(chain.name, hops, 7717), real=False,
                force_split="testreal", per_example_options=True,
                notes=f"{hops}-hop over the {chain.name} chain; NEVER trained on"))
    for comparator in COMPARATORS:
        for family in TRAINED_RANK_FAMILIES:
            if (family, comparator) in DEV_RANK_CELLS:
                out.append(RealTask(
                    row=ROW, name=f"relational_{family}_{comparator}", licence=LICENCE,
                    url=URL, load=_rank_loader(family, comparator, 6363), real=False,
                    force_split="devreal", per_example_options=True,
                    notes=f"{family} on the {comparator} comparison; {dev_note}"))
                continue
            for suffix, split, seed, cap in (("", "train", 0, MAX_PER_TASK_TRAIN),
                                             ("_eval", "devreal", 4242, MAX_PER_TASK_DEV)):
                name = f"relational_{family}_{comparator}{suffix}"
                out.append(RealTask(
                    row=ROW, name=name, licence=LICENCE, url=URL,
                    load=_rank_loader(family, comparator, seed, cap), real=False,
                    force_split=split, per_example_options=True,
                    notes=f"{family} on the {comparator} comparison; code-derived"))
        for family in HELDOUT_RANK_FAMILIES:
            name = f"relational_{family}_{comparator}"
            out.append(RealTask(
                row=ROW, name=name, licence=LICENCE, url=URL,
                load=_rank_loader(family, comparator, 7717), real=False,
                force_split="testreal", per_example_options=True,
                notes=f"{family} on the {comparator} comparison; NEVER trained on"))
    return out


