def draw_weights(rng: random.Random, k: int, uniform_share: float = 0.2,
                 strong: float = 0.35, top: int = 15):
    """Prior weights over k hypotheses: (weights, kind). `strong` is how often one
    hypothesis gets a dominant weight, of up to `top`."""
    if rng.random() < uniform_share:
        return [1] * k, "uniform"
    while True:
        if rng.random() < strong:
            ws = [rng.randint(1, 3) for _ in range(k)]
            ws[rng.randrange(k)] = rng.choice([w for w in STRONG_WEIGHTS if w <= top])
        else:
            ws = [rng.randint(1, 9) for _ in range(k)]
        if len(set(ws)) > 1:
            return ws, "stated"


def pick_truth(rng: random.Random, ws: list, conflict: float = 0.4) -> int:
    """The hidden hypothesis the observations are drawn from. Part of the time it is the
    one the prior likes least, so prior and evidence pull apart; the target does not
    depend on this choice, only which instances get drawn."""
    if rng.random() < conflict:
        lo = min(ws)
        return rng.choice([i for i, w in enumerate(ws) if w == lo])
    return rng.randrange(len(ws))


def prior_block(doc: Doc, rng: random.Random, names: list[str], ws: list[int], kind: str,
                what: str, style: str | None = None, frame: str = "lottery") -> str:
    """Add the prior over `names` to `doc`. -> the style used. `frame` says how a count
    prior is told: `lottery` (the hypothesis was drawn by lot, for urns, coins, doors) or
    `records` (base rates among comparable past cases, for facts about the world)."""
    k = len(names)
    p = norm(ws)
    if kind == "uniform":
        style = "uniform"
        s = rng.choice((
            f"Beforehand each of the {k} is equally likely to be {what}.",
            f"Beforehand no one of the {k} is favoured over another as {what}.",
            f"No option is favoured in advance: each has prior probability 1/{k}.",
        ))
        doc.facts("prior", [("rule", "uniform"), ("each", f"1/{k}")], s)
        return style
    if style is None:
        opts = ["counts", "counts", "pct", "frac", "dec", "ratio"]
        if k == 2:
            opts.append("odds")
        style = rng.choice(opts)
    if style in ("pct", "dec") and not all((pct if style == "pct" else dec)(x) for x in p):
        style = "frac"
    if style == "counts" and frame == "records":
        src = rng.choice(("comparable cases on record", "similar past cases",
                          "earlier cases in the reference set"))
        parts = [f"{w} {'was' if w == 1 else 'were'} {n}" for n, w in zip(names, ws)]
        s = (f"Base rates for {what}: of {sum(ws)} {src}, {join_and(parts)}.")
        doc.facts(f"base rates ({sum(ws)} {src})", list(zip(names, ws)), s)
    elif style == "counts":
        vessel, unit = rng.choice((("a hat", "slip"), ("a bag", "token"),
                                   ("a drum", "ticket"), ("a box", "card")))
        parts = [f"{plural(w, unit)} for {n}" for n, w in zip(names, ws)]
        s = (f"The choice of {what} was made by drawing one {unit} from {vessel} "
             f"holding {join_and(parts)}.")
        doc.facts(f"prior ({unit}s in {vessel})", list(zip(names, ws)), s)
    elif style == "ratio":
        s = (f"Beforehand the odds for {what} were {':'.join(str(w) for w in ws)} "
             f"across {join_and(names)}, in that order.")
        doc.facts("prior (odds ratio)", list(zip(names, [str(w) for w in ws])), s)
    elif style == "odds":
        s = (f"Beforehand the odds of {names[0]} against {names[1]} as {what} were "
             f"{ws[0]} to {ws[1]}.")
        doc.facts("prior", [("odds", f"{names[0]} : {names[1]} = {ws[0]} : {ws[1]}")], s)
    else:
        vals = [fmt_p(x, style) for x in p]
        s = rng.choice((
            f"Prior probability of {what}: " + ", ".join(f"{n} {v}" for n, v in zip(names, vals)) + ".",
            "Before any evidence, " + join_and([f"{n} had probability {v}" for n, v in zip(names, vals)])
            + f" of being {what}.",
        ))
        doc.facts("prior", list(zip(names, vals)), s)
    return style


