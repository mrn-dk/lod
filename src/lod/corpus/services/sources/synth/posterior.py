@dataclass
class Draft:
    """One problem before rendering. Hypotheses carry `prior`; every observation j
    carries `liks[j][h]` = P(obs_j | h, obs_<j); `pred[h][o]` maps a hypothesis to the
    outcome asked about (None: the options are the hypotheses themselves)."""
    variant: str
    prior: list[F]
    liks: list[list[F]]
    pred: list[list[F]] | None
    params: dict
    gen: dict
    render: Callable[[random.Random], tuple]    # -> state, question, instructions, options, descriptions
    picks: dict = field(default_factory=dict)   # outcome-level picker heuristics: name -> set
    keep: list[int] | None = None               # outcomes offered as options (default: all)
    shuffle: bool = True
    hyp_heuristics: bool = True                 # per-observation last/majority on hypotheses


def posterior(prior: list[F], liks: list[list[F]]) -> list[F]:
    w = list(prior)
    for lk in liks:
        w = [a * b for a, b in zip(w, lk)]
    s = sum(w)
    if s == 0:
        raise ZeroDivisionError("observations impossible under every hypothesis")
    return [x / s for x in w]


def to_outcomes(dist: list, pred) -> list:
    if pred is None:
        return list(dist)
    n_out = len(pred[0])
    return [sum(dist[h] * pred[h][o] for h in range(len(dist))) for o in range(n_out)]


def exact_target(d: Draft) -> list[F]:
    """The exact posterior over the offered outcomes, in outcome order."""
    t = to_outcomes(posterior(d.prior, d.liks), d.pred)
    if d.keep is not None:
        dropped = sum(t[o] for o in range(len(t)) if o not in d.keep)
        if dropped != 0:
            raise ValueError("an outcome left out of the options carries mass")
        t = [t[o] for o in d.keep]
    return t


def _fnorm(xs) -> list[float]:
    s = float(sum(xs))
    if s <= 0:
        return [1.0 / len(xs)] * len(xs)
    return [float(x) / s for x in xs]


def _argset(xs, tol=1e-12) -> set[int]:
    m = max(xs)
    return {i for i, x in enumerate(xs) if x >= m - tol}


def heuristics(d: Draft) -> dict[str, list[float]]:
    """Every shallow reading of the draft, as a distribution over the offered outcomes.

    prior       -- the hypotheses weighed by the prior only (the evidence ignored)
    likelihood  -- the evidence only (the prior ignored; uniform prior)
    last        -- the last observation alone
    majority    -- one vote per observation, for the hypothesis it favours
    <picks>     -- variant-specific pickers: the most reliable source, the last or most
                   frequent observed outcome, staying with the first door, ...
    """
    k = len(d.prior)
    out: dict[str, list] = {}
    out["prior"] = to_outcomes(_fnorm(d.prior), d.pred)
    lik = [F(1)] * k
    for lk in d.liks:
        lik = [a * b for a, b in zip(lik, lk)]
    out["likelihood"] = to_outcomes(_fnorm(lik), d.pred)
    if d.hyp_heuristics and len(d.liks) >= 2:
        out["last"] = to_outcomes(_fnorm(d.liks[-1]), d.pred)
        votes = [0.0] * k
        for lk in d.liks:
            best = _argset([float(x) for x in lk])
            for h in best:
                votes[h] += 1.0 / len(best)
        out["majority"] = to_outcomes(_fnorm(votes), d.pred)
    n_out = len(out["prior"])
    for name, chosen in d.picks.items():
        if chosen:
            out[name] = [1.0 if o in chosen else 0.0 for o in range(n_out)]
    if d.keep is not None:
        out = {n: [v[o] for o in d.keep] for n, v in out.items()}
    return {n: _fnorm(v) for n, v in out.items()}


def agreement(dist: list[float], target: list[float]) -> float:
    """Expected accuracy of picking uniformly among `dist`'s argmax, scored against the
    argmax set of the exact target."""
    a, t = _argset(dist, 1e-9), _argset(target, 1e-12)
    return len(a & t) / len(a)


def conf_bin(target: list[float]) -> int:
    k = len(target)
    m = (max(target) - 1 / k) / (1 - 1 / k)
    return min(N_BINS - 1, max(0, int(m * N_BINS)))


def band(name: str, k: int) -> tuple[float, float]:
    """The accuracy a heuristic is held to: at least chance, far below the exact answer."""
    c = 1.0 / k
    return c, c + (1 - c) * (0.30 if name == "prior" else 0.42)


class Balance:
    """Keeps a task's max-posterior bins flat, every heuristic inside its band, and the
    answer's outcome index near 1/k (so a fixed option set -- yes/no, heads/tails, a count
    of heads, "neither" -- carries no label prior)."""

    def __init__(self):
        self.n = 0
        self.bins = Counter()
        self.acc: dict[str, list[float]] = {}     # name -> [sum acc, sum lo, sum hi]
        self.gold = Counter()                     # (k, outcome index) -> answers there
        self.gold_n = Counter()                   # k -> questions with k options

    @staticmethod
    def _gold(info):
        t = info["target"]
        g = _argset(t, 1e-12)
        return {i: 1 / len(g) for i in g}

    def violation(self, info) -> float:
        """How far past its limits this draft would push the task (0: it fits)."""
        n1 = self.n + 1
        v = max(0.0, self.bins[info["bin"]] + 1 - (n1 / N_BINS + 2 + 0.02 * n1))
        k = len(info["target"])
        for name, a in info["agree"].items():
            lo, hi = band(name, k)
            s, sl, sh = self.acc.get(name, (0.0, 0.0, 0.0))
            v += 2 * max(0.0, s + a - (sh + hi + 2)) + 2 * max(0.0, (sl + lo - 2) - (s + a))
        n_k = self.gold_n[k] + 1
        for i, w in self._gold(info).items():
            lim = n_k / k + 0.04 * n_k + 2
            v += max(0.0, self.gold[(k, i)] + w - lim)
        return v

    def fits(self, info) -> bool:
        return self.violation(info) == 0

    def add(self, info) -> None:
        self.n += 1
        self.bins[info["bin"]] += 1
        k = len(info["target"])
        for name, a in info["agree"].items():
            lo, hi = band(name, k)
            s, sl, sh = self.acc.get(name, (0.0, 0.0, 0.0))
            self.acc[name] = [s + a, sl + lo, sh + hi]
        for i, w in self._gold(info).items():
            self.gold[(k, i)] += w
        self.gold_n[k] += 1


def assess(d: Draft) -> dict | None:
    try:
        exact = exact_target(d)
    except ZeroDivisionError:
        return None
    target = [float(x) for x in exact]
    if len(target) < 2 or len(target) > 12:
        return None
    heur = heuristics(d)
    return {"exact": exact, "target": target, "heur": heur, "bin": conf_bin(target),
            "agree": {n: agreement(v, target) for n, v in heur.items()}}


