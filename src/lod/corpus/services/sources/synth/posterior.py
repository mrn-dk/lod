"""Row 48 -- exact posteriors (domain 22).

Calibration breaks on unseen families (ECE 0.033 familiar against 0.145 unseen) and
forecast transfer collapses (r 0.917 -> 0.425 on unseen forecast families). The loss is
PSR-FT, a cross-entropy against soft targets whose optimum is the true probability, so a
question whose target *is* the true probability teaches calibrated reading directly.
Every question here states a small generative story (urns, coins, dice, a noisy test,
witnesses of stated reliability, a population table, a two-step chain) and an
observation, and asks for the hypothesis or the next outcome. The target is the exact
posterior, computed with `fractions.Fraction` from the numbers the text states; nothing is
estimated, sampled or guessed.

**Six concept families, 26 structural variants.** A variant is one shape of story
(`urn_which_norepl`, `sensor_repeat`, `sources_relay`, ...). Every family trains in two or
three variants; each family also has one variant held out to `devreal` and a different one
held out to `testreal`, so dev and test both measure transfer to an unseen *structure* of a
trained *concept*, and are disjoint from each other and from train (`VARIANTS`). Every
trained variant also has a fresh-seed `_eval` twin in `devreal`, whose `family` is its
trained sibling, for in-structure evaluation.

**The shortcuts are built to lose.** "The hypothesis the prior favours", "the one the
likelihood favours ignoring the prior", "the one the last observation favours", "the
majority of the observations" and "the most reliable source" are each computed for every
draft (`heuristics`), and the loader keeps a draft only while every one of them stays in a
band above chance and well below the exact answer (`Balance`). The same balancer holds the
normalised max-posterior flat over five bins, so targets are neither mostly near-certain
nor mostly near-uniform. A shortcut audit measures the result.

**Numbers in varied formats.** Priors, rates, compositions and reliabilities appear as
counts, percentages, fractions, decimals, "n in N" and occasionally odds, in JSON,
`key: value`, markdown tables or prose, in the state or in the instructions. The format is
drawn per example and recorded in `meta.gen`, with every other generator parameter, so dev
loss can be broken down by parameter.
"""

