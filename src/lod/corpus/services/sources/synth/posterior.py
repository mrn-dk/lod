@dataclass
class Block:
    title: str
    kind: str                      # facts | table | text
    pairs: list = field(default_factory=list)       # facts: [(key, value)]
    header: list = field(default_factory=list)      # table
    rows: list = field(default_factory=list)        # table
    prose: str = ""


class Doc:
    def __init__(self):
        self.blocks: list[Block] = []

    def facts(self, title, pairs, prose):
        self.blocks.append(Block(title, "facts", pairs=list(pairs), prose=prose))

    def table(self, title, header, rows, prose):
        self.blocks.append(Block(title, "table", header=list(header),
                                 rows=[list(r) for r in rows], prose=prose))

    def text(self, title, text):
        self.blocks.append(Block(title, "text", prose=text))

    def render(self, fmt: str, rng: random.Random) -> str:
        if fmt == "json":
            obj = {}
            for b in self.blocks:
                if b.kind == "facts":
                    obj[b.title] = {k: v for k, v in b.pairs}
                elif b.kind == "table":
                    obj[b.title] = [dict(zip(b.header, r)) for r in b.rows]
                else:
                    obj[b.title] = b.prose
            return json.dumps(obj, indent=rng.choice((None, 1, 2)), ensure_ascii=False)
        out = []
        for b in self.blocks:
            if fmt == "prose":
                out.append(b.prose)
            elif b.kind == "text":
                out.append(f"{b.title}: {b.prose}" if fmt == "kv" else b.prose)
            elif b.kind == "facts":
                out.append(f"{b.title}:\n" + "\n".join(f"  {k}: {v}" for k, v in b.pairs))
            elif fmt == "kv":
                lines = []
                for r in b.rows:
                    rest = "; ".join(f"{h}={c}" for h, c in zip(b.header[1:], r[1:]))
                    lines.append(f"  {r[0]}: {rest}")
                out.append(f"{b.title}:\n" + "\n".join(lines))
            else:
                head = "| " + " | ".join(str(h) for h in b.header) + " |"
                sep = "|" + "|".join("---" for _ in b.header) + "|"
                body = "\n".join("| " + " | ".join(str(c) for c in r) + " |" for r in b.rows)
                out.append(f"{b.title}\n{head}\n{sep}\n{body}")
        return "\n\n".join(out)


