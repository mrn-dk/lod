def pct(p: F) -> str | None:
    x = p * 100
    if x.denominator == 1:
        return f"{x.numerator}%"
    if (x * 10).denominator == 1:
        return f"{float(x):.1f}%"
    return None


def dec(p: F) -> str | None:
    if (p * 1000).denominator != 1:
        return None
    s = f"{float(p):.3f}".rstrip("0").rstrip(".")
    return s if s else "0"


def frac(p: F) -> str:
    return f"{p.numerator}/{p.denominator}" if p.denominator != 1 else str(p.numerator)


def fmt_p(p: F, style: str) -> str:
    """One probability in one style, always exact (falls back to a fraction)."""
    if style == "pct":
        return pct(p) or frac(p)
    if style == "dec":
        return dec(p) or frac(p)
    if style == "in":
        return f"{p.numerator} in {p.denominator}"
    if style == "odds":
        return f"odds {p.numerator} to {p.denominator - p.numerator}"
    return frac(p)


def norm(ws) -> list[F]:
    s = sum(F(w) for w in ws)
    return [F(w) / s for w in ws]


def grid(rng: random.Random, lo: int, hi: int, den: int) -> F:
    return F(rng.randint(lo, hi), den)


def rate(rng: random.Random, lo: float, hi: float) -> F:
    """A probability on a 1/20 or 1/100 grid (or 1/10), within [lo, hi]."""
    den = rng.choice((20, 20, 100, 10))
    a, b = math.ceil(lo * den), math.floor(hi * den)
    return F(rng.randint(a, max(a, b)), den)


def int_split(rng: random.Random, weights: list[float], total: int) -> list[int]:
    """Integer counts summing to `total`, proportional to `weights` (largest remainder)."""
    s = sum(weights)
    raw = [w * total / s for w in weights]
    out = [int(x) for x in raw]
    rest = total - sum(out)
    order = sorted(range(len(raw)), key=lambda i: -(raw[i] - out[i]) + rng.random() * 1e-9)
    for i in order[:rest]:
        out[i] += 1
    return out


def join_and(xs: list[str]) -> str:
    xs = list(xs)
    if len(xs) <= 1:
        return "".join(xs)
    return ", ".join(xs[:-1]) + " and " + xs[-1]


def plural(n: int, word: str) -> str:
    return f"{n} {word}" if n == 1 else f"{n} {word}s"


