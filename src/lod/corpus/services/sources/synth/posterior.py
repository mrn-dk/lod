def _coin_draw(rng, variant):
    query = {"coin_which": "which", "coin_next": "next", "coin_nextcount": "count"}[variant]
    k = rng.randint(2, 6) if query == "which" else rng.randint(2, 4)
    den = rng.choice((20, 20, 10, 100))
    edge = max(1, den // 20)
    for _ in range(50):
        biases = []
        for _h in range(k):
            if query != "which" and rng.random() < (0.5 if query == "next" else 0.2):
                # near-certain coins, so a prediction can be confident
                x = rng.randint(edge, max(edge, den // 7))
                biases.append(F(x if rng.random() < 0.5 else den - x, den))
            else:
                biases.append(F(rng.randint(edge, den - edge), den))
        if len(set(biases)) == k:
            break
    else:
        return None
    n = rng.randint(2, 10) if query == "which" else rng.randint(1, 5)
    ws, kind = draw_weights(rng, k, *((0.2, 0.35) if query == "which" else (0.1, 0.7, 150)))
    truth = pick_truth(rng, ws, 0.4 if query == 'which' else 0.7)
    tosses = [1 if rng.random() < biases[truth] else 0 for _ in range(n)]
    liks = [[b if t else 1 - b for b in biases] for t in tosses]
    seq_style = rng.choice(("letters", "words", "counts")) if query != "next" else \
        rng.choice(("letters", "words"))
    pred, picks, shuffle, m_next = None, {}, True, 0
    heads = sum(tosses)
    if query == "next":
        pred = [[b, 1 - b] for b in biases]
        maj = {0} if heads * 2 > n else {1} if heads * 2 < n else {0, 1}
        picks = {"last_outcome": {0 if tosses[-1] else 1}, "majority_outcome": maj}
    elif query == "count":
        m_next = rng.randint(2, 4)
        pred = [[F(math.comb(m_next, x)) * b ** x * (1 - b) ** (m_next - x)
                 for x in range(m_next + 1)] for b in biases]
        fr = F(heads, n)
        plug = [F(math.comb(m_next, x)) * fr ** x * (1 - fr) ** (m_next - x)
                for x in range(m_next + 1)]
        picks = {"plugin": _argset([float(x) for x in plug])}
        shuffle = False
    names = rng.choice(COIN_SETS)[:k]
    fmt = rng.choice(FORMATS)
    bstyle = rng.choice(("pct", "dec", "frac", "in", "odds"))
    gen = {"n_hyp": k, "n_obs": n, "prior": kind, "query": query, "fmt": fmt,
           "bias_style": bstyle, "seq_style": seq_style, "m_next": m_next, "bias_den": den}
    params = {"biases": biases, "prior": ws, "tosses": tosses, "query": query, "m": m_next}

    def render(r: random.Random):
        doc = Doc()
        vals = []
        for b in biases:
            if bstyle == "odds":
                vals.append(f"heads:tails odds {b.numerator}:{b.denominator - b.numerator}")
            elif bstyle == "in":
                vals.append(f"{b.numerator} heads in {b.denominator} tosses on average")
            else:
                vals.append(fmt_p(b, bstyle))
        prose = " ".join(f"{nm[0].upper() + nm[1:]} lands heads with probability {v}."
                         if bstyle not in ("odds", "in") else
                         f"{nm[0].upper() + nm[1:]}: {v}." for nm, v in zip(names, vals))
        doc.table("coins", ["coin", "P(heads)" if bstyle not in ("odds", "in") else "bias"],
                  [[nm, v] for nm, v in zip(names, vals)], prose)
        prior_block(doc, r, names, ws, kind, "the coin tossed")
        if seq_style == "letters":
            obs = "".join("H" if t else "T" for t in tosses) + " (H = heads, T = tails)"
        elif seq_style == "words":
            obs = ", ".join("heads" if t else "tails" for t in tosses)
        else:
            obs = f"{plural(heads, 'head')} and {plural(n - heads, 'tail')} in {n} tosses (order not recorded)"
        story = f"One coin was picked as described and tossed {n} times; tosses are independent."
        doc.facts("tosses", [("procedure", story), ("result", obs)], f"{story} Result: {obs}.")
        state = doc.render(fmt, r)
        instr = answer(r)
        if query == "which":
            q = r.choice(("Which coin was tossed?", "Which coin produced these tosses?",
                          "Which of the coins was picked?"))
            return state, q, instr, list(names), None
        if query == "next":
            q = r.choice(("What will the next toss of the same coin show?",
                          "The same coin is tossed once more. Heads or tails?"))
            return state, q, instr, ["heads", "tails"], None
        q = r.choice((f"The same coin is tossed {m_next} more times. How many heads will those "
                      f"{m_next} tosses show?",
                      f"How many heads will the next {m_next} tosses of the same coin give?"))
        opts = ["no heads"] + [f"exactly {plural(x, 'head')}" for x in range(1, m_next + 1)]
        return state, q, instr, opts, None

    return Draft(variant, norm(ws), liks, pred, params, gen, render, picks=picks,
                 shuffle=shuffle, hyp_heuristics=query == "which")


def _die_faces(rng, f, heavy=0.0):
    if rng.random() < 0.3:
        return [F(1, f)] * f, "fair"
    if rng.random() < heavy:                     # one face dominates
        ws = [1] * f
        ws[rng.randrange(f)] = rng.choice((4, 6, 9, 14, 20, 30, 45))
        return norm(ws), "loaded"
    ws = [rng.randint(1, 3) for _ in range(f)]
    for i in rng.sample(range(f), rng.randint(1, 2)):
        ws[i] = rng.randint(3, 9)
    return norm(ws), "loaded"


def _die_draw(rng, variant):
    query = "which" if variant == "die_which" else "next"
    f = rng.choice((6, 6, 6, 6, 4, 8)) if query == "which" else rng.choice((6, 6, 4, 4))
    k = rng.randint(2, 4)
    for _ in range(50):
        dice = [_die_faces(rng, f, 0.0 if query == "which" else 0.7) for _ in range(k)]
        if len({tuple(p) for p, _ in dice}) == k:
            break
    else:
        return None
    faces = [p for p, _ in dice]
    n = rng.randint(2, 8) if query == "which" else rng.randint(1, 3)
    ws, kind = draw_weights(rng, k, *((0.2, 0.35) if query == "which" else (0.1, 0.7, 150)))
    truth = pick_truth(rng, ws, 0.4 if query == 'which' else 0.7)
    rolls = rng.choices(range(f), weights=[float(x) for x in faces[truth]], k=n)
    liks = [[faces[h][x] for h in range(k)] for x in rolls]
    pred, picks = None, {}
    if query == "next":
        pred = [list(faces[h]) for h in range(k)]
        cnt = Counter(rolls)
        top = max(cnt.values())
        picks = {"last_outcome": {rolls[-1]}, "majority_outcome": {x for x in cnt if cnt[x] == top}}
    names = rng.choice(DIE_SETS)[:k]
    fmt = rng.choice(FORMATS)
    style = rng.choice(("pct", "frac", "dec", "frac"))
    gen = {"n_hyp": k, "n_obs": n, "prior": kind, "query": query, "fmt": fmt, "faces": f,
           "p_style": style, "n_fair": sum(1 for _, t in dice if t == "fair")}
    params = {"faces": faces, "prior": ws, "rolls": rolls, "query": query}

    def render(r: random.Random):
        doc = Doc()
        rows, prose = [], []
        for nm, (p, t) in zip(names, dice):
            rows.append([nm] + [fmt_p(x, style) for x in p])
            if t == "fair":
                prose.append(f"{nm[0].upper() + nm[1:]} is fair: each face has probability "
                             f"{fmt_p(F(1, f), style)}.")
            else:
                prose.append(f"{nm[0].upper() + nm[1:]} is loaded: " + ", ".join(
                    f"face {i + 1} {fmt_p(x, style)}" for i, x in enumerate(p)) + ".")
        doc.table(f"face probabilities ({f}-sided dice)", ["die"] + [f"face {i + 1}" for i in range(f)],
                  rows, " ".join(prose))
        prior_block(doc, r, names, ws, kind, "the die rolled")
        story = f"One die was picked as described and rolled {n} times; rolls are independent."
        obs = ", ".join(str(x + 1) for x in rolls)
        doc.facts("rolls", [("procedure", story), ("faces shown", obs)],
                  f"{story} The faces shown were {obs}.")
        state = doc.render(fmt, r)
        instr = answer(r)
        if query == "which":
            q = r.choice(("Which die was rolled?", "Which die produced these rolls?"))
            return state, q, instr, list(names), None
        q = r.choice(("The same die is rolled once more. Which face comes up?",
                      "What will the next roll of the same die show?"))
        return state, q, instr, [f"a {NUMBER_WORDS[i + 1]}" for i in range(f)], None

    return Draft(variant, norm(ws), liks, pred, params, gen, render, picks=picks,
                 shuffle=query == "which", hyp_heuristics=query == "which")


