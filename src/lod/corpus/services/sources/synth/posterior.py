def _urn_comp(rng, k, m, lo, hi, distinct_props, peaked=0.0):
    for _ in range(200):
        comps = []
        for _h in range(k):
            while True:
                if rng.random() < peaked:
                    c = [rng.randint(0, 2) for _ in range(m)]
                    c[rng.randrange(m)] = rng.randint(5, 10)
                else:
                    c = [rng.randint(0, 7) for _ in range(m)]
                if lo <= sum(c) <= hi and sum(1 for x in c if x) >= 1:
                    break
            comps.append(c)
        keys = [tuple(norm(c)) if distinct_props else tuple(c) for c in comps]
        if len(set(keys)) == k:
            return comps
    return None


def _urn_draw(rng, variant):
    mode = {"urn_which_repl": "repl", "urn_next_repl": "repl", "urn_which_norepl": "norepl",
            "urn_next_norepl": "norepl", "urn_which_polya": "polya"}[variant]
    query = "next" if "next" in variant else "which"
    k = rng.randint(2, 5) if query == "which" else rng.randint(2, 4)
    m = rng.randint(2, 4)
    lo, hi = (3, 14) if mode == "repl" else (4, 10)
    comps = _urn_comp(rng, k, m, lo, hi, mode == "repl", 0.6 if query == "next" else 0.0)
    if comps is None:
        return None
    totals = [sum(c) for c in comps]
    if mode == "repl":
        n = rng.randint(1, 6) if query == "which" else rng.randint(1, 4)
    elif mode == "polya":
        n = rng.randint(2, 5)
    else:
        n = rng.randint(1, min(5 if query == "which" else 3, min(totals) - 1))
    ws, kind = draw_weights(rng, k, *((0.2, 0.35) if query == "which" else (0.1, 0.7, 150)))
    truth = pick_truth(rng, ws, 0.4 if query == 'which' else 0.7)
    draws, cur = [], list(comps[truth])
    for _ in range(n):
        tot = sum(cur)
        if tot == 0:
            return None
        c = rng.choices(range(m), weights=cur)[0]
        draws.append(c)
        if mode == "norepl":
            cur[c] -= 1
        elif mode == "polya":
            cur[c] += 1
    liks, used = [], [0] * m
    for j, c in enumerate(draws):
        if mode == "repl":
            liks.append([F(comps[h][c], totals[h]) for h in range(k)])
        elif mode == "norepl":
            liks.append([F(max(0, comps[h][c] - used[c]), totals[h] - j) for h in range(k)])
        else:
            liks.append([F(comps[h][c] + used[c], totals[h] + j) for h in range(k)])
        used[c] += 1
    pred, picks = None, {}
    if query == "next":
        if mode == "repl":
            pred = [[F(comps[h][c], totals[h]) for c in range(m)] for h in range(k)]
        else:
            pred = [[F(max(0, comps[h][c] - used[c]), totals[h] - n) for c in range(m)]
                    for h in range(k)]
        cnt = Counter(draws)
        top = max(cnt.values())
        picks = {"last_outcome": {draws[-1]}, "majority_outcome": {c for c in cnt if cnt[c] == top}}
    kind_c, names = rng.choice(URN_SETS)
    names = names[:k]
    colours = rng.sample(COLOURS, m)
    item = rng.choice(ITEMS)
    fmt = rng.choice(FORMATS)
    comp_style = "counts" if mode != "repl" or rng.random() < 0.7 else rng.choice(("pct", "frac"))
    rule_in_instr = rng.random() < 0.5
    seq_style = rng.choice(("list", "numbered", "sentence"))
    gen = {"n_hyp": k, "n_colours": m, "n_obs": n, "prior": kind, "mode": mode,
           "query": query, "fmt": fmt, "comp_style": comp_style, "seq_style": seq_style,
           "rule_in_instr": rule_in_instr, "container": kind_c}
    params = {"comps": comps, "prior": ws, "draws": draws, "mode": mode, "query": query}

    def render(r: random.Random):
        doc = Doc()
        rows, prose = [], []
        for nm, c, t in zip(names, comps, totals):
            if comp_style == "counts":
                rows.append([nm] + [str(x) for x in c])
                parts = [f"{x} {col}" for x, col in zip(c, colours) if x]
                prose.append(f"{nm[0].upper() + nm[1:]} holds {join_and(parts)} "
                             f"{item}{'s' if t != 1 else ''}.")
            else:
                vals = [fmt_p(F(x, t), comp_style) for x in c]
                rows.append([nm] + vals)
                parts = [f"{v} are {col}" for v, col, x in zip(vals, colours, c) if x]
                prose.append(f"Of the {item}s in {nm}, {join_and(parts)}.")
        title = f"contents ({'counts' if comp_style == 'counts' else 'share of ' + item + 's'})"
        doc.table(title, [kind_c] + list(colours), rows, " ".join(prose))
        prior_block(doc, r, names, ws, kind, f"the {kind_c} used")
        rule = {"repl": f"Each {item} is put back and the {kind_c} is shaken before the next draw.",
                "norepl": f"{item[0].upper() + item[1:]}s are not put back: each draw leaves one fewer in the {kind_c}.",
                "polya": f"After each draw the {item} is put back together with one extra {item} "
                         f"of the same colour from a spare supply, so the {kind_c} grows by one "
                         f"each time."}[mode]
        seq = [colours[c] for c in draws]
        if seq_style == "list":
            obs = ", ".join(seq)
        elif seq_style == "numbered":
            obs = "; ".join(f"draw {j + 1}: {s}" for j, s in enumerate(seq))
        else:
            obs = " ".join(f"The {['first', 'second', 'third', 'fourth', 'fifth', 'sixth'][j]} "
                           f"{item} was {s}." for j, s in enumerate(seq))
        story = (f"One {kind_c} was picked as described and {plural(n, item)} "
                 f"{'was' if n == 1 else 'were'} drawn from it one at a time.")
        if not rule_in_instr:
            story += " " + rule
        doc.facts("draws", [("procedure", story), ("observed", obs)],
                  f"{story} Observed: {obs.rstrip('.')}.")
        state = doc.render(fmt, r)
        instr = (rule + " " if rule_in_instr else "") + answer(r)
        if query == "which":
            q = r.choice((f"Which {kind_c} were the {item}s drawn from?",
                          f"From which {kind_c} did the draws come?",
                          f"Which {kind_c} was picked?"))
            opts, descs = list(names), None
        else:
            q = r.choice((f"What colour will the next {item} drawn from the same {kind_c} be?",
                          f"If one more {item} is drawn from that {kind_c}, what colour is it?",
                          f"Predict the colour of the next draw from the same {kind_c}."))
            if mode == "norepl":
                q += f" (The {item}s already drawn stay out.)"
            opts, descs = list(colours), None
        return state, q, instr, opts, descs

    return Draft(variant, norm(ws), liks, pred, params, gen, render, picks=picks,
                 hyp_heuristics=query == "which")


