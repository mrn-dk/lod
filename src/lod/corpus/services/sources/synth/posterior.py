def _explain_draw(rng, variant):
    ctx = rng.choice(EXPLAIN_CONTEXTS)
    p1, p2 = rate(rng, 0.05, 0.7), rate(rng, 0.05, 0.7)
    cpt = {}
    for c1 in (1, 0):
        for c2 in (1, 0):
            lo, hi = (0.5, 0.99) if (c1 or c2) else (0.01, 0.3)
            cpt[(c1, c2)] = rate(rng, lo, hi)
    hyps = [(1, 1), (1, 0), (0, 1), (0, 0)]
    prior = [(p1 if a else 1 - p1) * (p2 if b else 1 - p2) for a, b in hyps]
    t1, t2 = rng.random() < 0.5, rng.random() < 0.5
    e = int(rng.random() < cpt[(int(t1), int(t2))])
    if rng.random() < 0.25:
        e = 1 - e
    liks = [[cpt[h] if e else 1 - cpt[h] for h in hyps]]
    c2_known = rng.random() < 0.4
    if c2_known:
        c2v = int(t2)
        liks.append([F(1) if h[1] == c2v else F(0) for h in hyps])
    query = "c1" if c2_known or rng.random() < 0.4 else "joint"
    pred = None if query == "joint" else [[F(1), F(0)] if h[0] else [F(0), F(1)] for h in hyps]
    fmt = rng.choice(FORMATS)
    style = rng.choice(("pct", "frac", "dec", "in"))
    gen = {"n_hyp": 4, "n_obs": len(liks), "prior": "stated", "fmt": fmt, "query": query,
           "effect": e, "c2_known": c2_known, "p_style": style}
    params = {"p1": p1, "p2": p2, "cpt": cpt, "e": e, "c2": int(t2) if c2_known else None,
              "query": query}

    def render(r: random.Random):
        doc = Doc()
        doc.facts("base rates", [(ctx["c1"], fmt_p(p1, style)), (ctx["c2"], fmt_p(p2, style))],
                  f"On a given day, {ctx['c1']} happens with probability {fmt_p(p1, style)} and "
                  f"{ctx['c2']} with probability {fmt_p(p2, style)}, independently.")
        rows = []
        for (a, b) in hyps:
            rows.append(["yes" if a else "no", "yes" if b else "no", fmt_p(cpt[(a, b)], style)])
        prose = " ".join(
            f"With {ctx['c1'] if a else ctx['not1']} and "
            f"{ctx['c2'] if b else ctx['not2']}, the chance that "
            f"{ctx['e']} is {fmt_p(cpt[(a, b)], style)}." for a, b in hyps)
        doc.table(f"P({ctx['e']})", [ctx["c1"], ctx["c2"], "probability"], rows, prose)
        obs = [("effect", ctx["e"] if e else ctx["e_no"])]
        text = f"Today {ctx['e'] if e else ctx['e_no']}."
        if c2_known:
            obs.append((ctx["c2"], "yes" if params["c2"] else "no"))
            text += f" It is known that there was {ctx['c2'] if params['c2'] else ctx['not2']}."
        doc.facts("today", obs, text)
        state = doc.render(fmt, r)
        instr = "The two causes occur independently of each other. " + answer(r)
        if query == "joint":
            q = r.choice(("Which causes were present today?", "What happened today?"))
            opts = [f"both {ctx['short1']} and {ctx['short2']}", f"{ctx['short1']} only",
                    f"{ctx['short2']} only", "neither"]
            descs = [f"{ctx['c1']} and {ctx['c2']}", f"{ctx['c1']}, {ctx['not2']}",
                     f"{ctx['c2']}, {ctx['not1']}", "neither cause occurred"]
            return state, q, instr, opts, descs
        q = f"Was there {ctx['c1']} today?"
        return state, q, instr, ["yes", "no"], None

    return Draft(variant, prior, liks, pred, params, gen, render)


