def _rng(seed: int, salt: str) -> random.Random:
    return random.Random(f"post:{seed}:{salt}")


def emit(d: Draft, info: dict, rng: random.Random, i: int) -> Example:
    state, q, instr, opts, descs = d.render(rng)
    order = list(d.keep) if d.keep is not None else list(range(len(opts)))
    pos = list(range(len(order)))            # positions within the offered outcomes
    if d.shuffle:
        rng.shuffle(pos)
    options = [opts[order[p]] for p in pos]
    target = [info["target"][p] for p in pos]
    descriptions = [descs[order[p]] for p in pos] if descs else None
    fam, split = VARIANTS[d.variant]
    t = info["target"]
    gen = {"family": fam, "variant": d.variant, "n_options": len(options),
           "max_post": round(max(t), 4), "conf_bin": info["bin"], **d.gen}
    return Example(state=state, questions=[Question(
        id=f"{d.variant}_{i}", question=q, instructions=instr, options=options,
        descriptions=descriptions, target=target, meta={"gen": gen})])


def generate(variant: str, seed: int, n: int) -> Iterator[tuple[Draft, dict, Example]]:
    """Up to n balanced (draft, assessment, example) triples for one variant."""
    bal = Balance()
    made = i = stall = 0
    best = None                    # the least-violating draft seen during a stall
    while made < n and i < n * 400:
        i += 1
        rng = _rng(seed, f"{variant}:{i}")
        d = DRAW[variant](rng, variant)
        if d is None:
            continue
        info = assess(d)
        if info is None:
            continue
        v = bal.violation(info)
        if v > 0:
            if best is None or v < best[0]:
                best = (v, d, info, rng, i)
            stall += 1
            if stall < STALL:
                continue
            _, d, info, rng, i_used = best
        else:
            i_used = i
        stall, best = 0, None
        bal.add(info)
        made += 1
        yield d, info, emit(d, info, rng, i_used)


def _loader(variant: str, seed: int, cap: int):
    def load(n: int) -> Iterator[Example]:
        for _, _, ex in generate(variant, seed, min(n, cap)):
            yield ex
    return load


def tasks() -> list[RealTask]:
    """Trained variants to `train` with a fresh-seed `_eval` twin in `devreal` (family =
    the trained sibling); dev-held-out variants to `devreal`; test-held-out variants to
    `testreal`. Held-out variants are never trained on."""
    out: list[RealTask] = []
    for v, (fam, split) in VARIANTS.items():
        name = f"post_{v}"
        common = dict(row=ROW, licence=LICENCE, url=URL, real=False, soft=True,
                      per_example_options=True)
        if split == "train":
            out.append(RealTask(name=name, load=_loader(v, SEED_TRAIN, MAX_PER_TASK),
                                force_split="train", family=name, min_quota=MAX_PER_TASK,
                                notes=f"exact posterior, {fam} family, variant {v}; trained",
                                **common))
            out.append(RealTask(name=f"{name}_eval", load=_loader(v, SEED_TWIN, MAX_PER_TWIN),
                                force_split="devreal", family=name, min_quota=MAX_PER_TWIN,
                                notes=f"in-structure twin of {name} (fresh seed)", **common))
        else:
            seed = SEED_DEV if split == "devreal" else SEED_TEST
            out.append(RealTask(name=name, load=_loader(v, seed, MAX_PER_HELDOUT),
                                force_split=split, family=name, min_quota=MAX_PER_HELDOUT,
                                notes=f"exact posterior, {fam} family, variant {v}; "
                                      f"held out to {split}, NEVER trained on", **common))
    return out
