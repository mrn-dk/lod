def _rel_text(r: F, style: str, rng: random.Random) -> str:
    if style == "counts":
        n = rng.choice((10, 20, 40, 50, 100))
        if (r * n).denominator == 1:
            return f"right in {r * n} of {n} past checks"
        style = "pct"
    if style == "odds":
        return f"odds {r.numerator} to {r.denominator - r.numerator} of being right"
    return f"accurate with probability {fmt_p(r, style)}"


def _sources_draw(rng, variant):
    ctx = rng.choice(SOURCE_CONTEXTS)
    m = rng.choice((2, 3, 3, 4, 4, 5, 6, 7, 8))
    values = rng.sample(ctx["values"], m)
    if variant == "sources_relay":
        n = rng.randint(2, 3)
    else:
        n = {"sources_2": 2, "sources_3": 3, "sources_4": 4}[variant]
    floor = 1 / m + 0.05
    rels = [rate(rng, max(0.3, floor), 0.95) for _ in range(n)]
    relays: list[F | None] = [None] * n
    if variant == "sources_relay":
        for j in rng.sample(range(n), rng.randint(1, min(2, n))):
            relays[j] = rate(rng, max(0.5, floor), 0.95)
    ws, kind = draw_weights(rng, m, uniform_share=0.2)
    truth = pick_truth(rng, ws)
    reports = []

    def noisy(v, r):
        if rng.random() < r:
            return v
        return rng.choice([x for x in range(m) if x != v])

    for j in range(n):
        v = noisy(truth, rels[j])
        if relays[j] is not None:
            v = noisy(v, relays[j])
        reports.append(v)
    eff = []
    for j in range(n):
        r = rels[j]
        if relays[j] is not None:
            q = relays[j]
            r = r * q + (1 - r) * (1 - q) / (m - 1)
        eff.append(r)
    liks = [[eff[j] if x == reports[j] else (1 - eff[j]) / (m - 1) for x in range(m)]
            for j in range(n)]
    top = max(rels)
    cnt = Counter(reports)
    mc = max(cnt.values())
    picks = {"reliable": {reports[j] for j in range(n) if rels[j] == top},
             "majority_report": {v for v in cnt if cnt[v] == mc}}
    srcs = rng.sample(ctx["srcs"], n)
    fmt = rng.choice(FORMATS)
    style = rng.choice(("pct", "pct", "dec", "frac", "counts", "odds"))
    gen = {"n_hyp": m, "n_obs": n, "n_sources": n, "prior": kind, "fmt": fmt,
           "rel_style": style, "n_relayed": sum(1 for x in relays if x is not None),
           "n_distinct_reports": len(cnt)}
    params = {"m": m, "rels": rels, "relays": relays, "reports": reports, "prior": ws}

    relayed = variant == "sources_relay"

    def render(r: random.Random):
        doc = Doc()
        doc.facts("candidates", [("values", ", ".join(values))],
                  f"The candidates for {ctx['attr']} are {join_and(values)}.")
        prior_block(doc, r, values, ws, kind, ctx["attr"], frame="records")
        rows, prose = [], []
        for j in range(n):
            rt = _rel_text(rels[j], style, r)
            if relays[j] is None:
                rows.append([srcs[j], rt] + (["direct"] if relayed else []) + [values[reports[j]]])
                prose.append(f"{srcs[j][0].upper() + srcs[j][1:]} ({rt}) gives {values[reports[j]]}.")
            else:
                via = r.choice(RELAYS)
                qt = _rel_text(relays[j], style, r).replace("accurate", "passes it on correctly")
                rows.append([srcs[j], rt, f"via {via} ({qt})", values[reports[j]]])
                prose.append(f"{srcs[j][0].upper() + srcs[j][1:]} ({rt}) is known only through "
                             f"{via}, who {qt.replace('right in', 'relays correctly in')}; the "
                             f"value that reached us is {values[reports[j]]}.")
        doc.table("reports", ["source", "reliability"] + (["channel"] if relayed else [])
                  + ["reported value"], rows,
                  " ".join(prose))
        state = doc.render(fmt, r)
        err = (f"A source that is not accurate names one of the other {m - 1} candidates, "
               f"each equally likely; sources err independently.")
        if variant == "sources_relay":
            err += (" A relay that garbles a value passes on one of the other candidates, each "
                    "equally likely.")
        instr = err + " " + answer(r)
        q = r.choice((f"What is {ctx['attr']}?", f"Which value is true for {ctx['attr']}?",
                      f"Given the reports, what was {ctx['attr']}?"))
        return state, q, instr, list(values), None

    return Draft(variant, norm(ws), liks, None, params, gen, render, picks=picks,
                 hyp_heuristics=True)


